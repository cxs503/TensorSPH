def flume_water_lattice(cfg: WaveFlumeConfig, device) -> torch.Tensor:
    """Particle positions of the resting water column, on the cell-centre lattice.

    The vertical lattice is exactly ``depth/dx`` rows (``validate_flume`` rejects a
    depth that is not an integer number of spacings), so the still-water level is
    the requested one to machine precision and the rest state really is at rest.
    ``cell_centres`` would instead drop the partial last row, leaving the column up
    to one spacing short of ``depth``.
    """
    xs = cell_centres(cfg.flume_length, cfg.dx, device)
    rows = int(round(cfg.depth / cfg.dx))
    ys = (torch.arange(rows, device=device,
                       dtype=torch.get_default_dtype()) + 0.5) * cfg.dx
    gx, gy = torch.meshgrid(xs, ys, indexing="xy")
    return torch.stack((gx.reshape(-1), gy.reshape(-1)), dim=-1)


def flume_particle_mass(cfg: WaveFlumeConfig, positions: torch.Tensor,
                        device) -> torch.Tensor:
    """Particle masses: hydrostatic Tait profile times the calibrated lattice mass.

    Both factors matter.  The calibrated lattice mass (:func:`lattice_mass_unit`)
    makes the interior summation density exactly ``rho0``; the hydrostatic factor
    ``rho(y)`` makes the initial state a discrete equilibrium instead of a column
    that first has to collapse.  See
    ``docs/verification_lattice_mass_calibration.md``.
    """
    unit = lattice_mass_unit(cfg)
    if cfg.hydrostatic_init:
        return hydrostatic_density(positions[:, 1], cfg,
                                   surface=cfg.depth) * (unit / cfg.rho0)
    return torch.full((positions.shape[0],), unit, device=device)


def static_wall_lattice(cfg: WaveFlumeConfig, device) -> torch.Tensor:
    """Fixed wall particles: the floor and the downstream (reflecting) wall.

    Three layers at the fluid spacing, half a spacing outside the water, as in
    :func:`tensorsph.droplet_impact.wall_lattice`.  The upstream end has no fixed
    wall: the paddle is there.
    """
    if cfg.wall_layers < 1:
        raise ValueError("wall_layers must be positive")
    dx, layers = cfg.dx, cfg.wall_layers
    top = cfg.free_surface_top()
    span_x = torch.arange(-(layers - 0.5) * dx,
                          cfg.flume_length + (layers - 0.5) * dx, dx,
                          device=device)
    columns = torch.arange(dx * 0.5, top, dx, device=device)
    parts = []
    for layer in range(1, layers + 1):
        y = torch.full_like(span_x[:1], dx * 0.5 - layer * dx)
        gx, gy = torch.meshgrid(span_x, y, indexing="xy")
        parts.append(torch.stack((gx.reshape(-1), gy.reshape(-1)), dim=-1))
    for layer in range(1, layers + 1):
        x = torch.full_like(columns[:1], cfg.flume_length - dx * 0.5 + layer * dx)
        gx, gy = torch.meshgrid(x, columns, indexing="xy")
        parts.append(torch.stack((gx.reshape(-1), gy.reshape(-1)), dim=-1))
    return torch.cat(parts, dim=0)


def paddle_lattice(cfg: WaveFlumeConfig, device) -> torch.Tensor:
    """Wall particles of the piston paddle, at its rest position (offset 0).

    The paddle is a rigid vertical block ``wall_layers`` columns thick whose face
    is the plane ``x = 0``, extending from the floor to the top of the
    computational box so the wave cannot spill over it.  It is translated rigidly
    every step and its velocity and acceleration are passed to
    :func:`tensorsph.droplet_impact.rhs`, so it acts as a moving, pressure-coupled
    boundary rather than a gate.
    """
    dx, layers = cfg.dx, cfg.wall_layers
    top = cfg.free_surface_top()
    rows = torch.arange(dx * 0.5, top, dx, device=device)
    offsets = torch.arange(layers, device=device, dtype=rows.dtype)
    xs = -dx * 0.5 - offsets * dx
    gx, gy = torch.meshgrid(xs, rows, indexing="xy")
    return torch.stack((gx.reshape(-1), gy.reshape(-1)), dim=-1)


