"""2-D numerical wave flume on the WCSPH core: piston wavemaker, sponge
absorption, wave gauges, and the analytic anchors used to grade it.

Physics modelled here
---------------------
A rectangular flume of still-water depth ``h`` and length ``L`` holds water at
rest in hydrostatic equilibrium.  A piston (vertically uniform paddle) at the
upstream end is driven by first-order wavemaker theory so that a wave of a
prescribed height ``H`` and period ``T`` (regular) or a prescribed height ``H``
(solitary) is generated.  The wave propagates along the flume and is absorbed by
a passive sponge layer in front of the downstream wall.  Gauges record the
free-surface elevation time series at fixed ``x``.

The solver is :func:`tensorsph.droplet_impact.rhs` unchanged except for the
optional moving-wall inputs (``wall_vel`` / ``wall_accel``): density summation,
Tait equation of state, symmetric pressure gradient, Morris-type viscosity, and
kinematic wall particles with the Adami, Hu & Adams (2012, eq. 11) pressure
extrapolation.  What this module adds is the *case*: a paddle that translates
rigidly with a prescribed motion, a damping layer, gauges, and the analytical
solutions the run is graded against.

Analytical anchors
------------------
* Linear (Airy) waves with ``omega^2 = g k tanh(k h)`` (Dean & Dalrymple 1991,
  *Water Wave Mechanics for Engineers and Scientists*, eq. 3.23); the wavelength
  of a given period is obtained by a monotone bisection of the dispersion
  relation.
* Piston wavemaker transfer function ``H/S = 2 (cosh 2kh - 1) /
  (sinh 2kh + 2kh)`` (Dean & Dalrymple, eq. 6.38), used to turn the requested
  wave height into a paddle stroke ``S``.
* First-order solitary wave ``eta = H sech^2(alpha (x - c t))`` with
  ``alpha = sqrt(3H/(4h^3))`` and ``c = sqrt(g (h + H))``, generated by Goring's
  (1979) condition ``U = c eta / (h + eta)`` for the paddle velocity.

Free-surface extraction, and what it costs
------------------------------------------
The elevation at a gauge is the highest particle centre in a horizontal bin plus
``surface_offset`` (default half a particle spacing).  That estimator is unbiased
on a flat lattice and carries an O(dx) bias on a curved surface, so
cross-resolution comparisons are only meaningful when the same estimator is used
on every level -- which is why the offset is one documented configuration value
rather than a per-case tweak.  The wave field is 2-D (unit width), the fluid is
single-phase and laminar, and the model is weakly compressible: the
O(gh/c0^2) compressibility bias of the gravity-wave celerity is *not* removed and
is part of every reported error.

Nothing here is claimed on the strength of the implementation existing: see
``docs/verification_wave_flume.md`` and ``benchmarks/wave_flume/`` for the
measured numbers, including what did not meet its target.
"""
