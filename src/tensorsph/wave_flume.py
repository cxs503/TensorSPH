def apply_flume_boundary(pos: torch.Tensor, vel: torch.Tensor,
                         cfg: WaveFlumeConfig, top: float | None = None) -> int:
    """Clamp fluid inside the box and zero the normal velocity on contact.

    A safety net, as in :func:`tensorsph.droplet_impact.apply_boundary`: with the
    kinematic walls working the returned count stays zero.  The upstream limit is
    ``-2 dx`` (behind the paddle face) because a particle there would be a
    wall-model failure, not a boundary.
    """
    height = cfg.free_surface_top() if top is None else float(top)
    tolerance = 0.25 * cfg.dx
    x_min, x_max = -2.0 * cfg.dx, cfg.flume_length
    y_min, y_max = 0.0, height
    low_x = pos[:, 0] < x_min - tolerance
    high_x = pos[:, 0] > x_max + tolerance
    low_y = pos[:, 1] < y_min - tolerance
    high_y = pos[:, 1] > y_max + tolerance
    pos[:, 0] = pos[:, 0].clamp(x_min, x_max)
    pos[:, 1] = pos[:, 1].clamp(y_min, y_max)
    vel[:, 0] = torch.where(low_x | high_x, torch.zeros_like(vel[:, 0]), vel[:, 0])
    vel[:, 1] = torch.where(low_y | high_y, torch.zeros_like(vel[:, 1]), vel[:, 1])
    return int((low_x | high_x | low_y | high_y).sum().item())


def xsph_correction(positions: torch.Tensor, velocity: torch.Tensor,
                    mass: torch.Tensor, density: torch.Tensor,
                    pairs: torch.Tensor, h: float, epsilon: float) -> torch.Tensor:
    """One XSPH smoothing pass over the fluid-fluid pairs.

    ``v_i <- v_i + eps * sum_j (m_j/rho_bar)(v_j - v_i) W_ij
    / sum_j (m_j/rho_bar) W_ij`` with ``rho_bar`` the pair mean density. The
    operator is a weighted average, so a uniform velocity is a fixed point; it
    removes velocity differences on the scale of the kernel (particle disorder)
    and leaves a field that is smooth on that scale -- a wave -- alone. Pair
    contributions are added to both ends with opposite signs so the smoothing
    conserves total momentum exactly (the weights are symmetric).
    """
    if epsilon <= 0.0 or pairs.numel() == 0:
        return velocity
    n = positions.shape[0]
    i, j = pairs.unbind(dim=1)
    fluid = (i < n) & (j < n)
    i, j = i[fluid], j[fluid]
    if i.numel() == 0:
        return velocity
    delta = positions[i] - positions[j]
    weight = cubic_spline_kernel(torch.linalg.vector_norm(delta, dim=1), h)
    rho_bar = 0.5 * (density[i] + density[j])
    scale = weight / rho_bar.clamp_min(1.0e-12)
    pull = (velocity[j] - velocity[i]) * (mass[j] * scale)[:, None]
    push = (velocity[i] - velocity[j]) * (mass[i] * scale)[:, None]
    numerator = torch.zeros_like(velocity)
    numerator = numerator.index_add(0, i, pull)
    numerator = numerator.index_add(0, j, push)
    denominator = torch.zeros(n, dtype=positions.dtype, device=positions.device)
    denominator = denominator.index_add(0, i, mass[j] * scale)
    denominator = denominator.index_add(0, j, mass[i] * scale)
    return velocity + epsilon * numerator / denominator.clamp_min(1.0e-30)[:, None]


@dataclass
class WaveFlumeRun:
    """Everything a grading script needs from one flume run.

    ``probe_eta[i][k]`` is the elevation at ``probe_x[i]`` and ``times[k]``
    (``nan`` where the bin was empty).  ``profiles`` holds ``(time, x, eta)`` at
    the requested snapshot times and ``snapshots`` the raw particle state there.
    """

    times: list
    probe_x: tuple
    probe_eta: list
    paddle_offset: list
    spec: WaveSpec
    config: dict
    dt: float
    steps_taken: int
    simulated_time: float
    mass: float
    escaped: int
    max_speed: float
    max_density_compression: float
    min_density_ratio: float
    rebuilds: int
    profiles: list
    snapshots: list
    final_positions: torch.Tensor
    speed_history: list = field(default_factory=list)
    compression_history: list = field(default_factory=list)
    mass_final: float | None = None

    @property
    def mass_drift(self) -> float:
        """Relative change of the total particle mass over the run.

        The mass of a SPH particle is a constant of the motion: the solver never
        creates, destroys or redistributes it, so the total is conserved to the
        last bit and the drift is exactly zero. The property exists so that the
        invariant is *asserted* in the tests instead of assumed -- a non-zero
        value would mean some code path had touched the mass array.
        """
        if self.mass_final is None:
            return 0.0
        if self.mass == 0.0:
            return float("inf")
        return (self.mass_final - self.mass) / self.mass


def run_case(cfg: WaveFlumeConfig, snapshot_times=None,
             probe_positions=None) -> WaveFlumeRun:
    """Integrate the flume and return the gauge records and snapshots.

    ``snapshot_times`` (seconds, increasing) captures the particle state and the
    free-surface profile at those instants; ``probe_positions`` overrides
    :func:`default_probe_positions`.
    """
    validate_flume(cfg)
    device = resolve_device(cfg.device)
    spec = flume_wave_spec(cfg)
    probes = (tuple(probe_positions) if probe_positions is not None
              else (tuple(cfg.probes) if cfg.probes
                    else default_probe_positions(cfg, spec)))
    probes = tuple(float(p) for p in probes)
    if any(p <= 0.0 or p >= cfg.sponge_start() for p in probes):
        raise ValueError("probes must sit in the propagation zone (0, sponge_start)")

    h = cfg.h_factor * cfg.dx
    surface_offset = cfg.surface_offset()
    positions = flume_water_lattice(cfg, device)
    mass = flume_particle_mass(cfg, positions, device)
    velocity = torch.zeros_like(positions)
    fluid_count = positions.shape[0]

    fixed_wall = static_wall_lattice(cfg, device)
    paddle_rest = paddle_lattice(cfg, device)
    fixed_count = fixed_wall.shape[0]
    wall = torch.cat((fixed_wall, paddle_rest), dim=0)
    wall_vel = torch.zeros_like(wall)
    wall_accel = torch.zeros_like(wall)

    skin = cfg.pair_skin_factor
    cache = (PairListCache(2.0 * h, skin * h, fluid_count=fluid_count)
             if skin > 0 else None)
    all_positions = torch.cat((positions, wall), dim=0)

    target_time = cfg.steps * cfg.dt
    snap_targets = sorted(float(t) for t in (snapshot_times or []))
    snap_next = 0
    profiles: list = []
    snapshots: list = []

    times: list = []
    probe_eta: list = [[] for _ in probes]
    paddle_offset: list = []
    speed_history: list = []
    compression_history: list = []
    escaped = 0
    max_speed = 0.0
    compression_peak = torch.zeros((), dtype=torch.float64, device=device)
    density_min = torch.full((), float("inf"), dtype=torch.float64, device=device)

    dt = min(cfg.dt, cfg.max_courant * h / cfg.sound_speed)
    elapsed = 0.0
    absorption_state = 0.0
    physical_viscosity = cfg.viscosity
    step = 0
    for step in range(cfg.steps + 1):
        # --- paddle kinematics, plus the optional absorption feedback ---------
        wave_time = max(0.0, elapsed - cfg.settle_time)
        settling = elapsed < cfg.settle_time
        cfg.viscosity = (cfg.viscosity_settle if settling and cfg.viscosity_settle > 0.0
                         else physical_viscosity)
        xsph_now = cfg.xsph_settle if settling else cfg.xsph
        offset, speed, accel = paddle_motion(spec, cfg, wave_time)
        if cfg.active_absorption > 0.0:
            eta_paddle = probe_elevation(
                positions, 2.0 * cfg.dx, cfg.depth, cfg.dx,
                half_width=cfg.probe_bin_halfwidth * cfg.dx,
                surface_offset=surface_offset)
            if math.isnan(eta_paddle):
                eta_paddle = 0.0
            eta_target = spec.elevation(2.0 * cfg.dx, wave_time)
            correction = (-cfg.active_absorption
                          * math.sqrt(cfg.gravity / cfg.depth)
                          * (eta_paddle - eta_target))
            absorption_state += dt * correction
        total_offset = offset + absorption_state
        wall[fixed_count:, 0] = paddle_rest[:, 0] + total_offset
        wall_vel[fixed_count:, 0] = speed
        wall_accel[fixed_count:, 0] = accel

        if cache is None:
            pairs = None
        else:
            all_positions[:fluid_count] = positions
            all_positions[fluid_count:] = wall
            pairs, _ = cache.get(all_positions)

        density, _, acc = rhs(positions, velocity, mass, cfg, pairs=pairs,
                              wall=wall, dt=dt, wall_vel=wall_vel,
                              wall_accel=wall_accel)
        if not torch.isfinite(acc).all():
            raise FloatingPointError(f"non-finite acceleration at step {step}")
        compression_scalar = float(density.max().double() / cfg.rho0 - 1.0)
        compression_peak = torch.maximum(
            compression_peak, density.max().double() / cfg.rho0 - 1.0)
        density_min = torch.minimum(density_min, density.min().double() / cfg.rho0)
        speed_now = (torch.linalg.vector_norm(velocity, dim=-1)
                     if velocity.numel() else torch.zeros(0, device=device))
        speed_scalar = float(speed_now.max()) if speed_now.numel() else 0.0
        max_speed = max(max_speed, speed_scalar)

        final = step == cfg.steps or elapsed >= target_time - 1.0e-12
        if step % cfg.output_every == 0 or final:
            times.append(elapsed)
            paddle_offset.append(total_offset)
            speed_history.append(speed_scalar)
            compression_history.append(compression_scalar)
            for index, x_probe in enumerate(probes):
                probe_eta[index].append(probe_elevation(
                    positions, x_probe, cfg.depth, cfg.dx,
                    half_width=cfg.probe_bin_halfwidth * cfg.dx,
                    surface_offset=surface_offset))
            while (snap_next < len(snap_targets)
                   and elapsed >= snap_targets[snap_next] - 1.0e-12):
                snapshots.append((elapsed, positions.detach().clone(),
                                  velocity.detach().clone()))
                x_prof, eta_prof = surface_profile(
                    positions, cfg.depth, cfg.dx, surface_offset=surface_offset)
                profiles.append((elapsed, x_prof.detach().clone(),
                                 eta_prof.detach().clone()))
                snap_next += 1
        if final:
            break

        velocity = velocity + dt * acc
        if xsph_now > 0.0 and pairs is not None:
            velocity = xsph_correction(positions, velocity, mass, density,
                                       pairs, h, xsph_now)
        alpha = sponge_rate(positions[:, 0], cfg, spec)
        if float(alpha.max()) > 0.0:
            velocity = velocity * (1.0 - alpha * dt).clamp_min(0.0)[:, None]
        positions = positions + dt * velocity
        escaped += apply_flume_boundary(positions, velocity, cfg)
        elapsed += dt
        # Acoustic Courant control with the current maximum speed.
        dt = min(cfg.dt, cfg.max_courant * h / (cfg.sound_speed + speed_scalar))

    cfg.viscosity = physical_viscosity
    config_summary = {
        "dx": cfg.dx,
        "h_factor": cfg.h_factor,
        "dt_requested": cfg.dt,
        "dt_final": dt,
        "sound_speed": cfg.sound_speed,
        "viscosity": cfg.viscosity,
        "density_diffusion": cfg.density_diffusion,
        "gravity": cfg.gravity,
        "flume_length": cfg.flume_length,
        "depth": cfg.depth,
        "wave_type": cfg.wave_type,
        "wave_height": cfg.wave_height,
        "wave_period": cfg.wave_period,
        "ramp_periods": cfg.ramp_periods,
        "sponge_length": cfg.sponge_length,
        "sponge_strength": cfg.sponge_strength,
        "sponge_exponent": cfg.sponge_exponent,
        "active_absorption": cfg.active_absorption,
        "settle_time": cfg.settle_time,
        "xsph": cfg.xsph,
        "xsph_settle": cfg.xsph_settle,
        "viscosity_settle": cfg.viscosity_settle,
        "surface_offset_cells": cfg.surface_offset_cells,
        "steps": cfg.steps,
        "output_every": cfg.output_every,
        "wall_layers": cfg.wall_layers,
        "particle_count": int(fluid_count),
        "wall_count": int(wall.shape[0]),
        "wavelength": spec.wavelength,
        "celerity": spec.celerity,
        "stroke": spec.stroke,
        "probes": list(probes),
        "depth_cells": cfg.depth / cfg.dx,
        "height_cells": cfg.wave_height / cfg.dx,
    }
    return WaveFlumeRun(
        times=times, probe_x=probes, probe_eta=probe_eta,
        paddle_offset=paddle_offset, spec=spec, config=config_summary,
        dt=dt, steps_taken=step, simulated_time=elapsed,
        mass=float(mass.sum()), escaped=escaped, max_speed=max_speed,
        max_density_compression=float(compression_peak),
        min_density_ratio=float(density_min),
        rebuilds=0 if cache is None else cache.rebuilds,
        profiles=profiles, snapshots=snapshots,
        final_positions=positions.detach().clone(),
        speed_history=speed_history, compression_history=compression_history,
        mass_final=float(mass.sum()),
    )


