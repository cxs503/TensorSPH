def _as_series(time, eta):
    t = torch.as_tensor(time, dtype=torch.float64).reshape(-1)
    e = torch.as_tensor(eta, dtype=torch.float64).reshape(-1)
    if t.numel() != e.numel():
        raise ValueError("time and eta must have the same length")
    if t.numel() < 8:
        raise ValueError("need at least 8 samples")
    if not torch.isfinite(e).all():
        raise ValueError("the elevation series contains nan/inf")
    return t, e


def _window(time, eta, start=None, end=None):
    t, e = _as_series(time, eta)
    mask = torch.ones_like(t, dtype=torch.bool)
    if start is not None:
        mask &= t >= float(start)
    if end is not None:
        mask &= t <= float(end)
    if int(mask.sum()) < 8:
        raise ValueError("the requested window has fewer than 8 samples")
    return t[mask], e[mask]


def _spectrum(time, eta):
    t, e = _as_series(time, eta)
    step = float(t[1] - t[0])
    sample_count = e.numel()
    window = torch.hann_window(sample_count, dtype=torch.float64, periodic=False)
    spectrum = torch.fft.rfft((e - e.mean()) * window)
    freqs = torch.fft.rfftfreq(sample_count, step)
    return freqs, spectrum


def dominant_omega(time, eta, start=None, end=None) -> float:
    """Angular frequency of the dominant spectral peak, parabola-refined.

    The FFT bin spacing is ``1/(N dt)``; refining the peak with a parabola through
    the three log-magnitudes around it brings the estimate well below one bin,
    which matters because the dispersion check compares to 1 %.
    """
    t, e = _window(time, eta, start, end)
    freqs, spectrum = _spectrum(t, e)
    magnitude = spectrum.abs().clone()
    if magnitude.numel() < 4:
        raise ValueError("series too short for a spectral peak")
    magnitude[0] = 0.0
    peak = int(torch.argmax(magnitude))
    shift = 0.0
    if 0 < peak < magnitude.numel() - 1:
        logs = torch.log(magnitude.clamp_min(1.0e-300))
        left, centre, right = logs[peak - 1], logs[peak], logs[peak + 1]
        denominator = left - 2.0 * centre + right
        if float(denominator) != 0.0:
            shift = float(0.5 * (left - right) / denominator)
    bin_width = float(freqs[1] - freqs[0])
    return 2.0 * math.pi * (float(freqs[peak]) + shift * bin_width)


def zero_crossing_period(time, eta, start=None, end=None):
    """Mean period from upward mean crossings, linearly interpolated.

    Returns ``(period, crossing_count)``.  Independent of the spectral estimate,
    so the two together separate a shifted-mean artefact from a real period
    error.
    """
    t, e = _window(time, eta, start, end)
    centred = e - e.mean()
    sign = centred >= 0.0
    crossings = torch.nonzero((~sign[:-1]) & sign[1:]).reshape(-1)
    if crossings.numel() < 2:
        raise ValueError("fewer than two upward mean crossings in the window")
    crossing_times = []
    for position in range(crossings.numel() - 1):
        k = int(crossings[position])
        t0, t1 = float(t[k]), float(t[k + 1])
        e0, e1 = float(centred[k]), float(centred[k + 1])
        crossing_times.append(t0 - e0 * (t1 - t0) / (e1 - e0))
    intervals = torch.tensor(
        [crossing_times[i + 1] - crossing_times[i]
         for i in range(len(crossing_times) - 1)], dtype=torch.float64)
    if intervals.numel() == 0:
        raise ValueError("fewer than three upward mean crossings in the window")
    return float(intervals.mean()), int(crossings.numel())


def wavenumber_from_two_probes(time, eta1, eta2, separation,
                               start=None, end=None) -> float:
    """Wave number from the cross-spectrum phase of two gauges.

    For a single right-going component ``eta ~ cos(k x - omega t)`` the phase of
    ``conj(F1) F2`` at the spectral peak is ``-k (x2 - x1)`` with
    ``torch.fft``'s ``exp(+i omega t)`` convention, so the returned wave number is
    positive for a wave travelling in ``+x``.  The gauge spacing is below
    ``lambda/2`` so the phase does not wrap.
    """
    separation = _positive("separation", separation)
    t1, e1 = _window(time, eta1, start, end)
    t2, e2 = _window(time, eta2, start, end)
    if t1.numel() != t2.numel():
        raise ValueError("both gauges must share the same samples")
    _, spectrum1 = _spectrum(t1, e1)
    _, spectrum2 = _spectrum(t2, e2)
    magnitude = spectrum1.abs().clone()
    magnitude[0] = 0.0
    peak = int(torch.argmax(magnitude))
    cross = torch.conj(spectrum1[peak]) * spectrum2[peak]
    return -float(torch.angle(cross)) / separation


def separate_incident_reflected(time, elevations, positions, omega, k,
                                start=None, end=None) -> dict:
    """Least-squares split of a gauge array into incident and reflected waves.

    For a single frequency the field is modelled as

        eta(x,t) = a1 cos(kx - wt) + b1 sin(kx - wt)      (incident, +x)
                 + a2 cos(kx + wt) + b2 sin(kx + wt)      (reflected, -x)

    Four unknowns, three or more gauges: the over-determined system is solved in
    the least-squares sense over every gauge and every sample of the window (the
    over-determined form of the Goda & Suzuki 1976 three-gauge method).  The
    amplitudes are ``hypot(a, b)``; their ratio is the reflection coefficient, and
    it is only the reflection coefficient of the *reflecting end* when the window
    excludes the second round trip (the run script chooses it that way).
    """
    omega = _positive("omega", omega)
    k = _positive("k", k)
    xs = torch.as_tensor(positions, dtype=torch.float64).reshape(-1)
    if len(elevations) != int(xs.numel()):
        raise ValueError("one elevation series per gauge position is required")
    if xs.numel() < 3:
        raise ValueError("at least three gauges are needed to separate the two waves")
    t, first = _window(time, elevations[0], start, end)
    target = first.numel()
    rows = []
    values = []
    for x, series in zip(xs.tolist(), elevations):
        _, e = _window(time, series, start, end)
        if e.numel() != target:
            raise ValueError("all gauges must share the same samples")
        incident = k * x - omega * t
        reflected = k * x + omega * t
        rows.append(torch.stack((torch.cos(incident), torch.sin(incident),
                                 torch.cos(reflected), torch.sin(reflected)), dim=1))
        values.append(e)
    matrix = torch.cat(rows, dim=0)
    rhs_vector = torch.cat(values, dim=0)
    solution = torch.linalg.lstsq(matrix, rhs_vector).solution
    a1, b1, a2, b2 = (float(v) for v in solution)
    incident_amplitude = math.hypot(a1, b1)
    reflected_amplitude = math.hypot(a2, b2)
    residual = matrix @ solution - rhs_vector
    total = float(torch.linalg.vector_norm(rhs_vector))
    return {
        "incident_amplitude": incident_amplitude,
        "reflected_amplitude": reflected_amplitude,
        "ratio": (reflected_amplitude / incident_amplitude
                  if incident_amplitude > 0.0 else float("inf")),
        "coefficients": [a1, b1, a2, b2],
        "samples": int(target),
        "gauges": int(xs.numel()),
        "relative_residual": (float(torch.linalg.vector_norm(residual)) / total
                              if total > 0.0 else float("inf")),
    }


def reflection_coefficient(time, elevations, positions, omega, k,
                           start=None, end=None) -> float:
    """``|a_reflected| / |a_incident|`` from :func:`separate_incident_reflected`."""
    return separate_incident_reflected(time, elevations, positions, omega, k,
                                       start, end)["ratio"]
