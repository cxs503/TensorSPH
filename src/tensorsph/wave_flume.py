def probe_elevation(positions: torch.Tensor, x_probe: float, depth: float,
                    dx: float, half_width: float | None = None,
                    surface_offset: float = 0.0) -> float:
    """Surface elevation ``eta`` at ``x_probe`` from the topmost particle in a bin.

    Returns ``nan`` when the bin is empty (a probe outside the water, or a trough
    that dropped below the bin); the run keeps the ``nan`` rather than inventing a
    value, and the analysis reports how many samples were lost.
    """
    half = 1.0 * dx if half_width is None else float(half_width)
    mask = (positions[:, 0] >= x_probe - half) & (positions[:, 0] <= x_probe + half)
    if not bool(mask.any()):
        return float("nan")
    return float(positions[mask, 1].max()) + surface_offset - depth


def surface_profile(positions: torch.Tensor, depth: float, dx: float,
                    x_min: float | None = None, x_max: float | None = None,
                    bin_width: float | None = None,
                    surface_offset: float = 0.0):
    """Free-surface profile ``(x, eta)`` by binning particles along ``x``.

    Each bin reports its topmost particle centre plus ``surface_offset``; empty
    bins are dropped.  ``bin_width`` defaults to one particle spacing, the
    smallest width that keeps the estimator from averaging a crest with its
    trough.
    """
    if positions.numel() == 0:
        raise ValueError("surface_profile needs at least one particle")
    width = float(dx if bin_width is None else bin_width)
    lo = float(positions[:, 0].min()) if x_min is None else float(x_min)
    hi = float(positions[:, 0].max()) if x_max is None else float(x_max)
    if hi <= lo:
        raise ValueError("x_max must exceed x_min")
    count = max(1, int(math.ceil((hi - lo) / width)))
    index = ((positions[:, 0] - lo) / width).floor().long().clamp_(0, count - 1)
    top = torch.full((count,), -float("inf"), dtype=positions.dtype,
                     device=positions.device)
    top = top.scatter_reduce(0, index, positions[:, 1], reduce="amax",
                             include_self=True)
    keep = torch.isfinite(top)
    centres = lo + (torch.arange(count, dtype=positions.dtype,
                                 device=positions.device) + 0.5) * width
    return centres[keep], top[keep] + surface_offset - depth


def default_probe_positions(cfg: WaveFlumeConfig, spec: WaveSpec) -> tuple:
    """Four gauges in the propagation zone, upstream of the sponge.

    Spacing is ``lambda/8`` for regular waves: small enough that the two-probe
    phase difference stays below ``pi`` (no wrapping in the spectral estimate)
    and large enough to resolve it, and four gauges make the incident/reflected
    least-squares fit over-determined.
    """
    x_lo = 0.45 * cfg.sponge_start()
    if spec.kind == "regular":
        spacing = spec.wavelength / 8.0
    else:
        spacing = 0.5 * spec.length_scale
    return tuple(x_lo + i * spacing for i in range(4))


