@dataclass
class WaveFlumeConfig(Config):
    """Wave-flume case parameters.

    Geometry: the flume occupies ``x in [0, flume_length]`` and
    ``y in [0, depth]`` at rest; the paddle face is the plane ``x = 0`` and
    translates rigidly in ``x``.  The water columns are the cell centres of that
    rectangle (see :func:`tensorsph.droplet_impact.cell_centres`), so the last
    column always sits inside the domain.

    ``wave_type="regular"`` uses ``wave_period`` / ``wave_height`` with linear
    theory (Airy dispersion and the piston transfer function);
    ``wave_type="solitary"`` uses ``wave_height`` only, with the first-order
    sech^2 solution and Goring's paddle motion.

    ``sponge_strength`` is the damping coefficient at the far end of the sponge in
    units of ``c / L_sponge`` (the inverse of the time a wave needs to cross the
    sponge) and ``sponge_exponent`` shapes the ramp.  Damping acts on the fluid
    *velocity* only, ``v <- v (1 - alpha dt)``: a passive sponge like this
    dissipates the wave, it does not remove mass.

    ``active_absorption`` is the gain of a proportional paddle-velocity feedback
    that tries to cancel whatever comes back to the paddle,
    ``v_corr = -gain sqrt(g/h) (eta_meas - eta_target)``, i.e. the shallow-water
    impedance relation ``u = eta sqrt(g/h)``.  Zero is the passive paddle.
    """

    flume_length: float = 3.2
    depth: float = 0.25
    wave_type: str = "regular"
    wave_height: float = 0.03
    wave_period: float = 1.0
    # Raised-cosine ramp of the paddle amplitude. Without it the paddle starts
    # with a velocity step and radiates a high-frequency transient.
    ramp_periods: float = 2.0
    sponge_length: float = 0.9
    sponge_strength: float = 4.0
    sponge_exponent: float = 3.0
    active_absorption: float = 0.0
    # Time the paddle is held at rest before the wavemaker starts. The resting
    # lattice is not an exact discrete equilibrium (the free-surface shell is
    # under-supported), so the first fraction of a second carries a start-up
    # transient; waiting it out gives the wave a quiet medium to propagate into.
    settle_time: float = 0.0
    # XSPH velocity smoothing (Monaghan 1989, J. Comput. Phys. 82:1; the "delta"
    # of DualSPHysics): v_i <- v_i + xsph * sum_j (m_j/rbar)(v_j - v_i) W_ij /
    # sum_j (m_j/rbar) W_ij. It damps particle-scale velocity noise -- which is
    # exactly what the under-supported free-surface shell generates in a still
    # flume -- while a coherent wave is a smooth field and is left almost
    # untouched. Zero disables it.
    xsph: float = 0.0
    # Start-up damping. The resting lattice is not an exact discrete equilibrium,
    # so the first instants carry a particle-scale churn. Both knobs below are
    # active only while ``elapsed < settle_time``: a much larger XSPH coefficient
    # and a much larger viscosity. Both are short-wavelength dissipators (rate
    # 2 nu k^2: for a k ~ pi/dx churn that is thousands of 1/s, for the wave
    # k ~ 5 1/m it is a fraction of 1/s), which is why they can quiet the
    # transient without damping the wave -- but they are only on during the
    # settle window, so no wave ever sees them.
    xsph_settle: float = 0.0
    viscosity_settle: float = 0.0
    # Probe positions; empty means "derive them from the propagation zone".
    probes: tuple = ()
    probe_bin_halfwidth: float = 1.5
    # Surfaces are reported as (topmost particle) + this many particle spacings.
    surface_offset_cells: float = 0.5
    freeboard: float = 0.03
    hydrostatic_init: bool = True
    # Flume defaults: fresh-water laminar viscosity, delta-SPH density diffusion
    # for pressure noise, and an acoustic speed that keeps the O(g h/c0^2)
    # compressibility bias of the celerity below 0.3 %.
    viscosity: float = 1.0e-6
    density_diffusion: float = 0.1
    sound_speed: float = 30.0
    dx: float = 0.0125
    dt: float = 4.0e-4
    steps: int = 5000
    output_every: int = 20

    def free_surface_top(self) -> float:
        """Height of the computational box."""
        return float(self.depth + 3.0 * self.wave_height + self.freeboard)

    def sponge_start(self) -> float:
        return float(self.flume_length - self.sponge_length)

    def surface_offset(self) -> float:
        return float(self.surface_offset_cells * self.dx)


@dataclass
class WaveSpec:
    """The target wave: what the paddle is asked to generate."""

    kind: str
    height: float
    depth: float
    gravity: float
    stroke: float
    celerity: float
    k: float = 0.0
    omega: float = 0.0
    period: float = 0.0
    wavelength: float = 0.0
    length_scale: float = 0.0

    def elevation(self, x, time: float) -> float:
        """Analytic elevation of the target wave at ``(x, time)``."""
        if self.kind == "regular":
            return airy_elevation(x, time, self.height, self.k, self.omega)
        return solitary_wave_elevation(x, time, self.height, self.depth,
                                       self.gravity)


def flume_wave_spec(cfg: WaveFlumeConfig) -> WaveSpec:
    """Derive the target wave: dispersion, celerity and required paddle stroke."""
    height = _positive("wave_height", cfg.wave_height)
    depth = _positive("depth", cfg.depth)
    gravity = _positive("gravity", cfg.gravity)
    if cfg.wave_type == "regular":
        period = _positive("wave_period", cfg.wave_period)
        k = wavenumber_from_period(period, depth, gravity)
        omega = linear_dispersion_omega(k, depth, gravity)
        return WaveSpec(kind="regular", height=height, depth=depth,
                        gravity=gravity,
                        stroke=piston_stroke_amplitude(height, k, depth),
                        celerity=omega / k, k=k, omega=omega, period=period,
                        wavelength=2.0 * math.pi / k)
    if cfg.wave_type == "solitary":
        return WaveSpec(kind="solitary", height=height, depth=depth,
                        gravity=gravity,
                        stroke=goring_max_stroke(height, depth),
                        celerity=solitary_wave_celerity(height, depth, gravity),
                        length_scale=solitary_wave_length(height, depth))
    raise ValueError(
        f"wave_type must be 'regular' or 'solitary', got {cfg.wave_type!r}")


def validate_flume(cfg: WaveFlumeConfig) -> None:
    """Reject geometries and settings that would silently produce a wrong case."""
    if cfg.dx <= 0 or cfg.dt <= 0 or cfg.h_factor <= 0:
        raise ValueError("dx, dt and h_factor must be positive")
    if cfg.depth <= 0 or cfg.flume_length <= 2.0 * cfg.depth:
        raise ValueError("the flume must be at least twice as long as it is deep")
    if cfg.boundary != "wall":
        raise ValueError(
            "the flume holds its water with kinematic wall particles; "
            f"boundary={cfg.boundary!r} is not supported")
    spec = flume_wave_spec(cfg)
    if spec.height >= 0.5 * cfg.depth:
        raise ValueError(
            f"wave_height/depth = {spec.height / cfg.depth:.2f} is outside the "
            "range where first-order theory is a meaningful anchor (keep < 0.5)")
    if cfg.depth / cfg.dx < 6.0:
        raise ValueError(
            f"depth/dx = {cfg.depth / cfg.dx:.2f} is too coarse; keep at least "
            "6 particles through the still-water depth")
    if cfg.sponge_length <= 0.0 or cfg.sponge_length >= 0.5 * cfg.flume_length:
        raise ValueError("the sponge must be positive and shorter than half the flume")
    if cfg.sponge_strength <= 0.0 or cfg.sponge_exponent <= 0.0:
        raise ValueError("sponge_strength and sponge_exponent must be positive")
    if cfg.active_absorption < 0.0:
        raise ValueError("active_absorption is a non-negative gain")
    if spec.kind == "regular":
        if spec.wavelength > cfg.flume_length:
            raise ValueError("the flume is shorter than one wavelength")
        if cfg.sponge_length < 0.5 * spec.wavelength:
            raise ValueError(
                "the sponge must be at least half a wavelength long, otherwise the "
                f"damping profile acts as a wall (sponge {cfg.sponge_length:g} m, "
                f"wavelength {spec.wavelength:g} m)")
    if cfg.wave_height / cfg.dx < 2.0:
        raise ValueError(
            f"wave_height/dx = {cfg.wave_height / cfg.dx:.2f}: the crest is not "
            "resolved by at least two particle spacings")
    for name, value in (("depth", cfg.depth), ("flume_length", cfg.flume_length)):
        cells = value / cfg.dx
        if abs(cells - round(cells)) > 1.0e-9:
            raise ValueError(
                f"{name}/dx = {cells:.4f} is not an integer. The water lattice is "
                "anchored on the floor and on the paddle face, so a partial cell "
                "leaves the last column up to one spacing from the wall: the "
                "under-supported column is then kicked away from the wall at "
                "start-up (measured: 0.5 m/s and a 1.4 % compression spike in the "
                "first 25 ms at 1.38 dx clearance). Set both depth and "
                "flume_length to multiples of dx.")


