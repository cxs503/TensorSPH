# --------------------------------------------------------------------------- #
# Linear wave theory
# --------------------------------------------------------------------------- #

def _positive(name: str, value) -> float:
    value = float(value)
    if not math.isfinite(value) or value <= 0.0:
        raise ValueError(f"{name} must be finite and positive, got {value!r}")
    return value


def linear_dispersion_omega(k, depth, gravity: float = 9.81) -> float:
    """Angular frequency of a linear gravity wave, ``omega^2 = g k tanh(k h)``."""
    k = _positive("k", k)
    depth = _positive("depth", depth)
    gravity = _positive("gravity", gravity)
    return math.sqrt(gravity * k * math.tanh(k * depth))


def wavenumber_from_omega(omega, depth, gravity: float = 9.81) -> float:
    """Solve ``omega^2 = g k tanh(k h)`` for ``k``.

    ``g k tanh(k h)`` increases monotonically from 0 to infinity in ``k``, so a
    bracket plus bisection converges unconditionally; 200 halvings take the
    bracket to machine precision of the root and cost nothing.
    """
    omega = _positive("omega", omega)
    depth = _positive("depth", depth)
    gravity = _positive("gravity", gravity)
    target = omega * omega
    lo = 1.0e-12
    hi = 10.0 * max(target / gravity, omega / math.sqrt(gravity * depth))
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if gravity * mid * math.tanh(mid * depth) < target:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def wavenumber_from_period(period, depth, gravity: float = 9.81) -> float:
    """Wave number of the linear wave of the given period."""
    period = _positive("period", period)
    return wavenumber_from_omega(2.0 * math.pi / period, depth, gravity)


def wavelength(period, depth, gravity: float = 9.81) -> float:
    """Linear wavelength of the given period, ``2 pi / k``."""
    return 2.0 * math.pi / wavenumber_from_period(period, depth, gravity)


def phase_speed(period, depth, gravity: float = 9.81) -> float:
    """Linear phase speed ``omega / k`` of the given period."""
    k = wavenumber_from_period(period, depth, gravity)
    return linear_dispersion_omega(k, depth, gravity) / k


def airy_elevation(x, time, height, k, omega, phase: float = 0.0):
    """First-order progressive wave ``eta = H/2 cos(k x - omega t + phase)``."""
    return 0.5 * height * math.cos(k * x - omega * time + phase)


def _piston_transfer(k: float, depth: float) -> float:
    """``H/S`` of a piston wavemaker; series form near ``kh = 0``."""
    kh = k * depth
    if kh < 1.0e-3:
        return kh * (1.0 - kh ** 4 / 45.0)
    return 2.0 * (math.cosh(2.0 * kh) - 1.0) / (math.sinh(2.0 * kh) + 2.0 * kh)


def piston_stroke_amplitude(height, k, depth) -> float:
    """Piston stroke ``S`` that generates a linear wave of height ``H``.

    ``H/S = 2 (cosh 2kh - 1)/(sinh 2kh + 2kh)`` is the piston wavemaker transfer
    function: the stroke per unit wave height grows like ``1/(kh)`` for long
    waves, because a long wave's particle excursion is large compared with its
    surface elevation.  For ``kh < 1e-3`` the closed form loses digits to
    cancellation and the series ``H/S = kh (1 - (kh)^4/45 + O((kh)^6))`` is used.
    """
    height = _positive("height", height)
    k = _positive("k", k)
    depth = _positive("depth", depth)
    return height / _piston_transfer(k, depth)


def paddle_stroke_for_height(stroke, k, depth) -> float:
    """Inverse of :func:`piston_stroke_amplitude`: wave height of a stroke."""
    stroke = _positive("stroke", stroke)
    k = _positive("k", k)
    depth = _positive("depth", depth)
    return stroke * _piston_transfer(k, depth)


# --------------------------------------------------------------------------- #
# Solitary wave (first-order Rayleigh / Boussinesq)
# --------------------------------------------------------------------------- #

def solitary_wave_celerity(height, depth, gravity: float = 9.81) -> float:
    """``c = sqrt(g (h + H))``: first-order solitary-wave celerity."""
    height = _positive("height", height)
    depth = _positive("depth", depth)
    gravity = _positive("gravity", gravity)
    return math.sqrt(gravity * (depth + height))


def solitary_alpha(height, depth) -> float:
    """Inverse width ``alpha = sqrt(3H/(4h^3))`` of the sech^2 profile."""
    height = _positive("height", height)
    depth = _positive("depth", depth)
    return math.sqrt(3.0 * height / (4.0 * depth ** 3))


def solitary_wave_length(height, depth) -> float:
    """Characteristic length ``1/alpha``: the profile is ``sech^2(x/L)``."""
    return 1.0 / solitary_alpha(height, depth)


def solitary_wave_elevation(x, time, height, depth, gravity: float = 9.81,
                            crest: float = 0.0):
    """``eta = H sech^2(alpha (x - c t - crest))``, first order in ``H/h``."""
    height = _positive("height", height)
    depth = _positive("depth", depth)
    alpha = solitary_alpha(height, depth)
    celerity = solitary_wave_celerity(height, depth, gravity)
    return height / math.cosh(alpha * (x - celerity * time - crest)) ** 2


def _sech2(value: float) -> float:
    return 1.0 / math.cosh(value) ** 2


def _atanh(value: float) -> float:
    return 0.5 * math.log((1.0 + value) / (1.0 - value))


def goring_paddle_velocity(tau, height, depth, gravity: float = 9.81) -> float:
    """Paddle velocity of Goring's (1979) solitary-wave generator.

    ``U = c eta/(h + eta)`` is the depth-averaged fluid velocity of the wave the
    paddle pushes ahead of itself; for a long wave the depth-uniform paddle
    velocity has to match it, which is what makes this the standard
    solitary-wave wavemaker condition.  ``tau`` is measured from the instant the
    crest leaves the paddle.
    """
    height = _positive("height", height)
    depth = _positive("depth", depth)
    alpha = solitary_alpha(height, depth)
    celerity = solitary_wave_celerity(height, depth, gravity)
    eta = height * _sech2(alpha * celerity * tau)
    return celerity * eta / (depth + eta)


def goring_paddle_acceleration(tau, height, depth, gravity: float = 9.81) -> float:
    """``dU/dtau`` of :func:`goring_paddle_velocity` (analytic, not differenced)."""
    height = _positive("height", height)
    depth = _positive("depth", depth)
    alpha = solitary_alpha(height, depth)
    celerity = solitary_wave_celerity(height, depth, gravity)
    argument = alpha * celerity * tau
    shading = _sech2(argument)
    eta = height * shading
    d_eta = -2.0 * alpha * celerity * height * shading * math.tanh(argument)
    return celerity * depth * d_eta / (depth + eta) ** 2


def goring_stroke(tau, height, depth, gravity: float = 9.81) -> float:
    """Paddle displacement of Goring's generator, in closed form.

    Integrating ``ds/dt = c eta/(h + eta)`` from ``-inf`` with
    ``eta = H sech^2(alpha c t)``:

        s(tau) = (H/(alpha h)) (2/sqrt(mu(1+mu)))
                 artanh( sqrt(mu/(1+mu)) tanh(alpha c tau) ),   mu = H/h

    The odd function is zero when the crest passes the paddle.  A closed form
    avoids accumulating the stroke from thousands of quadrature steps, so the
    paddle motion is reproducible from the parameters alone.
    """
    height = _positive("height", height)
    depth = _positive("depth", depth)
    alpha = solitary_alpha(height, depth)
    celerity = solitary_wave_celerity(height, depth, gravity)
    mu = height / depth
    scale = (height / (alpha * depth)) * (1.0 / math.sqrt(mu * (1.0 + mu)))
    return scale * _atanh(math.sqrt(mu / (1.0 + mu))
                          * math.tanh(alpha * celerity * tau))


def goring_max_stroke(height, depth) -> float:
    """Total stroke ``s(+inf) - s(-inf)`` of Goring's generator."""
    height = _positive("height", height)
    depth = _positive("depth", depth)
    mu = height / depth
    alpha = solitary_alpha(height, depth)
    scale = (height / (alpha * depth)) * (1.0 / math.sqrt(mu * (1.0 + mu)))
    return 2.0 * scale * math.log(math.sqrt(1.0 + mu) + math.sqrt(mu))


