def _ramp(time: float, duration: float):
    """Raised-cosine start ramp and its first two time derivatives."""
    if duration <= 0.0 or time >= duration:
        return 1.0, 0.0, 0.0
    if time <= 0.0:
        return 0.0, 0.0, 0.0
    omega = math.pi / duration
    return (0.5 * (1.0 - math.cos(omega * time)),
            0.5 * omega * math.sin(omega * time),
            0.5 * omega * omega * math.cos(omega * time))


def solitary_time_origin(spec: WaveSpec) -> float:
    """Lead time before the crest passes the paddle, so the start velocity is ~0.

    ``U(tau)`` decays like ``sech^2``; three characteristic times ahead of the
    crest shadow the paddle velocity to below 1 % of its peak.
    """
    alpha = solitary_alpha(spec.height, spec.depth)
    return 3.0 / (alpha * spec.celerity)


def paddle_motion(spec: WaveSpec, cfg: WaveFlumeConfig, time: float):
    """Prescribed paddle ``(offset, velocity, acceleration)`` at ``time``.

    Regular waves: ``s = (S/2) r(t) sin(omega t)`` with a raised-cosine amplitude
    ramp ``r`` -- the piston's first-order motion, so the generated wave height is
    the ``H`` that :func:`piston_stroke_amplitude` inverted.  Solitary waves:
    Goring's displacement and velocity, evaluated a few characteristic times
    before the crest so the paddle starts from rest.
    """
    if cfg.wave_type == "regular":
        ramp, ramp_dot, ramp_ddot = _ramp(time, cfg.ramp_periods * spec.period)
        half = 0.5 * spec.stroke
        phase = spec.omega * time
        offset = half * ramp * math.sin(phase)
        speed = half * (ramp_dot * math.sin(phase)
                        + ramp * spec.omega * math.cos(phase))
        accel = half * (ramp_ddot * math.sin(phase)
                        + 2.0 * ramp_dot * spec.omega * math.cos(phase)
                        - ramp * spec.omega ** 2 * math.sin(phase))
        return offset, speed, accel
    lead = solitary_time_origin(spec)
    tau = time - lead
    offset = (goring_stroke(tau, spec.height, spec.depth, spec.gravity)
              - goring_stroke(-lead, spec.height, spec.depth, spec.gravity))
    return (offset,
            goring_paddle_velocity(tau, spec.height, spec.depth, spec.gravity),
            goring_paddle_acceleration(tau, spec.height, spec.depth,
                                       spec.gravity))


def sponge_rate(x, cfg: WaveFlumeConfig, spec: WaveSpec):
    """Damping rate ``alpha(x)`` [1/s] of the sponge layer.

    Zero upstream of ``sponge_start``; inside the layer
    ``alpha = alpha_max ((x - x_s)/L_s)^p`` with ``alpha_max = sponge_strength *
    c / L_s``.  The smooth ramp is what keeps the layer from reflecting: a step in
    damping is a step in impedance.  Accepts a float or a ``torch.Tensor`` (the
    driver damps per particle).
    """
    start = cfg.sponge_start()
    length = float(cfg.sponge_length)
    alpha_max = cfg.sponge_strength * spec.celerity / length
    if isinstance(x, torch.Tensor):
        ramp = ((x - start).clamp_min(0.0) / length).clamp(max=1.0)
        return alpha_max * ramp.pow(cfg.sponge_exponent)
    if x <= start:
        return 0.0
    return alpha_max * min(1.0, (x - start) / length) ** cfg.sponge_exponent


