"""m16454: A2 large-deflection check of the elastic-gate rod, in the same frame.

The delivered A2 (mission m16352, ``docs/fsi_elastic_gate/03_report.md``) read
"+86.8 %" as a *rod* accuracy gap and used it to declare the gate-tip
displacement metric untrustworthy.  The rod stands along ``+y`` and is loaded
along ``+x``; :func:`tensorsph.fsi_elastic_gate.elastica_tip` integrates a
cantilever along its own ``+x`` axis with a transverse load along ``+y``.  The
delivered A2 therefore compared the rod's *transverse* deflection with the
elastica's *axial* coordinate.  This script re-runs A2 in one frame, adds two
more metrics (axial shortening, tip slope), and sweeps the rod resolution.

It also solves the elastica *shape* independently (own ODE integration) so the
deformed geometry can be plotted against the discrete rod.

Everything printed/plotted here is generated by this script; no number is
transcribed into the markdown by hand.

Usage::

    python scripts/m16454_a2_frame_fix.py            # full sweep + figure
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from tensorsph import fsi_elastic_gate as fg  # noqa: E402

OUT = ROOT / "runs" / "fsi_elastic_gate_a2"
FIG = ROOT / "docs" / "fsi_elastic_gate" / "fig_a2_frame_fix.png"


def elastica_shape(load: float, height: float, ei: float, n_s: int = 401):
    """Independent integration of the Kirchhoff elastica, returning x(s), y(s).

    Same physical problem as :func:`fg.elastica_tip` but a *separate*
    implementation (fixed ``x_tip`` from that module, ``solve_ivp`` dense
    output here) so the plotted reference curve is not the rod's own data.
    """
    from scipy.integrate import solve_ivp

    x_tip = fg.elastica_tip(load, height, ei)["tip_x"]

    def rhs(_s, y):
        theta, x, _yy = y
        return [load * (x_tip - x) / ei, math.cos(theta), math.sin(theta)]

    s = np.linspace(0.0, height, n_s)
    sol = solve_ivp(rhs, (0.0, height), [0.0, 0.0, 0.0], t_eval=s,
                    rtol=1e-12, atol=1e-14)
    return s, sol.y[1], sol.y[2]


def rod_shape(case, load, ei):
    nodal = torch.zeros((case.n_gate_nodes, 2), dtype=torch.float64)
    nodal[-1, 0] = load
    nodes = fg.rod_static_equilibrium(case, nodal, gravity=False)
    x = nodes[:, 0].numpy() - case.water_width          # transverse
    y = nodes[:, 1].numpy()                            # axial (from the floor)
    return x, y


def metrics(n: int, load_ratio: float = 10.0) -> dict:
    case = fg.ElasticGateCase(dx=0.0125, n_gate_nodes=n)
    a2 = fg.verify_cantilever(case)["A2_elastica"]
    a2 = {k: (float(v) if isinstance(v, (int, float)) else v) for k, v in a2.items()}
    a2["n_gate_nodes"] = n
    a2["segments"] = n - 1
    return a2


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    FIG.parent.mkdir(parents=True, exist_ok=True)

    case25 = fg.ElasticGateCase(dx=0.0125, n_gate_nodes=25)
    ei = case25.gate_stiffness_bending()
    height = case25.gate_height
    load = 10.0 * ei / height ** 2

    rows = [metrics(n) for n in (13, 25, 50)]

    # reference cross-checks: the elastica must fall back on Euler-Bernoulli
    eb_checks = []
    for eps in (1.0e-3, 1.0e-2, 1.0e-1):
        p = eps * ei / height ** 2
        ref = fg.elastica_tip(p, height, ei)
        eb = fg.eb_tip_point_load(p, height, ei)
        eb_checks.append({"P_H2_over_EI": eps, "tip_y_elastica": float(ref["tip_y"]),
                          "tip_y_euler_bernoulli": eb,
                          "rel_error": float(ref["tip_y"] / eb - 1.0)})

    # geometry for the figure
    x_rod, y_rod = rod_shape(case25, load, ei)
    s_ref, x_ref, y_ref = elastica_shape(load, height, ei)

    payload = {
        "case": "CASE-SPH-FSI-ELASTIC-GATE / A2 (large-deflection cantilever)",
        "source": "scripts/m16454_a2_frame_fix.py",
        "frame": ("rod: along +y, loaded along +x -> transverse = dx, axial = y; "
                  "elastica_tip: along +x, transverse load along +y -> "
                  "transverse = tip_y, axial = tip_x.  Congruent under "
                  "(dx, y) -> (y, dx)."),
        "EI": ei, "H": height, "P": load, "P_H2_over_EI": load * height ** 2 / ei,
        "elastica_vs_euler_bernoulli": eb_checks,
        "sweep": rows,
        "tip_geometry": {
            "rod_x": x_rod.tolist(), "rod_y": y_rod.tolist(),
            "elastica_s": s_ref.tolist(), "elastica_x": x_ref.tolist(),
            "elastica_y": y_ref.tolist(),
        },
    }
    (OUT / "a2_metrics.json").write_text(json.dumps(payload, indent=2))

    # ---------------- figure ----------------
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, (ax0, ax1) = plt.subplots(1, 2, figsize=(11.0, 4.6))

    # (a) deformed geometry in one frame: transverse vs axial coordinate
    ax0.plot(y_ref, x_ref, "-", color="tab:blue", lw=2.0,
             label="Kirchhoff elastica (independent ODE)")
    ax0.plot(y_rod, x_rod, "o--", color="tab:red", ms=4.5,
             label="discrete rod, n=25 (energy minimisation)")
    ax0.plot(y_rod[0], x_rod[0], "ks", ms=6)
    ax0.annotate("clamped", (y_rod[0], x_rod[0]), textcoords="offset points",
                 xytext=(8, -12), fontsize=8)
    ax0.set_xlabel("axial coordinate $y$ / m")
    ax0.set_ylabel("transverse deflection $x$ / m")
    ax0.set_title("(a) $PH^2/EI=10$: rod vs elastica, one frame")
    ax0.set_aspect("equal")
    ax0.grid(alpha=0.3)
    ax0.legend(fontsize=8, loc="upper left")

    # (b) error vs rod resolution, plus the historical frame-mismatch number
    ns = [r["n_gate_nodes"] for r in rows]
    ax1.semilogy(ns, [abs(r["rel_error"]) * 100 for r in rows], "o-",
                 label="transverse deflection")
    ax1.semilogy(ns, [abs(r["axial_rel_error"]) * 100 for r in rows], "s-",
                 label="axial shortening")
    ax1.semilogy(ns, [abs(r["slope_rel_error"]) * 100 for r in rows], "^-",
                 label="tip slope")
    ax1.semilogy(ns, [abs(r["frame_mismatch_rel_error"]) * 100 for r in rows],
                 "k--", alpha=0.6,
                 label="delivered A2 (frame mismatch, not a rod error)")
    ax1.axhline(5.0, color="tab:green", ls=":", lw=1.0, label="5 % gate")
    ax1.set_xlabel("rod nodes $n$")
    ax1.set_ylabel("absolute error vs elastica / %")
    ax1.set_title("(b) same-frame error converges as the rod is refined")
    ax1.grid(alpha=0.3, which="both")
    ax1.legend(fontsize=7.5)

    fig.tight_layout()
    fig.savefig(FIG, dpi=160)
    plt.close(fig)

    print(json.dumps({"sweep": [{k: r[k] for k in
                                 ("n_gate_nodes", "rel_error", "axial_rel_error",
                                  "slope_rel_error", "frame_mismatch_rel_error")}
                                for r in rows],
                      "eb_checks": eb_checks,
                      "figure": str(FIG.relative_to(ROOT)),
                      "json": str((OUT / "a2_metrics.json").relative_to(ROOT))},
                     indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())