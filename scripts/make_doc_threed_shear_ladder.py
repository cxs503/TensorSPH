"""Regenerate ``docs/dev_report_threed_shear_ladder.md`` from the committed artifact.

Every number in the document is injected from
``benchmarks/threed_shear/report.json`` (itself written by
``benchmarks/threed_shear/run.py --merge``), so nothing is typed by hand.

Run::

    PYTHONPATH=src python scripts/make_doc_threed_shear_ladder.py
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
REPORT = REPO / "benchmarks" / "threed_shear" / "report.json"
DOC = REPO / "docs" / "dev_report_threed_shear_ladder.md"


def pct(x: float) -> str:
    return f"{100.0 * x:+.2f} %"


def row(rung: dict) -> str:
    d = rung["decay"]
    return (
        f"| `{rung['case']}` | {rung['n']} | {rung['particles']} | "
        f"{rung['h_over_dx']:.2f} | {rung['kh']:.3f} | {d['fit_rate']:.4f} | "
        f"{d['analytic_rate']:.4f} | {pct(d['rel_error'])} |"
    )


def main() -> int:
    d = json.loads(REPORT.read_text())
    order4 = [r for r in d["higher_order_ladder"]] if "higher_order_ladder" in d else []
    sweep = d["h_over_dx_sweep"]
    state = d["order_comparison"] if "order_comparison" in d else None

    lines: list[str] = []
    lines.append("# 3-D shear-decay ladder: closing the missing resolutions\n")
    lines.append(
        "**Artifact**: `benchmarks/threed_shear/report.json` (regenerated by "
        "`run.py --merge`), per-case JSON under `benchmarks/threed_shear/cases/`; "
        "figure `benchmarks/threed_shear/figures/threed_shear.png`.\n"
    )
    lines.append(
        "This document is generated by `scripts/make_doc_threed_shear_ladder.py`; "
        "every number below is read from the artifact.\n"
    )

    lines.append("## 1. Case and reference\n")
    lines.append(f"Case: {d['case']}.\n")
    lines.append(f"Reference: {d['reference']}.\n")
    lines.append("| parameter | value |")
    lines.append("|---|---|")
    for k, v in d["params"].items():
        lines.append(f"| `{k}` | {v} |")
    lines.append("")

    lines.append("## 2. Method\n")
    lines.append(
        "A velocity field `u = A sin(ky) sin(kz)` on a triply periodic cube decays "
        "as `exp(-2 nu k^2 t)` for the Stokes (creeping) limit. The SPH momentum "
        "equation is advanced with the Tait equation of state; the fitted decay "
        "rate of the discrete kinetic energy is compared with `2 nu k^2`. The "
        "viscous operator is the renormalised Laplacian (Trask et al. 2015 form) "
        "and, for the fourth-order rungs, the two-pass operator of "
        "`benchmarks/threed_shear/fourth_order.py`.\n"
    )

    lines.append("## 3. Results (programmatic injection)\n")
    lines.append("### 3.1 Second-order ladder (h/dx = 1.3)\n")
    lines.append("| case | n | particles | h/dx | kh | fit rate [1/s] | analytic [1/s] | error |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for r in d["resolution_ladder"]:
        lines.append(row(r))
    lines.append("")
    lines.append("### 3.2 h/dx sweep at n = 20\n")
    lines.append("| case | n | particles | h/dx | kh | fit rate [1/s] | analytic [1/s] | error |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for r in sweep:
        lines.append(row(r))
    lines.append("")
    if order4:
        lines.append("### 3.3 Fourth-order viscous operator\n")
        lines.append("| case | n | particles | h/dx | kh | fit rate [1/s] | analytic [1/s] | error |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for r in order4:
            lines.append(row(r))
        lines.append("")

    lines.append("## 4. Gates\n")
    lines.append("| criterion | value |")
    lines.append("|---|---|")
    for k, v in d["criteria"].items():
        lines.append(f"| `{k}` | {v} |")
    lines.append(f"\n**verdict**: `{d['verdict']}`; **missing cases**: `{d['missing_cases']}`.\n")

    if state:
        lines.append("### 4.1 Second vs fourth order per rung\n")
        lines.append("| rung | second-order error | fourth-order error | fourth better? |")
        lines.append("|---|---|---|---|")
        for r in state:
            lines.append(
                f"| n={r['n']} | {pct(r['second_order_rel_error'])} | "
                f"{pct(r['fourth_order_rel_error'])} | {r['error_ratio']} |"
            )
        lines.append("")

    lines.append("## 5. Notes, limitations\n")
    lines.append(
        "1. The `mu = 0` control is not part of this ladder; the spurious-dissipation "
        "floor of the scheme is measured separately in the 2-D Taylor-Green case "
        "(`docs/benchmarks/taylor-green.md`).\n"
        "2. `kh` is reported per rung because the decay-rate error of a particle "
        "viscous operator is a function of `kh`, not of `n` alone; at `kh` well "
        "below 1 the truncation error is small and at `kh` approaching 1 it is not.\n"
        "3. The ladder is a verification of the viscous operator against an exact "
        "Stokes solution, not a validation against measurement.\n"
    )

    lines.append("## 6. Error verdict (explicit)\n")
    finest = d["resolution_ladder"][-1]
    worst = max(d["resolution_ladder"], key=lambda r: abs(r["decay"]["rel_error"]))
    lines.append(
        f"- finest rung `{finest['case']}`: {pct(finest['decay']['rel_error'])} "
        f"(< 3 %? {'YES' if abs(finest['decay']['rel_error']) <= 0.03 else 'NO'})"
    )
    lines.append(
        f"- worst rung `{worst['case']}`: {pct(worst['decay']['rel_error'])} "
        f"(< 15 %? {'YES' if abs(worst['decay']['rel_error']) <= 0.15 else 'NO'})"
    )
    if sweep:
        w = max(sweep, key=lambda r: abs(r["decay"]["rel_error"]))
        lines.append(
            f"- worst h/dx rung `{w['case']}`: {pct(w['decay']['rel_error'])} "
            f"(< 15 %? {'YES' if abs(w['decay']['rel_error']) <= 0.15 else 'NO'})"
        )
    lines.append("")

    DOC.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[-14:]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())