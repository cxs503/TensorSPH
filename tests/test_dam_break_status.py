"""Pin the dam-break (B2) verification status to its machine-checked artifacts.

This is the regression guard for docs/verification_dam_break.md: the document is
generated by benchmarks/dam_break/make_status_doc.py from
resolution_ladder.json + reference_audit.json, and these tests assert that the
document, the artifacts, and the provenance verdict all agree. No simulation is
run here (the artifacts are the evidence; re-running the ladder is a separate,
heavier mission).

Pinned facts (see docs/verification_dam_break.md):
* the bundled Martin & Moyce (1952) table is graded WITHHELD and is NOT usable
  as a validation target (exact tau lattice + exact 0.05 ordinate quantum);
* the experimental gate therefore FAILS on the number but is not a valid
  accuracy verdict;
* the stability gates (mass / escape / Mach / compression) all PASS;
* the Ritter comparison at H/a=2 is a diagnostic (no gate).
"""
import json
import re
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parents[1]
LADDER = HERE / "benchmarks" / "dam_break" / "resolution_ladder.json"
AUDIT = HERE / "benchmarks" / "dam_break" / "reference_audit.json"
DOC = HERE / "docs" / "verification_dam_break.md"
FIG = HERE / "docs" / "assets" / "dam_break_status.png"


@pytest.fixture(scope="module")
def ladder():
    return json.loads(LADDER.read_text())


@pytest.fixture(scope="module")
def audit():
    return json.loads(AUDIT.read_text())


def test_artifacts_exist_and_parse(ladder, audit):
    assert LADDER.exists() and AUDIT.exists()
    assert len(ladder["results"]) >= 3
    assert "table_audit" in audit and "ritter" in audit


def test_martin_moyce_table_is_withheld(audit):
    """The bundled M&M table cannot arbitrate a 15% gate (provenance)."""
    t = audit["table_audit"]
    assert t["grade"] == "WITHHELD"
    assert t["usable_as_validation_target"] is False
    # the provenance evidence: exact lattice + exact quantum
    assert t["tau_lattice_residual"] < 1e-9
    assert t["ordinate_quantum_residual"] < 1e-9
    assert t["ordinate_quantum"] == 0.05


def test_experimental_gate_fails_but_reference_unusable(ladder, audit):
    """FAIL on the number, WITHHELD on the reference: both must stay true."""
    exp = ladder["gates"]["experimental_comparison"]
    assert exp["result"] == "fail"
    assert exp["measured"] > exp["limit"]
    assert audit["table_audit"]["usable_as_validation_target"] is False


def test_stability_gates_all_pass(ladder):
    for name in ("mass_conservation", "bounded_flow", "mach_number",
                 "density_compression"):
        assert ladder["gates"][name]["result"] == "pass", name


def test_ritter_is_diagnostic_not_gated(ladder):
    rit = ladder["gates"]["ritter_comparison"]
    assert "limit" not in rit  # no gate: finite-reservoir offset is physics
    assert rit["measured"] > 0.0


def test_ladder_errors_decrease_with_refinement(ladder):
    """Both error measures must not grow under refinement (dx 0.04->0.01)."""
    res = ladder["results"]
    ritter = [r["ritter_mean_relative_error"] for r in res]
    exp = [r["experimental_error"]["mean_absolute_error"] for r in res]
    assert ritter[-1] < ritter[0]
    assert exp[-1] < exp[0]


def test_document_is_in_sync_with_artifacts(ladder, audit):
    """The doc must carry the same verdicts as the JSON (no drift)."""
    assert DOC.exists(), "run benchmarks/dam_break/make_status_doc.py"
    md = DOC.read_text()
    assert "WITHHELD" in md
    assert "synthetic-looking" in md
    # the experimental gate number must match the JSON to 3 decimals
    measured = ladder["gates"]["experimental_comparison"]["measured"]
    assert f"{100 * measured:.1f}%" in md
    # stability gates must be reported as PASS in the doc
    assert "PASS" in md
    assert FIG.exists() and FIG.stat().st_size > 10_000


def test_figure_is_committed_under_docs():
    """The status figure must live under docs/ and the doc must embed it.

    Regression pin for PR #155: the figure was committed under benchmarks/, where
    the push gate drops ``*.png``, so the branch reached CI without the artifact
    that ``test_document_is_in_sync_with_artifacts`` requires.
    """
    rel = FIG.relative_to(HERE)
    assert rel.parts[0] == "docs", rel
    link = re.search(r"!\[[^\]]*\]\(([^)]+)\)", DOC.read_text())
    assert link, "the doc must embed the status figure"
    assert (DOC.parent / link.group(1)).resolve() == FIG.resolve()
