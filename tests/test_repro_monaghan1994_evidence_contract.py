"""Evidence contract for REPRO-SPH-MONAGHAN1994 (independent drift + honesty guards).

Why this file exists (adversarial review m16936)
-----------------------------------------------
The reproduction bundle merged in m16873 (``benchmarks/repro_monaghan_1994``)
shipped ~8 k lines of JSON, a generated document and two scripts, but **no
test**.  Nothing therefore failed if

  * ``results/summary.json`` drifted away from ``results/trajectory_*.json``
    (the summary being the only number source of the document),
  * the generated document re-acquired a claim the artefacts contradict, or
  * the probe artefact stopped describing the committed trajectory.

The document is regenerated by ``make_artifacts.py``; the guards below re-derive
the load-bearing numbers *independently* of that script (own interpolation, own
metric) and then compare against what is committed and what is printed.

No simulation runs here: every check reads committed artefacts, so the file is
fast enough for the default suite.
"""

from __future__ import annotations

import json
import math
import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
BENCH = REPO / "benchmarks" / "repro_monaghan_1994"
RESULTS = BENCH / "results"
DOC = REPO / "docs" / "repro_monaghan_1994.md"

WINDOW = (0.5, 3.0)
N_SAMPLES = 161


def _load(name: str) -> dict:
    path = RESULTS / name
    assert path.exists(), f"missing committed artefact {path}"
    return json.loads(path.read_text())


def _interp(xs, ys, xq):
    if xq <= xs[0]:
        return ys[0]
    if xq >= xs[-1]:
        return ys[-1]
    lo, hi = 0, len(xs) - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if xs[mid] <= xq:
            lo = mid
        else:
            hi = mid
    span = xs[hi] - xs[lo]
    if span <= 0:
        return ys[lo]
    return ys[lo] + (ys[hi] - ys[lo]) * (xq - xs[lo]) / span


def _metric(tau, za, ref) -> dict:
    """MAE, bias and amplitude over the pre-registered window (own implementation)."""
    lo = max(WINDOW[0], min(tau), min(ref["tau"]))
    hi = min(WINDOW[1], max(tau), max(ref["tau"]))
    grid = [lo + (hi - lo) * i / (N_SAMPLES - 1) for i in range(N_SAMPLES)]
    sim = [_interp(tau, za, g) for g in grid]
    exp = [_interp(ref["tau"], ref["za"], g) for g in grid]
    amp = max(exp)
    deltas = [s - e for s, e in zip(sim, exp)]
    mae = sum(abs(d) for d in deltas) / len(deltas)
    return {"amplitude": amp, "mae": mae, "bias": sum(deltas) / len(deltas),
            "mae_over_amplitude": mae / amp, "window": [lo, hi]}


def _reference_tables() -> dict:
    """Load both transcriptions exactly as the case's own loader does."""
    import sys
    if str(REPO) not in sys.path:
        sys.path.insert(0, str(REPO))
    from benchmarks.repro_monaghan_1994.run import references  # noqa: WPS433
    return references()


def test_summary_metrics_rederive_from_committed_trajectories():
    """summary.json must be recoverable from the trajectory files it summarises."""
    summary = _load("summary.json")
    tables = _reference_tables()
    checked = 0
    for run in summary["runs"]:
        traj = _load(f"trajectory_{run['case']}.json")
        for name in ("crosscheck", "bundled"):
            committed = summary["comparisons"][run["case"]][name]
            mine = _metric(traj["tau"], traj["za"], tables[name])
            assert mine["window"] == pytest.approx(committed["window"], abs=1e-12)
            for key in ("amplitude", "mae", "bias", "mae_over_amplitude"):
                assert mine[key] == pytest.approx(committed[key], rel=1e-9, abs=1e-12), (
                    f"{run['case']}/{name}/{key}: summary says {committed[key]}, "
                    f"trajectories give {mine[key]}")
            checked += 1
    assert checked == 6, "expected 3 resolutions x 2 references"


def test_ladder_is_non_monotone_only_because_the_bias_crosses_zero():
    """The documented diagnosis must be the one the artefacts support.

    |MAE| is non-monotone (4.67 % -> 1.65 % -> 4.38 %) while the *bias* changes
    sign between dx = 2 cm and dx = 1 cm.  A future "fix" that makes the gate
    green by picking a different normalisation would break this invariant; so
    would a document that explains the fail as non-convergence.
    """
    summary = _load("summary.json")
    ladder = sorted(summary["ladder"]["crosscheck"], key=lambda e: -e["dx"])
    biases = [summary["comparisons"][e["case"]]["crosscheck"]["bias"] for e in ladder]
    maes = [e["mae_over_amplitude"] for e in ladder]
    assert maes[1] < maes[0] and maes[2] > maes[1], "|MAE| non-monotonicity is the observation"
    assert biases[0] < 0 < biases[1], "bias must change sign across the ladder"
    assert biases[1] < biases[2], "bias must keep growing in the refinement direction"
    assert summary["gates"]["resolution_trend_vs_independent"]["result"] == "fail", (
        "the trend gate must stay red: the trend is not satisfied, the diagnosis only "
        "explains why a red trend is not a red solver")


def test_document_verdict_matches_the_artifact_numbers():
    """The ⑥ verdict line must not claim the 3 % paper grade that the table denies.

    Regression guard: the merged version of the generator hard-coded
    "误差在 3 % 以内（回答「是」）" while the same document's table printed
    4.38 % -> 否.  The sentence is now generated from the metric.
    """
    summary = _load("summary.json")
    tables = _reference_tables()
    finest = min(summary["runs"], key=lambda r: r["dx"])
    traj = _load(f"trajectory_{finest['case']}.json")
    measured = _metric(traj["tau"], traj["za"], tables["crosscheck"])["mae_over_amplitude"]
    text = DOC.read_text()

    verdict = [line for line in text.splitlines() if line.startswith("结论：")]
    assert len(verdict) == 1, "expected exactly one conclusion line"
    line = verdict[0]
    assert f"{100 * measured:.2f} %" in line, line
    if measured < 0.03:
        assert "在 3 % 以内（回答“是”）" in line
        assert "不在 3 % 以内" not in line
    else:
        assert "不在 3 % 以内（回答“否”）" in line, line
        assert "误差在 3 % 以内" not in text, "document overstates the error against the 3 % grade"
    # The platform tolerance is a different line and must be named as such.
    assert "15 %" in line and "pass" in line


def test_document_tables_quote_the_committed_numbers():
    """Every MAE in the ③.3 ladder table must appear in summary.json verbatim."""
    summary = _load("summary.json")
    text = DOC.read_text()
    for entry in summary["ladder"]["crosscheck"] + summary["ladder"]["bundled"]:
        printed = f"{100 * entry['mae_over_amplitude']:.2f} %"
        assert printed in text, f"{entry['case']}: {printed} missing from the document"
    for entry in summary["ladder"]["crosscheck"]:
        bias = summary["comparisons"][entry["case"]]["crosscheck"]["bias"]
        assert f"{bias:+.3f}" in text, f"{entry['case']}: bias {bias:+.3f} not printed"


def test_front_estimator_probe_reproduces_the_committed_trajectory():
    """The probe must be a re-run of the shipped case, not a re-plot of it."""
    probe_path = RESULTS / "front_estimator_probe.json"
    if not probe_path.exists():
        pytest.skip("probe artefact not committed")
    probe = json.loads(probe_path.read_text())
    for case in probe["cases"]:
        traj = _load(f"trajectory_{case['case']}.json")
        za = case["estimators"]["x_max"]
        n = min(len(za), len(traj["za"]))
        assert n > 10
        worst = max(abs(a - b) for a, b in zip(za[:n], traj["za"][:n]))
        # Same machine, same code path: the re-run must be bit-identical, which is
        # what makes the estimator comparison a property of the case and not noise.
        assert worst == 0.0, f"{case['case']}: re-run differs from the committed run by {worst}"
        assert case["tau"][:n] == pytest.approx(traj["tau"][:n], rel=0, abs=0)
        # No ejecta: max is the cloud's own leading edge at the probed resolutions.
        worst_ahead = max(q["n_ahead_of_p995_by_2dx"] for q in case["probe"])
        assert worst_ahead == 0, "a stray particle ahead of the cloud would invalidate max-x"


def test_probe_quantile_ladder_brackets_the_shipped_estimator():
    """max is the *most advanced* reading: quantiles must sit behind it."""
    probe_path = RESULTS / "front_estimator_probe.json"
    if not probe_path.exists():
        pytest.skip("probe artefact not committed")
    probe = json.loads(probe_path.read_text())
    tables = _reference_tables()
    for case in probe["cases"]:
        za = case["estimators"]
        mine = {k: _metric(case["tau"], v, tables["crosscheck"]) for k, v in za.items()}
        # quantile fronts lag the maximum, so their bias is more negative
        assert mine["x_max"]["bias"] > mine["p995"]["bias"] > mine["p99"]["bias"], case["case"]
        # and the estimator choice moves the graded quantity by well under a factor 2
        assert mine["p995"]["mae_over_amplitude"] < 2 * mine["x_max"]["mae_over_amplitude"]