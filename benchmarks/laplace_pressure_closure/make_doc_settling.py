""" + "\n".join(
        f"| {a['dx_m'] * 1e3:.1f} | {a['sound_speed']:g} | "
        + (f"{a['rel_error_pct']:+.1f} | {'yes' if abs(a['rel_error_pct']) < 15 else 'NO'} | "
           f"{'yes' if abs(a['rel_error_pct']) < 3 else 'NO'} |" if a["recorded"]
           else "not recorded | - | - |")
        for a in acc) + f"""

