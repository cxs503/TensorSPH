"""Render ``docs/xval_sphinx_tvc/LIMITER_LEG.md`` from ``data/limiter_leg.json``.

Every number in the document is read from the payload written by
``benchmarks/xval_sphinx_tvc/limiter_leg.py`` -- nothing is typed by hand, so
the document cannot drift from the run it describes.

Usage::

    python benchmarks/xval_sphinx_tvc/make_limiter_doc.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DATA = ROOT / "docs" / "xval_sphinx_tvc" / "data" / "limiter_leg.json"
OUT = ROOT / "docs" / "xval_sphinx_tvc" / "LIMITER_LEG.md"
FIG = ROOT / "docs" / "xval_sphinx_tvc" / "figure_limiter_leg.png"


def pct(x, nd=1):
    return "—" if x is None else f"{100.0 * x:.{nd}f} %"


def num(x, nd=4):
    return "—" if x is None else f"{x:.{nd}f}"


def figure(payload: dict, path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    op = payload["operator_level"]
    phys = payload["physics_level"]
    fig, ax = plt.subplots(1, 2, figsize=(11.0, 4.2))

    # (a) limiter law with the three regimes measured on the operator
    xs = [i / 400.0 for i in range(1, 401)]
    ax[0].plot(xs, [min(op["slope"] * x, 1.0) for x in xs], lw=1.6,
               label="TruncatedLinear(100): min(100 x, 1)")
    ax[0].axvline(op["threshold_abs_g_h"] ** 2, ls="--", c="k", lw=1.0,
                  label=f"threshold |g|h = {op['threshold_abs_g_h']:.2f}")
    ax[0].axvline(op["free_surface"]["grad_abs_h_mean"] ** 2, ls="-.",
                  c="tab:red", lw=1.2,
                  label=f"free surface |g|h = "
                        f"{op['free_surface']['grad_abs_h_mean']:.3f}")
    ax[0].axvline(op["jittered_bulk"]["grad_abs_h_mean"] ** 2, ls=":",
                  c="tab:green", lw=1.4,
                  label=f"jittered bulk |g|h = "
                        f"{op['jittered_bulk']['grad_abs_h_mean']:.4f}")
    ax[0].set_xlim(0, max(1.0, 1.2 * op["free_surface"]["grad_abs_h_mean"] ** 2))
    ax[0].set_ylim(0, 1.1)
    ax[0].set_xlabel(r"$x = h_{ref}^2\,|grad\text{-}1|^2$")
    ax[0].set_ylabel(r"limiter($x$)")
    ax[0].set_title("(a) ported limiter vs the operator's regimes")
    ax[0].legend(fontsize=7, loc="lower right")

    # (b) dam break: MAE with and without the limiter
    labels, vals_a, vals_b = [], [], []
    for dx in phys["resolutions"]:
        by = {r["variant"]: r for r in phys["records"] if r["dx"] == dx}
        for a, b in (("tvc_a005_all", "tvc_a005_all_tl"),
                     ("tvc_a020_all", "tvc_a020_all_tl")):
            if a in by and b in by:
                labels.append(f"dx={dx}\n$\\alpha$="
                              f"{by[a]['params'].get('tvc_alpha')}")
                vals_a.append(by[a]["score"]["mae"])
                vals_b.append(by[b]["score"]["mae"])
    idx = range(len(labels))
    ax[1].bar([i - 0.19 for i in idx], vals_a, 0.38, label="NoLimiter")
    ax[1].bar([i + 0.19 for i in idx], vals_b, 0.38,
              label="TruncatedLinear(100)")
    ax[1].axhline(0.15, ls="--", c="k", lw=1.0, label="gate MAE < 0.15")
    ax[1].set_xticks(list(idx))
    ax[1].set_xticklabels(labels, fontsize=7)
    ax[1].set_ylabel("MAE of $Z/a$ vs Martin & Moyce")
    ax[1].set_title("(b) dam break: limiter changes the MAE by little")
    ax[1].legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def render(data: Path = DATA, out: Path = OUT, fig: Path = FIG) -> int:
    payload = json.loads(Path(data).read_text())
    op = payload["operator_level"]
    phys = payload["physics_level"]
    ver = payload["verdicts"]
    figure(payload, Path(fig))

    L: list[str] = []
    a = L.append
    a("# The `TruncatedLinear` limiter: transcription and measured effect")
    a("")
    a(f"Anchor: `{payload['anchor']}`. Generated by")
    a("`benchmarks/xval_sphinx_tvc/limiter_leg.py` -> "
      "`benchmarks/xval_sphinx_tvc/make_limiter_doc.py` from")
    a(f"`data/limiter_leg.json` (wall clock {payload['wall_clock_s']:.1f} s, "
      f"torch {payload['env']['torch']}, {payload['env']['machine']}).")
    a("")
    a("![limiter leg](figure_limiter_leg.png)")
    a("")
    a("## 1. The gap this leg closes")
    a("")
    a("The port shipped upstream's operator with `NoLimiter` only and recorded")
    a("the limiter as *not transcribed*. Upstream ships two limiter objects in")
    a(f"`{payload['upstream']['file']}`")
    a(f"(sha256 `{payload['upstream']['sha256']}`, verbatim copy in")
    a("`oss_source/common_functors.h`): `NoLimiter` (factor 1) and")
    a("`TruncatedLinear`, whose `operator()` is")
    a("`SMIN(slope_ * dimensionless_measure, 1)` with `slope = 100` by default")
    a("(`SMIN(a, b) = (a <= b ? a : b)`). The argument passed by `update()` is")
    a("`h_ref^2 |inconsistency|^2`, so the limiter is `min(100 x, 1)`,")
    a("`x = h_ref^2 |grad-1|^2`.")
    a("")
    a("Which alias is which matters: `TransportVelocityCorrectionComplex` (the")
    a("alias of *most* examples) uses `NoLimiter`, but the three")
    a("`TransportVelocityLimitedCorrection*Complex` aliases use")
    a("`TruncatedLinear`:")
    for al in payload["upstream"]["aliases_using_it"]:
        a(f"* `{al}`")
    a("")
    a("instantiated by " + ", ".join(
        f"`{e}`" for e in payload["upstream"]["upstream_examples_using_it"]) + ".")
    a("")
    a("Note on a claim retired here: the earlier port docstring said upstream")
    a("also has `ModifiedTruncatedLinear`. It does not, in this revision -- the")
    a("fetched `common_functors.h` defines exactly the two objects above. That")
    a("sentence came from memory and is corrected against the source.")
    a("")
    a("## 2. How it was done")
    a("")
    a("| step | what |")
    a("|---|---|")
    a("| transcription | `tensorsph.transport_velocity_correction.truncated_linear(slope=100.0)`, "
      "`min(slope*x, 1)`, wired into the operator as `limiter=` |")
    a("| unit pinning | `tests/test_transport_velocity_correction.py`: value table "
      "against `SMIN(100x, 1)`, threshold `x = 1/slope`, slope argument, "
      "invalid slopes, bit-exact displacement law `dr = alpha h^2 limiter g` |")
    a("| solver wiring | `DamBreakConfig.tvc_limiter` (`None`/`\"none\"` = "
      "`NoLimiter`, `\"truncated_linear\"`), `tvc_limiter_slope` |")
    a("| operator-level measurement | `|g|h_ref` and the limiter on three "
      "particle sets: plane free surface, regular bulk, bulk + 2 % dx jitter |")
    a(f"| physics measurement | Martin & Moyce dam break, `dx = "
      f"{', '.join(str(r) for r in phys['resolutions'])}` m, `t = "
      f"{phys['seconds']} s`, alpha in {{0.05, 0.20}} x {{NoLimiter, "
      f"TruncatedLinear}}, scored with the same `score()` as the other legs |")
    a("")
    a("Predeclared before the runs (in the payload, "
      "`hypotheses_predeclared`):")
    for k, v in payload["hypotheses_predeclared"].items():
        a(f"* **{k}** — {v}")
    a("")
    a("## 3. Results — operator level")
    a("")
    a("| regime | particles | `|g| h_ref` | limiter(mean) | limiter(max) | "
      "`|dr|` ratio TL/NoLimiter |")
    a("|---|---|---|---|---|---|")
    fs, br, jb = op["free_surface"], op["bulk_regular"], op["jittered_bulk"]
    a(f"| plane free surface (top row) | {fs['particles']} | "
      f"{num(fs['grad_abs_h_mean'], 3)} | 1 | 1 | "
      f"{'1 (bit-identical)' if fs['shift_identical_to_NoLimiter'] else '≠1'} |")
    a(f"| regular bulk (square interior) | {br['particles']} | "
      f"{br['grad_abs_h_mean']:.2e} | {num(br['limiter_mean'], 3)} | "
      f"{num(br['limiter_max'], 3)} | — (`|g|` = 0 to round-off for both) |")
    a(f"| bulk + 2 % dx jitter | {jb['particles']} | "
      f"{num(jb['grad_abs_h_mean'], 4)} | "
      f"{num(jb['limiter_quantiles']['p50'], 4)} (p50) | "
      f"{num(jb['limiter_quantiles']['p99'], 4)} (p99) | "
      f"{num(jb['shift_ratio_quantiles']['p50'], 4)} (p50) |")
    a("")
    a(f"Analytic continuum scale for the free surface: `2 I(h,0) = 30/(7 pi) = "
      f"{num(fs['continuum_anchor_2I0'], 3)}`; the production lattice "
      f"`h/dx = {op['h_over_dx']}` measures `{num(fs['grad_abs_h_mean'], 3)}` "
      f"({pct(1 - fs['grad_abs_h_mean'] / fs['continuum_anchor_2I0'])} below, "
      "the plane-truncation bias already documented in `SURFACE_ANCHOR.md`).")
    a("")
    a(f"Threshold `|g| h_ref = sqrt(1/{op['slope']:.0f}) = "
      f"{op['threshold_abs_g_h']:.2f}`: the free surface is "
      f"{fs['grad_abs_h_mean'] / op['threshold_abs_g_h']:.1f}x above it, the "
      f"jittered bulk is "
      f"{op['threshold_abs_g_h'] / jb['grad_abs_h_mean']:.1f}x below it.")
    a("")
    a("H1 sub-conditions (all must hold): "
      + ", ".join(f"`{k}={v}`" for k, v in op["H1_detail"].items()))
    a("")
    a("**H1** — "
      + ("supported" if ver["H1_supported"] else "not supported")
      + ": the limiter is exactly inert wherever the free surface drives the")
    a("correction, and attenuates the (small) corrections of a nearly regular")
    a("bulk. Per-particle the applied displacement ratio equals the limiter")
    a("value elementwise "
      f"(`shift_ratio_equals_limiter = {jb['shift_ratio_equals_limiter']}`).")
    a("")
    a("## 4. Results — dam break")
    a("")
    a("| dx [m] | variant | MAE | mean rel. | max `|dr|/h` | gate |")
    a("|---|---|---|---|---|---|")
    for dx in phys["resolutions"]:
        for r in [x for x in phys["records"] if x["dx"] == dx]:
            sc = r["score"]
            gate = "PASS" if (sc["gate_abs_pass"] and sc["gate_rel_pass"]) else "FAIL"
            a(f"| {dx} | `{r['variant']}` | {num(sc['mae'], 3)} | "
              f"{pct(sc['mean_rel_error'])} | "
              f"{num(r['max_tvc_shift_over_h'], 4)} | {gate} |")
    a("")
    a("### 4a. Paired difference (the only thing this leg claims)")
    a("")
    a("| dx | pair | MAE NoLimiter | MAE TL | ΔMAE | Δ rel. mean | verdict changed |")
    a("|---|---|---|---|---|---|---|")
    for c in ver["comparisons"]:
        a(f"| {c['dx']} | `{c['pair']}` | {num(c['mae_no_limiter'], 3)} | "
          f"{num(c['mae_truncated_linear'], 3)} | {num(c['delta_mae'], 4)} | "
          f"{pct(c['rel_mean_truncated_linear'] - c['rel_mean_no_limiter'])} | "
          f"{c['gate_verdict_changed']} |")
    a("")
    a(f"Worst |ΔMAE| = {num(ver['worst_abs_delta_mae'], 4)} against the "
      f"predeclared tolerance {ver['H2_tolerance_abs']}: **H2 "
      + ("supported" if ver["H2_supported"] else "*not* supported") + "**"
      + (", no gate verdict flips."
         if not ver["any_gate_verdict_flip"] else
         ", a gate verdict does flip."))
    a("")
    a("Limiter census on the final state of the `_tl` runs (one lattice volume")
    a("per particle, `h = 1.3 dx`):")
    a("")
    a("| dx | variant | share of particles with limiter < 1 | share of total "
      "shift carried by them | mean shift ratio TL/NoLimiter |")
    a("|---|---|---|---|---|")
    for r in phys["records"]:
        c = r["limiter_census"]
        if not c:
            continue
        a(f"| {r['dx']} | `{r['variant']}` | "
          f"{pct(c['limiter_below_one_fraction'])} | "
          f"{pct(c['shift_share_of_limiters_only'])} | "
          f"{num(c['mean_shift_ratio_tl_over_none'], 3)} |")
    a("")
    a(f"Max fraction anywhere: {pct(ver['max_limiter_active_fraction'])} -> **H3 "
      + ("supported" if ver["H3_supported"] else "*not* supported") + "**.")
    a("")
    a("H2 split by coefficient (worst |ΔMAE| over the resolutions): "
      + ", ".join(f"`{k}`: {v:.4f}"
                  for k, v in ver["worst_abs_delta_mae_by_alpha"].items())
      + f". The predeclared tolerance is {ver['H2_tolerance_abs']} in `Z/a`.")
    a("")
    a("## 5. What this changes in the other legs")
    a("")
    a("* The dam-break conclusions of `UNCALIBRATED_DEFAULTS.md`, "
      "`RESOLUTION_LADDER.md` and `DISTRIBUTION_LADDER.md` stand: on a")
    a("  free-surface case the missing limiter is not a source of error, so the")
    a("  residual 10–17 % vs Martin & Moyce cannot be blamed on it.")
    a("* For the **bulk-scope, well-ordered** runs that upstream's limited")
    a("  aliases are actually used for (lid-driven cavity, throat), the port's")
    a("  `NoLimiter` default is *not* upstream-equivalent: it applies a")
    a("  correction that `TruncatedLinear` attenuates to "
      f"{pct(jb['shift_ratio_quantiles']['p50'])} of its size at the median")
    a("  bulk particle. Any upstream comparison of that family must pass")
    a("  `tvc_limiter=\"truncated_linear\"`.")
    a("* The limiter is a noise floor, not a cap: it never reduces a")
    a("  free-surface-scale correction. Code that expects it to bound the")
    a("  displacement under strong compression should use `tvc_max_shift` (the")
    a("  port's own safety cap), not this limiter.")
    a("")
    a("## 6. Limitations (honest)")
    a("")
    a("* Still no numeric diff against a live SPHinXsys build: the transcription")
    a("  is pinned to the source text and to the operator's algebra, not to a")
    a("  binary's output (gap 2 of the main report remains open).")
    a("* The dam-break evidence covers one case family (Martin & Moyce dry bed)")
    a("  at two resolutions; a lid-driven-cavity leg, where the limiter matters")
    a("  most, is *not* run here -- the operator-level table plus the census is")
    a("  the evidence for that regime, and that is weaker than a case run.")
    a("* The census uses one lattice volume per particle instead of the")
    a("  summation-density volume, so it is a snapshot diagnostic, not a")
    a("  per-step audit.")
    a("* `TruncatedLinear` interacts with `LinearGradientCorrection` in the two")
    a("  upstream \"Corrected\" aliases; the kernel-correction factor `C_i` is")
    a("  supported by the operator but not exercised in these runs.")
    a("")
    a("## 7. Artifacts")
    a("")
    a("* `src/tensorsph/transport_velocity_correction.py` — `truncated_linear`,")
    a("  `TRUNCATED_LINEAR_DEFAULT_SLOPE`")
    a("* `src/tensorsph/dam_break.py` — `tvc_limiter`, `tvc_limiter_slope`,")
    a("  `tvc_limiter_callable`")
    a("* `tests/test_transport_velocity_correction.py` — 9 limiter tests")
    a("* `benchmarks/xval_sphinx_tvc/limiter_leg.py`, `make_limiter_doc.py`")
    a("* `docs/xval_sphinx_tvc/data/limiter_leg.json`, "
      "`docs/xval_sphinx_tvc/oss_source/common_functors.h`")
    Path(out).write_text("\n".join(L) + "\n")
    print(f"wrote {out} and {fig}")
    return 0


if __name__ == "__main__":
    raise SystemExit(render())