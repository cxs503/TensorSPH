#!/usr/bin/env python3
"""Figure for the Rayleigh–Taylor *artifact integrity* fix (mission m16744).

Left panel: how much of the campaign the summary exposed before and after the
merge-by-tag fix — the audit state (1 row of 8 case files) against the rebuilt
summary.  Right panel: every growth-rate measurement the summary now carries,
plotted as ``sigma / sqrt(A g k)`` against particle spacing, with the declared
10 % acceptance band.  The right panel exists to make one point explicit: the
fix restores *evidence coverage*, it does not move a single number, and the
physics verdict on this case stays FAIL as the audit reported.

All numbers are read from ``runs/`` (per-case files + summary) — nothing is
typed in by hand.  The figure is regenerated by::

    PYTHONPATH=src python benchmarks/rayleigh_taylor/make_summary_integrity_figure.py
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = Path(__file__).resolve().parent
RUNS = HERE / "runs"
FIGDIR = HERE.parents[1] / "docs" / "figures" / "m16744"


def main() -> int:
    sys.path.insert(0, str(HERE))
    import summary_io  # noqa: E402

    case_files = sorted(p for p in RUNS.glob("*.json")
                        if p.stem not in summary_io.NON_CASE_STEMS)
    on_disk = summary_io.load_case_rows(RUNS)
    rows = json.loads((RUNS / "summary.json").read_text())

    # The audit state, re-derived rather than trusted: before the fix the
    # summary was written from one invocation, so it could hold at most the
    # number of cases in a single shard.  Recorded in audit_verdict_m16318.
    before_rows = 1

    FIGDIR.mkdir(parents=True, exist_ok=True)
    fig, (ax0, ax1) = plt.subplots(1, 2, figsize=(11.0, 4.3))

    # ---- left: coverage -------------------------------------------------- #
    labels = ["per-case files\non disk", "summary before\n(audit m16318)",
              "summary after\n(merge by tag)"]
    values = [len(case_files), before_rows, len(rows)]
    colors = ["#9ecae1", "#d62728", "#2ca02c"]
    bars = ax0.bar(labels, values, color=colors)
    for bar, value in zip(bars, values):
        ax0.text(bar.get_x() + bar.get_width() / 2, value + 0.15, str(value),
                 ha="center", va="bottom", fontsize=11, fontweight="bold")
    ax0.set_ylim(0, max(values) + 1.6)
    ax0.set_ylabel("case rows exposed")
    ax0.set_title("(a) campaign evidence coverage")

    # ---- right: the numbers themselves ----------------------------------- #
    ok = [r for r in rows if r["status"] == "ok"]
    bad = [r for r in rows if r["status"] != "ok"]
    pts = []
    for row in ok:
        dx = float(row["tag"].split("_")[0][2:])
        pts.append((dx, row["sigma_over_ideal"], row["tag"]))
    pts.sort()
    ax1.axhspan(0.9, 1.1, color="#2ca02c", alpha=0.12,
                label="declared 10% acceptance band")
    ax1.axhline(1.0, color="0.3", lw=1.0, ls="--", label=r"theory $\sqrt{Agk}$")
    ax1.plot([p[0] for p in pts], [p[1] for p in pts], "o-", color="#1f77b4",
             label="WCSPH growth rate (fit window 0.02-0.1 s)")
    for dx, ratio, tag in pts:
        ax1.annotate(f"{100 * (ratio - 1):+.0f}%", (dx, ratio),
                     textcoords="offset points", xytext=(6, 6), fontsize=8)
    for row in bad:
        dx = float(row["tag"].split("_")[0][2:])
        ax1.plot([dx], [0.0], marker="x", color="#d62728", ms=9,
                 label="no usable fit window (status=no_fit)")
    ax1.set_xlabel("particle spacing dx [m]")
    ax1.set_ylabel(r"$\sigma / \sqrt{Agk}$")
    ax1.set_ylim(-0.05, 1.25)
    ax1.invert_xaxis()
    ax1.set_title("(b) every row the summary now carries")
    ax1.legend(fontsize=7.5, loc="lower left")
    ax1.grid(alpha=0.25)

    fig.suptitle("CASE-SPH-RAYLEIGH-TAYLOR-MP — summary merge-by-tag: "
                 "coverage restored, numbers unchanged", fontsize=11)
    fig.tight_layout()
    out = FIGDIR / "rt_summary_integrity.png"
    fig.savefig(out, dpi=150)
    print("wrote", out)
    print("rows:", len(rows), "ok:", len(ok), "no_fit:", len(bad),
          "case files:", len(case_files))
    worst = min(pts, key=lambda p: p[1]) if pts else None
    if worst:
        print(f"worst deviation: {100 * (worst[1] - 1):+.2f}% at dx={worst[0]:g}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())