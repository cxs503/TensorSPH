"""How far from discrete equilibrium does a particle lattice start, and does it matter?

Why this benchmark exists
-------------------------
``docs/algorithm-gap-analysis.md`` carries an open P2 entry ("lattice
initialisation is not in discrete equilibrium") and ``backlog_update_m2971.md``
carries a P1 that states the offset is *universal*:

    "any wcSPH case at c0 = 20 carries 2.4 kPa of spurious initial pressure"

That number was measured on the *hexagonal* drop of
``benchmarks/laplace_pressure_floor``.  This benchmark asks the question
properly: the offset of a summation-density lattice is a purely geometric
quantity,

    rho_i/rho0 = (lattice mass) * sum_j W_ij        (self term included)

so it depends on the lattice type and on ``h/dx`` only -- not on ``c0``, not on
the case.  Measuring it over ``h/dx`` turns the constant into a curve, and the
curve shows that the production square lattice at the default ``h = 1.3 dx``
is *nearly exact* (b = -5.3e-5), while the same lattice at ``h = 1.5 dx``
carries b = +3.4e-3, i.e. 1.4 kPa of startup pressure at ``c0 = 20 m/s``.
The 2.4 kPa in the backlog is therefore not a universal property of the solver;
it is a property of the hexagonal lattice at ``h = 1.3 dx``.

What is measured
----------------
  L1  discrete kernel sum ``S`` on a square and on a hexagonal lattice, and the
      resulting offset ``b = (lattice mass) * S - 1``, over h/dx = 1.0 .. 2.0.
      ``tensorsph.lattice_kernel_sum`` is checked against the *measured* sum
      density of real particles, not against itself.
  L2  the spurious startup pressure the offset produces through the Tait law,
      ``p = B[(1+b)^gamma - 1]`` (only for b > 0; b < 0 is clamped to zero by
      the free-surface treatment), at c0 = 5 and 20 m/s.
  L3  the production case: ``make_particles`` + ``wall_lattice``, interior
      relative density and ``p_max/(rho0 c0^2)`` with the calibration off and
      on, including the m2971 acceptance ratio ``p_max/(rho0 c0^2) < 1e-4``.
  L4  a *dynamic* A/B: start from rest and take 100 steps with the offset left
      in and taken out.  Any motion at all is generated by the offset, because
      the initial velocity is exactly zero -- this answers "does it matter",
      which a t = 0 snapshot cannot.
  L5  the ``hydrostatic_init`` profile: the analytical hydrostatic mass profile
      is only correct up to the same lattice offset unless it is scaled by the
      calibrated mass unit.

Nothing here changes ``src/``; it measures what ``src/`` does.

Usage
-----
    PYTHONPATH=src python benchmarks/lattice_equilibrium/run.py
    PYTHONPATH=src python benchmarks/lattice_equilibrium/run.py --quick
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import torch

from tensorsph.droplet_impact import (
    Config,
    acoustic_courant,
    calibrated_particle_mass,
    cubic_spline_kernel,
    hydrostatic_density,
    lattice_kernel_sum,
    lattice_mass_unit,
    make_particles,
    pool_lattice,
    rhs,
    suggested_dt,
    tait_pressure,
    wall_lattice,
    wall_mass,
)
from tensorsph.neighbor_search import cell_linked_pairs

torch.set_num_threads(4)

HERE = Path(__file__).resolve().parent

DX = 0.025
RHO0 = 1000.0
GAMMA = 7.0
SOUND_SPEEDS = (20.0, 5.0)
DEFAULT_H_FACTOR = 1.3
TRAP_H_FACTOR = 1.5          # measured worst case on the square lattice
DYNAMIC_STEPS = 100


# --------------------------------------------------------------------------- #
# L1: the lattice offset
# --------------------------------------------------------------------------- #
def hexagonal_offsets(h: float, dx: float) -> torch.Tensor:
    """Offset cloud of a hexagonal lattice with row spacing ``dx sqrt(3)/2``."""
    dy = dx * math.sqrt(3.0) / 2.0
    rows = int(math.ceil(2.0 * h / dy)) + 2
    columns = int(math.ceil(2.0 * h / dx)) + 2
    pieces = []
    for row in range(-rows, rows + 1):
        x = torch.arange(-columns, columns + 1, dtype=torch.float64) * dx
        if row % 2:
            x = x + 0.5 * dx
        pieces.append(torch.stack((x, torch.full_like(x, row * dy)), dim=1))
    return torch.cat(pieces, dim=0)


def hexagonal_kernel_sum(h: float, dx: float) -> float:
    r = torch.linalg.vector_norm(hexagonal_offsets(h, dx), dim=1)
    return float(cubic_spline_kernel(r, h).sum())


def lattice_mass_hex(dx: float, rho0: float = RHO0) -> float:
    """Mass per particle of a hexagonal lattice: ``rho0 * dx * dy``."""
    return rho0 * dx * (dx * math.sqrt(3.0) / 2.0)


def bias_curve(h_factors, dx: float = DX, rho0: float = RHO0) -> list[dict]:
    rows = []
    for hf in h_factors:
        h = hf * dx
        square = dx * dx * lattice_kernel_sum(h, dx) - 1.0
        # b is dimensionless: the lattice *area* per particle times the kernel
        # sum. Dividing the lattice mass by rho0 gives that area; using the mass
        # itself would put a factor rho0 into a dimensionless offset.
        hex = (lattice_mass_hex(dx, rho0) / rho0) * hexagonal_kernel_sum(h, dx) - 1.0
        rows.append({
            "h_over_dx": hf,
            "square_bias": square,
            "hexagonal_bias": hex,
            "calibrated_mass_over_lattice_mass": (rho0 / lattice_kernel_sum(h, dx))
            / (rho0 * dx * dx),
        })
    return rows


# --------------------------------------------------------------------------- #
# L2: what the offset costs through the equation of state
# --------------------------------------------------------------------------- #
def spurious_pressure(bias: float, c0: float, rho0: float = RHO0,
                      gamma: float = GAMMA) -> float:
    """``B[(1+b)^gamma - 1]``, clamped at zero like ``tait_pressure``."""
    bulk = rho0 * c0 * c0 / gamma
    return max(0.0, bulk * ((1.0 + bias) ** gamma - 1.0))


# --------------------------------------------------------------------------- #
# L3: the production case
# --------------------------------------------------------------------------- #
def production_state(h_factor: float, c0: float, calibrated: bool,
                     hydrostatic: bool = False, dx: float = DX,
                     rho0: float = RHO0, gamma: float = GAMMA):
    """Density and pressure of ``make_particles`` + ``wall_lattice`` at t = 0."""
    cfg = Config(dx=dx, h_factor=h_factor, rho0=rho0, gamma=gamma,
                 sound_speed=c0, density_calibration=calibrated,
                 hydrostatic_init=hydrostatic)
    device = torch.device("cpu")
    pos, mass = make_particles(cfg, device)
    wall = wall_lattice(cfg, device)
    n = pos.shape[0]
    h = cfg.h_factor * cfg.dx
    all_pos = torch.cat((pos, wall), dim=0)
    all_mass = torch.cat((mass, wall_mass(cfg, wall.shape[0], device)), dim=0)
    pairs = cell_linked_pairs(all_pos, 2.0 * h)

    rho_all = all_mass * cubic_spline_kernel(torch.zeros(all_pos.shape[0]), h)
    i, j = pairs.unbind(dim=1)
    d = torch.linalg.vector_norm(all_pos[i] - all_pos[j], dim=1)
    w = cubic_spline_kernel(d, h)
    rho_all = rho_all.index_add(0, i, all_mass[j] * w)
    rho_all = rho_all.index_add(0, j, all_mass[i] * w)
    rho = rho_all[:n]
    pressure = tait_pressure(rho, cfg)

    x, y = pos[:, 0], pos[:, 1]
    interior = ((y > 0.05) & (y < cfg.pool_depth - 0.08)
                & (x > 0.05) & (x < cfg.pool_width - 0.05))
    rel = rho[interior] / cfg.rho0 - 1.0
    return {
        "h_over_dx": h_factor, "sound_speed": c0, "calibrated": calibrated,
        "hydrostatic_init": hydrostatic, "n_fluid": int(n),
        "mass_unit": float(mass[0]),
        "mass_unit_uncorrected": cfg.rho0 * cfg.dx * cfg.dx,
        "interior_rel_density_mean": float(rel.mean()),
        "interior_rel_density_max_abs": float(rel.abs().max()),
        "p_max_Pa": float(pressure.max()),
        "p_max_over_rho0c02": float(pressure.max()) / (cfg.rho0 * c0 * c0),
        "passes_1e-4": float(pressure.max()) / (cfg.rho0 * c0 * c0) < 1.0e-4,
    }


# --------------------------------------------------------------------------- #
# L4: does the offset move the fluid?
# --------------------------------------------------------------------------- #
def dynamic_ab(h_factor: float, c0: float, calibrated: bool, steps: int,
               dx: float = DX):
    """Resting pool, zero gravity: every metre per second of motion is an artefact.

    The impact case cannot answer "does the offset matter", because the drop is
    in free fall and the pool sloshes whatever the lattice does.  With
    ``gravity = 0`` and no surface tension, a pool at rest has exactly one
    possible force: the pressure gradient generated by the density offset, so
    any motion at all is the artefact being measured.
    """
    cfg = Config(dx=dx, h_factor=h_factor, sound_speed=c0,
                 density_calibration=calibrated, gravity=0.0)
    device = torch.device("cpu")
    pos = pool_lattice(cfg, device)
    mass = torch.full((pos.shape[0],), lattice_mass_unit(cfg), device=device)
    wall = wall_lattice(cfg, device)
    vel = torch.zeros_like(pos)
    dt = float(suggested_dt(cfg))
    h = cfg.h_factor * cfg.dx
    v_max, hard = 0.0, 0.0
    p_max = 0.0
    for _ in range(steps):
        pairs = cell_linked_pairs(torch.cat((pos, wall), dim=0), 2.0 * h)
        rho, pressure, acc = rhs(pos, vel, mass, cfg, pairs=pairs, wall=wall,
                                 dt=dt)
        vel = vel + dt * acc
        pos = pos + dt * vel
        v_max = max(v_max, float(torch.linalg.vector_norm(vel, dim=1).max()))
        hard = max(hard, float((rho / cfg.rho0 - 1.0).abs().max()))
        p_max = max(p_max, float(pressure.max()))
    return {
        "h_over_dx": h_factor, "sound_speed": c0, "calibrated": calibrated,
        "steps": steps, "dt_s": dt,
        "courant": acoustic_courant(dt, cfg),
        "v_max_m_per_s": v_max,
        "density_error_max": hard,
        "p_max_Pa": p_max,
        "p_max_over_rho0c02": p_max / (cfg.rho0 * c0 * c0),
        "kinetic_energy_density_J_per_m3": 0.5 * cfg.rho0 * v_max ** 2,
        "finite": bool(torch.isfinite(pos).all() and torch.isfinite(vel).all()),
    }


# --------------------------------------------------------------------------- #
# L5: hydrostatic initialisation
# --------------------------------------------------------------------------- #
def hydrostatic_profile_error(h_factor: float, calibrated: bool, c0: float = 20.0,
                              dx: float = DX):
    """t = 0 vertical profile error of ``hydrostatic_init`` against Tait hydrostatics."""
    cfg = Config(dx=dx, h_factor=h_factor, sound_speed=c0,
                 density_calibration=calibrated, hydrostatic_init=True)
    device = torch.device("cpu")
    pos, mass = make_particles(cfg, device)
    wall = wall_lattice(cfg, device)
    n = pos.shape[0]
    h = cfg.h_factor * cfg.dx
    all_pos = torch.cat((pos, wall), dim=0)
    all_mass = torch.cat((mass, wall_mass(cfg, wall.shape[0], device)), dim=0)
    pairs = cell_linked_pairs(all_pos, 2.0 * h)
    rho_all = all_mass * cubic_spline_kernel(torch.zeros(all_pos.shape[0]), h)
    i, j = pairs.unbind(dim=1)
    d = torch.linalg.vector_norm(all_pos[i] - all_pos[j], dim=1)
    w = cubic_spline_kernel(d, h)
    rho_all = rho_all.index_add(0, i, all_mass[j] * w)
    rho_all = rho_all.index_add(0, j, all_mass[i] * w)
    rho = rho_all[:n]

    x, y = pos[:, 0], pos[:, 1]
    interior = ((y > 0.05) & (y < cfg.pool_depth - 0.08)
                & (x > 0.05) & (x < cfg.pool_width - 0.05))
    target = hydrostatic_density(y[interior], cfg)
    err = rho[interior] / target - 1.0
    return {
        "calibrated": calibrated, "sound_speed": c0,
        "n_interior": int(interior.sum()),
        "rel_error_mean": float(err.mean()),
        "rel_error_max_abs": float(err.abs().max()),
        "rel_error_rms": float(torch.sqrt(err.square().mean())),
    }


# --------------------------------------------------------------------------- #
# figure
# --------------------------------------------------------------------------- #
def make_figures(report: dict) -> dict:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    curve = report["bias_curve"]
    hf = [row["h_over_dx"] for row in curve]
    fig, axes = plt.subplots(1, 3, figsize=(15.5, 4.4))

    ax = axes[0]
    ax.semilogy(hf, [abs(row["square_bias"]) for row in curve], "o-",
                label="square lattice (production)")
    ax.semilogy(hf, [abs(row["hexagonal_bias"]) for row in curve], "s-",
                label="hexagonal lattice (B3 drop)")
    ax.axvline(DEFAULT_H_FACTOR, color="k", ls=":", lw=1)
    ax.annotate("default h/dx = 1.3", (DEFAULT_H_FACTOR, 2e-3), rotation=90,
                fontsize=8, ha="right")
    ax.set_xlabel("h / dx")
    ax.set_ylabel("| b | = | lattice mass * sum_j W - 1 |")
    ax.set_title("L1  discrete kernel-sum offset")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=8)

    ax = axes[1]
    ax.plot(hf, [spurious_pressure(row["square_bias"], 20.0) for row in curve],
            "o-", label="square, c0 = 20 m/s")
    ax.plot(hf, [spurious_pressure(row["hexagonal_bias"], 20.0) for row in curve],
            "s-", label="hexagonal, c0 = 20 m/s")
    ax.plot(hf, [spurious_pressure(row["square_bias"], 5.0) for row in curve],
            "o--", lw=1, label="square, c0 = 5 m/s")
    ax.axhline(360.0, color="tab:red", ls="--", lw=1)
    ax.annotate("sigma/R = 360 Pa (R = 20 mm drop)", (1.02, 380), color="tab:red",
                fontsize=8)
    ax.set_xlabel("h / dx")
    ax.set_ylabel("spurious startup pressure [Pa]")
    ax.set_title("L2  offset converted by Tait (c0 = 20 m/s)")
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=8)

    ax = axes[2]
    labels, values = [], []
    for run in report["production"]:
        labels.append(f"h={run['h_over_dx']:g}\n"
                      f"{'cal' if run['calibrated'] else 'raw'}")
        values.append(run["p_max_over_rho0c02"])
    colors = ["tab:gray" if "raw" in lab else "tab:green" for lab in labels]
    ax.bar(range(len(values)), values, color=colors)
    ax.set_yscale("log")
    ax.set_xticks(range(len(values)))
    ax.set_xticklabels(labels, fontsize=7)
    ax.axhline(1e-4, color="tab:red", ls="--", lw=1)
    ax.annotate("m2971 acceptance 1e-4", (0, 1.3e-4), color="tab:red", fontsize=8)
    ax.set_ylabel("p_max / (rho0 c0^2) at t = 0")
    ax.set_title("L3  production lattice, interior pressure")
    ax.grid(True, axis="y", alpha=0.3)

    fig.tight_layout()
    path = HERE / "lattice_equilibrium.png"
    fig.savefig(path, dpi=130)
    plt.close(fig)
    return {"name": "lattice_equilibrium.png",
            "caption": "L1 offset vs h/dx for both lattices; L2 its Tait "
                       "conversion at c0 = 20 m/s against sigma/R = 360 Pa; "
                       "L3 p_max/(rho0 c0^2) of the production case at t = 0."}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--steps", type=int, default=DYNAMIC_STEPS)
    args = ap.parse_args()

    h_factors = ([1.0, 1.2, DEFAULT_H_FACTOR, 1.4, TRAP_H_FACTOR, 1.6]
                 if args.quick else
                 [round(1.0 + 0.05 * k, 2) for k in range(21)])
    curve = bias_curve(h_factors)

    production = []
    for hf in (DEFAULT_H_FACTOR, TRAP_H_FACTOR):
        for c0 in SOUND_SPEEDS:
            for calibrated in (False, True):
                run = production_state(hf, c0, calibrated)
                production.append(run)
                print(f"L3 h={hf:g} c0={c0:5g} cal={calibrated!s:5}: "
                      f"rel_rho {run['interior_rel_density_mean']:+.3e}  "
                      f"p_max {run['p_max_Pa']:9.2f} Pa  "
                      f"p/(rho0c0^2) {run['p_max_over_rho0c02']:.3e}", flush=True)

    dynamic = []
    steps = 30 if args.quick else args.steps
    for hf in (DEFAULT_H_FACTOR, TRAP_H_FACTOR):
        for calibrated in (False, True):
            run = dynamic_ab(hf, 20.0, calibrated, steps)
            dynamic.append(run)
            print(f"L4 h={hf:g} cal={calibrated!s:5}: "
                  f"v_max {run['v_max_m_per_s']:.5f} m/s  "
                  f"density_err {run['density_error_max']:.4e}  "
                  f"p_max {run['p_max_Pa']:9.2f} Pa", flush=True)

    hydro = [hydrostatic_profile_error(DEFAULT_H_FACTOR, calibrated)
             for calibrated in (False, True)]
    for row in hydro:
        print(f"L5 cal={row['calibrated']!s:5}: t=0 hydrostatic profile "
              f"rms {row['rel_error_rms']:.3e}", flush=True)

    report = {
        "benchmark": "lattice_equilibrium",
        "reference": {"dx_m": DX, "rho0": RHO0, "gamma": GAMMA,
                      "default_h_factor": DEFAULT_H_FACTOR,
                      "trap_h_factor": TRAP_H_FACTOR,
                      "sigma_over_R_Pa": 360.0,
                      "acceptance_ratio": 1.0e-4},
        "bias_curve": curve,
        "production": production,
        "dynamic": dynamic,
        "hydrostatic_profile": hydro,
        "calibration_helpers": {
            "square_bias_at_default": bias_curve([DEFAULT_H_FACTOR])[0]["square_bias"],
            "hexagonal_bias_at_default": bias_curve([DEFAULT_H_FACTOR])[0]["hexagonal_bias"],
            "calibrated_particle_mass": calibrated_particle_mass(
                Config(dx=DX, h_factor=DEFAULT_H_FACTOR)),
            "uncorrected_mass": RHO0 * DX * DX,
        },
    }
    (HERE / "report.json").write_text(json.dumps(report, indent=1))
    report["figures"] = [make_figures(report)]
    (HERE / "report.json").write_text(json.dumps(report, indent=1))
    print("wrote", HERE / "report.json", report["figures"])


if __name__ == "__main__":
    main()
