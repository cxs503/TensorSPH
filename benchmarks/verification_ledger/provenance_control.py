"""Provenance and resolution control for the one sub-15 % Laplace reading.

Context
-------
The verification ledger (``ledger.py``) finds exactly one Δp reading in the
whole repository that clears the 15 % gate while crossing a one-sided free
surface: ``laplace_law#relaxed#0``, quoted as ``+5.60 %``.  Before that number
may be quoted as evidence that the free-surface pressure closure works, three
questions have to be answered, and this module answers all three from the
family's *own* code path (``benchmarks/laplace_law/run.py::relax``):

1. **Is the committed artefact reproducible?**  ``run.py`` emits
   ``{"instant": [...], "relax": {...}}``; the committed report has
   ``setup/reference/laplace/history`` at ``dx = 0.004`` and 380 steps, i.e. a
   summary written by an older code state.  Re-running at those exact
   settings gives a different number (``+8.17 %``), so the committed value is
   stale, not wrong-by-rounding.
2. **Is the reading produced by surface tension at all, or is it the
   un-decayed initialisation pressure?**  Controlled by setting sigma -> 0
   (1e-9 N/m) with everything else identical.  The initialisation residue
   (2395 Pa at t=0, audit C2 in ``backlog_update_m2971.md``) decays to exactly
   0 Pa within 50 steps when sigma ~ 0, while the sigma = 7.2 N/m case sustains
   a non-zero core pressure: the reading is genuinely generated by the CSF
   force, not a numerical leftover.
3. **Is it resolution-stable?**  Refining R/dx from 5 to 10 with the same
   code path, same instant convention and the same physical time flips the
   reading to ``-105 %``: at the finer resolution the upper band is no longer
   clamped at zero pressure, so ``p_core - p_band`` subtracts the signal away.
   The "passing" reading is therefore an artefact of a degenerate operand, and
   the convention it belongs to (``center_minus_band_instant``) is retired.

Usage::

    # rebuild provenance_control.json from the recorded run snapshots
    python benchmarks/verification_ledger/provenance_control.py --from-snapshots

    # re-execute the three cases from scratch (~3 min at 128 cores when idle,
    # noticeably slower under load; each case is a few hundred particles)
    python benchmarks/verification_ledger/provenance_control.py --run --only sigma7_rdx5
    python benchmarks/verification_ledger/provenance_control.py --run --only sigma0_rdx5
    python benchmarks/verification_ledger/provenance_control.py --run --only sigma7_rdx10

Raw snapshots produced by ``--run`` live next to this file and are kept as
provenance; the normalised ``provenance_control.json`` is what the ledger and
the tests read.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path
from typing import Any, Dict

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = HERE / "provenance_control.json"
RUN_PY = ROOT / "benchmarks" / "laplace_law" / "run.py"

# case id -> (sigma [N/m], dx [m], steps)
CASES: Dict[str, Dict[str, Any]] = {
    "sigma7_rdx5": dict(sigma=7.2, dx=0.004, steps=380,
                        question="committed artefact's own settings (R/dx = 5)"),
    "sigma7_rdx10": dict(sigma=7.2, dx=0.002, steps=380,
                         question="same code path and time, one refinement step (R/dx = 10)"),
    "sigma0_rdx5": dict(sigma=1e-9, dx=0.004, steps=380,
                        question="sigma -> 0 control: is the reading surface-tension generated?"),
}
RADIUS = 0.02
RHO0 = 1000.0
SOUND_SPEED = 20.0
VISCOSITY = 0.01
SIGMA_REF = 7.2  # N/m, the reference surface tension of this family


def _load_run_module():
    spec = importlib.util.spec_from_file_location("laplace_law_run", RUN_PY)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _normalise(case_id: str, raw: Dict[str, Any]) -> Dict[str, Any]:
    """Reduce a raw ``relax()`` output (or snapshot) to the ledger's schema."""
    lap = raw["laplace"]
    setup = raw.get("setup") or {}
    hist = raw.get("history") or {}
    dx = float(setup.get("dx_m", CASES[case_id]["dx"]))
    return dict(
        question=CASES[case_id]["question"],
        dx_m=dx,
        radius_m=RADIUS,
        R_over_dx=round(RADIUS / dx, 3),
        sigma_N_per_m=CASES[case_id]["sigma"],
        steps=int(setup.get("steps", CASES[case_id]["steps"])),
        n_particles=setup.get("n_particles"),
        t_over_t_sigma=round(float(setup.get("t_over_t_sigma", float("nan"))), 4),
        p_core_Pa=round(float(lap["p_center_Pa"]), 4),
        p_band_Pa=round(float(lap["p_interface_band_Pa"]), 4),
        dp_measured_Pa=round(float(lap["delta_p_measured_Pa"]), 4),
        dp_theory_Pa=round(float(lap["delta_p_theory_Pa"]), 4),
        rel_error_pct=round(float(lap["rel_error_pct"]), 4),
        within_15pct=bool(lap["within_15pct"]),
        density_compression_at_center=round(
            float(lap["density_compression_at_center"]), 8),
        p_core_trace_Pa=[round(float(x), 2) for x in hist.get("p_center", [])],
        t_trace_s=[round(float(x), 6) for x in hist.get("t", [])],
    )


def run_case(case_id: str) -> Dict[str, Any]:
    mod = _load_run_module()
    spec = CASES[case_id]
    raw = mod.relax(radius=RADIUS, dx=spec["dx"], sigma=spec["sigma"], rho0=RHO0,
                    sound_speed=SOUND_SPEED, steps=spec["steps"],
                    viscosity=VISCOSITY)
    snapshot = HERE / f"snapshot_{case_id}.json"
    snapshot.write_text(json.dumps(raw, indent=1), encoding="utf-8")
    return _normalise(case_id, raw)


def _merge(case_id: str, record: Dict[str, Any]) -> None:
    payload = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else {
        "description": "provenance and resolution control for laplace_law#relaxed#0",
        "code_path": "benchmarks/laplace_law/run.py::relax",
        "cases": {},
    }
    payload["cases"][case_id] = record
    payload["cases"] = dict(sorted(payload["cases"].items()))
    payload["sigma_reference_N_per_m"] = SIGMA_REF
    OUT.write_text(json.dumps(payload, indent=1, sort_keys=False) + "\n",
                   encoding="utf-8")


def from_snapshots() -> None:
    """Normalise the recorded raw snapshots without re-running the solver."""
    mapping = {
        "sigma7_rdx5": HERE / "snapshot_sigma_pair_rdx5.json",
        "sigma0_rdx5": HERE / "snapshot_sigma_pair_rdx5.json",
        "sigma7_rdx10": HERE / "snapshot_sigma7_rdx10.json",
    }
    for case_id, path in mapping.items():
        if not path.exists():
            raise SystemExit(f"missing snapshot {path}")
        data = json.loads(path.read_text(encoding="utf-8"))
        if case_id == "sigma7_rdx5":
            raw = dict(laplace=data["7.2"]["laplace"], setup={}, history=data["7.2"])
            raw["setup"] = dict(dx_m=0.004, steps=380,
                                n_particles=88,
                                t_over_t_sigma=0.8892)
        elif case_id == "sigma0_rdx5":
            raw = dict(laplace=data["1e-09"]["laplace"], setup={},
                       history=data["1e-09"])
            raw["setup"] = dict(dx_m=0.004, steps=380, n_particles=88,
                                t_over_t_sigma=0.8892)
        else:
            raw = dict(laplace=data["d"], setup={}, history={})
            raw["setup"] = dict(dx_m=0.002, steps=380, n_particles=362,
                                t_over_t_sigma=0.8892)
            raw["laplace"] = dict(raw["laplace"],
                                 p_center_Pa=data["d"]["p_center_Pa"],
                                 p_interface_band_Pa=data["d"]["p_interface_band_Pa"],
                                 delta_p_measured_Pa=data["d"]["delta_p_measured_Pa"],
                                 delta_p_theory_Pa=data["d"]["delta_p_theory_Pa"],
                                 rel_error_pct=data["d"]["rel_error_pct"],
                                 within_15pct=data["d"]["within_15pct"],
                                 density_compression_at_center=data["d"]["density_compression_at_center"])
        _merge(case_id, _normalise(case_id, raw))
    print(f"wrote {OUT.relative_to(ROOT)} from recorded snapshots")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", action="store_true", help="execute the cases")
    parser.add_argument("--only", choices=sorted(CASES), default=None)
    parser.add_argument("--from-snapshots", action="store_true",
                        help="normalise recorded snapshots without re-running")
    args = parser.parse_args(argv)

    if args.from_snapshots:
        from_snapshots()
        return 0
    if not args.run:
        parser.error("choose --run or --from-snapshots")
    for case_id in ([args.only] if args.only else list(CASES)):
        record = run_case(case_id)
        _merge(case_id, record)
        print(f"{case_id}: dp={record['dp_measured_Pa']:.1f} Pa "
              f"rel={record['rel_error_pct']:+.2f}% (R/dx={record['R_over_dx']:g})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
