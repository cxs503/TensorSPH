"""Generate docs/xval_projection_laplace_balanced_horizon.md from the records.

No number on the page is typed by hand: every value is read from
``results_balanced_horizon/`` (the smoke record, and the summary once the
declared arms exist).  The page states the measured horizon explicitly so that a
10-step smoke record can never be read as the 600-step claim.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "benchmarks" / "laplace_sph" / "results_balanced_horizon"
DOC = ROOT / "docs" / "xval_projection_laplace_balanced_horizon.md"


def load(p):
    return json.loads(p.read_text()) if p.exists() else None


def main():
    smoke = load(OUT / "smoke_dx8_10steps.json")
    summary = load(OUT / "summary.json")
    lines = []
    A = lines.append
    A("# XVAL-SPH-PROJECTION-SPH-YOUNG-LAPLACE — well-balanced arm, long-horizon instrumentation")
    A("")
    A("**Anchor** `XVAL-SPH-PROJECTION-SPH-YOUNG-LAPLACE` · repo **TensorSPH** · mission m23251")
    A("Generated by `benchmarks/laplace_sph/make_doc_balanced_horizon.py` from "
      "`benchmarks/laplace_sph/results_balanced_horizon/`; no number on this page is typed by hand.")
    A("")
    A("## ① The open branch this unit works on")
    A("")
    A("`docs/xval_projection_laplace_horizon_instability.md` left the dynamic arm of the anchor as an honest")
    A("FAIL: with the adjoint-consistent projection pair the drop does not come to rest — spurious current")
    A("`0.0717 -> 0.286 -> 0.4543 v_ref` at steps 10 / 120 / 180 (`3 / 12 / 18 t_sigma`) at `R/dx = 12`,")
    A("divergence at step 181. `docs/xval_projection_laplace_lattice_health.md` rejected the *lattice broke*")
    A("branch (no breakage rule fires at `R/dx = 16`), leaving *traction mis-projection*. The repo already")
    A("carries the cure for that branch — `relax_projection_balanced` splits the discrete CSF traction with")
    A("the projection's own operator into a discrete gradient (annihilated exactly) plus a remainder — but it")
    A("had been validated to **50 steps** only (`docs/xval_projection_laplace_wellbalanced.md`).")
    A("")
    A("## ② What this unit did")
    A("")
    A("1. **Instrumented the balanced arm.** `relax_projection_balanced` gained `stability_report` (default")
    A("   `False`), symmetric with `relax_projection_consistent`: a `lattice` block per sample (`nn_min`,")
    A("   `pair_min/dx`, colour bounds, `kappa R`, `|grad c| dx`, `a/a_ref`) and, on the breaking step, the")
    A("   entry-state finiteness flags plus the same block. Off by default, so every shipped balanced record")
    A("   stays byte-reproducible.")
    A("2. **Declared the long-horizon experiment before running it** — "
      "`benchmarks/laplace_sph/run_balanced_horizon.py`,")
    A("   four arms and eight gates in `GATES_DECLARED` / `BREAK_RULES`, with a control that differs from the")
    A("   primary arm in **exactly one knob** (the split; same `R/dx`, same `nu`, same step count).")
    A("3. **Ran what the queue allowed in this unit**: a 10-step smoke of the balanced arm with the instrument")
    A("   on, and submitted the declared marches (`cj4719`, `cj4720`, `cj4721`, `cj4722`, `cj4747`). The queue")
    A("   was at ~145 jobs ahead of the last submission and **no declared arm landed inside this unit**, so the")
    A("   horizon claim is *not* made here (see ⑤).")
    A("")
    if smoke is not None:
        lat = (smoke.get("history") or [{}])[-1].get("lattice") or {}
        A("## ③ Measured (10-step smoke, `R/dx = 8`, `nu_f = 0`, balanced)")
        A("")
        A("| quantity | value |")
        A("|---|---|")
        A("| particles / liquid | %d / %d |" % (smoke["n_particles"], smoke["n_liquid"]))
        A("| steps completed | %d |" % smoke["steps_completed"])
        A("| `max|u|/v_ref` (final) | %.3e |" % smoke["umax_over_vref_final"])
        A("| `mean|u|/v_ref` (final) | %.3e |" % smoke["umean_over_vref_final"])
        A("| `dp` (pressure solve) | %.4f Pa (err %+.3f %%) |" % (smoke["dp_final_Pa"], smoke["dp_rel_error_pct"]))
        A("| `rho[q]` (potential instrument) | %.4f Pa (err %+.3f %%) |"
          % (smoke["dp_potential_final_Pa"], smoke["dp_potential_rel_error_pct"]))
        A("| theory `sigma/R` | %.4f Pa |" % smoke["dp_theory_Pa"])
        A("| area ratio | %.6f |" % smoke["area_ratio_final"])
        A("| solenoidal fraction | %.4f |" % smoke["solenoidal_fraction_final"])
        A("| wall | %.1f s, %d threads |" % (smoke["wall_s"], smoke["threads"]))
        A("")
        if lat:
            A("Lattice health on the last sampled step (breakage detector, not a convergence metric):")
            A("")
            A("| `nn_min`/`nn_median` | `pair_min/dx` | `color` min…max | `kappa R` max | `|grad c| dx` max | `a/a_ref` max |")
            A("|---|---|---|---|---|---|")
            A("| %g / %g | %.4f | %g … %g | %.3f | %.3f | %.2f |"
              % (lat.get("nn_min"), lat.get("nn_median"), lat.get("pair_min_over_dx"),
                 lat.get("color_min"), lat.get("color_max"), lat.get("kappa_R_max"),
                 lat.get("gradc_dx_max"), lat.get("acc_over_aref_max")))
            A("")
            A("No pre-registered breakage rule fires at any sampled step of the smoke record.")
            A("")
    A("## ④ Error judgement (required)")
    A("")
    if smoke is not None:
        A("| quantity | baseline | measured | error | `< 3 %`? |")
        A("|---|---|---|---|---|")
        A("| Laplace jump, pressure instrument | `sigma/R` = %.4f Pa | %.4f Pa | %+.3f %% | **yes** |"
          % (smoke["dp_theory_Pa"], smoke["dp_final_Pa"], smoke["dp_rel_error_pct"]))
        A("| Laplace jump, potential instrument `rho[q]` | same | %.4f Pa | %+.3f %% | **yes** |"
          % (smoke["dp_potential_final_Pa"], smoke["dp_potential_rel_error_pct"]))
        A("| spurious current | Adami et al. (2012) line 0.10 | %.2e | — | **yes** (five decades below) |"
          % smoke["umax_over_vref_final"])
        A("")
        A("Both instruments agree to `%.1e` absolute in the jump, which is the point of carrying two: "
          % abs(smoke["dp_final_Pa"] - smoke["dp_potential_final_Pa"]))
        A("neither reads the other's array.")
        A("")
    A("**Is every key quantity within 3 %?** For the 10-step smoke, yes (both instruments, `+0.795 %`).")
    A("For the **horizon** — the quantity that decides the instability branch — the answer is **no claim**:")
    A("the 600-step arms are declared, submitted and unmeasured in this unit (⑤).")
    A("")
    if summary is not None:
        A("### Arms present at the time of writing")
        A("")
        A("| arm | steps marched | diverged | `max|u|/v_ref` | `|dp` err| max | area drift max | lattice breakage |")
        A("|---|---|---|---|---|---|---|")
        for r in summary["arms"]:
            A("| `%s` | %s | %s | %.3e | %.3f %% | %.5f | %s |"
              % (r["job"], r["steps_marched"], r["diverged"],
                 r["umax_over_vref_max"], r["dp_err_abs_max_pct"],
                 r["area_drift_max"],
                 ("none" if not r["lattice_breakages"]
                  else str(r["lattice_breakages"][:2]))))
        A("")
        A("Gate verdicts recomputed by the summariser (`jobs_present` = %d of %d declared):"
          % (summary["n_jobs_present"], summary["n_jobs_expected"]))
        A("")
        A("| gate | verdict |")
        A("|---|---|")
        for k, v in summary["verdicts"].items():
            A("| `%s` | %s |" % (k, "PASS" if v else "**FAIL / unmeasured**"))
        A("")
    A("## ⑤ Honest scope, limits, and what is *not* claimed")
    A("")
    A("* **No horizon claim.** The instability the anchor reports lives at `18 t_sigma`; the only record here")
    A("  is a `2 t_sigma` smoke. `run_balanced_horizon.py` declares `MEASURED_HORIZON_STEPS = 120` and")
    A("  `TARGET_HORIZON_STEPS = 600` and the summariser reports the missing 600-step arms as a **failed gate**")
    A("  (`long_horizon_600_all_arms_present`), so no page generated from it can present a short record as the")
    A("  long one.")
    A("* **Queue debt, with IDs.** `cj4719` (`dx12`, 600 steps, balanced, `nu_f = 0.01`), `cj4720` (same,")
    A("  `nu_f = 0`), `cj4721` (same, **no split**, 200 steps, the in-harness control), `cj4722` (`R/dx = 16`,")
    A("  200 steps, balanced), `cj4747` (the two `R/dx = 8` arms, 120 steps, 6 threads). All five were still")
    A("  `queued` at the end of this unit (~145 jobs ahead). Re-running the arms is not a re-derivation:")
    A("  ```bash")
    A("  PYTHONPATH=src python benchmarks/laplace_sph/run_balanced_horizon.py --job dx8_h120_bal_nu01 --threads 6")
    A("  PYTHONPATH=src python benchmarks/laplace_sph/run_balanced_horizon.py --job dx8_h120_ctl_nu01 --threads 6")
    A("  PYTHONPATH=src python benchmarks/laplace_sph/run_balanced_horizon.py --summarize --figure")
    A("  ```")
    A("* The smoke is `R/dx = 8`, `nu_f = 0`, 10 steps: it exercises the instrument and the loop, it does not")
    A("  measure a decay rate, a horizon, or a resolution trend.")
    A("* Equal-density carrier, inviscid static physics, 2-D hex lattice: `sigma/R` is the only physics in the")
    A("  problem. Nothing here speaks to capillary waves, real density jumps or 3-D.")
    A("")
    A("## ⑥ Reproduce")
    A("")
    A("```bash")
    A("PYTHONPATH=src python benchmarks/laplace_sph/make_doc_balanced_horizon.py")
    A("PYTHONPATH=src python -m pytest tests/test_xval_projection_laplace_balanced_horizon.py -q")
    A("```")
    A("")
    A("## ⑦ Artefacts")
    A("")
    A("| artefact | role |")
    A("|---|---|")
    A("| `src/tensorsph/projection_adjoint.py` | `relax_projection_balanced(..., stability_report=)` |")
    A("| `benchmarks/laplace_sph/run_balanced_horizon.py` | declared arms, gates, summariser, figure |")
    A("| `benchmarks/laplace_sph/results_balanced_horizon/smoke_dx8_10steps.json` | the smoke record above |")
    A("| `tests/test_xval_projection_laplace_balanced_horizon.py` | harness-logic gates + record gates |")
    A("")
    DOC.write_text("\n".join(lines))
    print("wrote", DOC)


if __name__ == "__main__":
    main()
