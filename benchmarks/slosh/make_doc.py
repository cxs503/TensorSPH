"""Generate ``docs/benchmarks/slosh.md`` from ``benchmarks/slosh/results.json``.

Every number in the document is injected from the JSON that the benchmark wrote,
so the document cannot drift from the run it describes; the prose is fixed here
on purpose.  Run after ``benchmarks/slosh/run.py``::

    PYTHONPATH=src python benchmarks/slosh/make_doc.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DOCS = HERE.parents[1] / "docs" / "benchmarks" / "slosh.md"


def fmt(value, digits=3, suffix=""):
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int,)):
        return f"{value}{suffix}"
    try:
        if value != value:  # NaN
            return "—"
    except TypeError:
        return str(value)
    return f"{value:.{digits}f}{suffix}"


def main() -> None:
    data = json.loads((HERE / "results.json").read_text())
    cfg = data["config"]
    cases = data["cases"]
    gate = data["gate"]
    lines: list[str] = []
    add = lines.append

    add("# Benchmark B5: standing gravity-wave (sloshing) dispersion")
    add("")
    add("*Generated by `benchmarks/slosh/make_doc.py` from `results.json`; "
        "every number below is injected, none is typed by hand.*")
    add("")
    add(f"**Gate:** {gate['n_cases']} cases, {gate['n_failed']} outside "
        f"{data['tolerance_pct']:.0f} %, {gate['n_within_3pct']} inside "
        f"{data['target_pct']:.0f} % — **{gate['result'].upper()}**.")
    add("")

    # ------------------------------------------------------------------ 1
    add("## 1. Case: why this benchmark exists")
    add("")
    add("The other benchmarks in this repository score a static balance, a steady")
    add("flow, or a transient without an analytic reference. None of them measures")
    add("whether the free surface oscillates at the frequency potential-flow theory")
    add("predicts, which is the property seakeeping and tank-sloshing work depends")
    add("on first. This benchmark closes that gap with a closed rectangular tank")
    add("started in a single standing mode.")
    add("")
    add("| quantity | value |")
    add("|---|---|")
    add(f"| tank length `L` | {fmt(cfg['length_m'])} m |")
    add(f"| still-water depth `H` | {fmt(cfg['depth_m'])} m |")
    add(f"| initial amplitude `A` | {fmt(cfg['amplitude_ratio'] * cfg['depth_m'], 4)} m"
        f" (`A/H` = {fmt(cfg['amplitude_ratio'], 2)}) |")
    add(f"| modes` n` | 1 and 2, `k_n = n pi / L` |")
    add(f"| spacing `dx` | {', '.join(sorted({fmt(c['dx_m'], 4) for c in cases}))} m |")
    add(f"| sound speed `c0` | {fmt(cfg['sound_speed'], 1)} m/s |")
    add(f"| viscosity `nu` | {fmt(cfg['viscosity'], 3)} (inviscid reference) |")
    add("| wall friction / density diffusion | 0 / 0 |")
    add(f"| simulated time | {fmt(cfg['periods'], 1)} periods of each mode |")
    add("")
    add("Analytic reference (linear theory, inviscid, irrotational):")
    add("")
    add("```")
    add("omega_n^2 = g k_n tanh(k_n H),    k_n = n pi / L")
    add("```")
    add("")
    add("Lamb (1932) *Hydrodynamics* Art. 231; Abramson (1966) NASA SP-106 eq. 2-9;")
    add("Faltinsen & Timokha (2009) *Sloshing* eq. 4.3. The initial condition is the")
    add("mode shape `eta_0(x) = A cos(k_n x)` with each column's mass from the")
    add("analytic hydrostatic profile of that column, so the run starts from a")
    add("discrete equilibrium of the perturbed surface instead of free fall.")
    add("")

    # ------------------------------------------------------------------ 2
    add("## 2. Method")
    add("")
    add("**Elevation, primary estimator — column volume.** Vertical integration is")
    add("exact and only the horizontal direction is smoothed:")
    add("")
    add("```")
    add("h(x_p) = sum_j V_j G_sigma(x_p - x_j),   V_j = m_j / rho_j,")
    add("eta(x_p) = h(x_p) - H,                   sigma = 1.2 dx")
    add("```")
    add("")
    add("Reading the elevation as `max(y)` in a bin would quantise it to `dx`; the")
    add("2-D kernel level set `c = 1/2` is computed on the same instant as an")
    add("independent cross-check. The Gaussian attenuates a mode of wavenumber `k`")
    add("by `exp(-(sigma k)^2 / 2)`; that factor is divided out (0.4 % for mode 1).")
    add("")
    add("**Modal coordinate.** `q_n(t) = (2/L) int_0^L eta cos(k_n x) dx`, i.e. the")
    add("quantity the analytic solution predicts to be a pure sinusoid.")
    add("")
    add("**Frequency.** Least-squares scan: fit `a cos(omega t) + b sin(omega t) + c`")
    add("on a 601-point grid of `omega` inside `+/-40 %` of the analytic value and")
    add("report the residual minimiser, with `R^2` and an `at_scan_edge` flag. A raw")
    add("FFT peak is limited by the window to `1/T` and would be coarser than the")
    add("acceptance band. The estimator is calibrated on synthetic sinusoids in")
    add("`tests/test_slosh.py`.")
    add("")
    add("**Integration.** Verlet neighbour cache (`pair_skin_factor = 0.25`),")
    add("three-layer static walls with Adami et al. (2012) pressure, acoustic Courant")
    add("0.25, single-threaded CPU (small SPH tensors are 17x faster that way).")
    add("")

    # ------------------------------------------------------------------ 3
    add("## 3. Results")
    add("")
    add("| mode | `dx` [m] | layers | particles | steps | `omega` measured [rad/s] "
        "| `omega` analytic [rad/s] | error | `R^2` | amp. ratio | damping [1/s] "
        "| max Mach | max compression | wall clock [s] |")
    add("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for c in cases:
        add(f"| {c['mode']} | {fmt(c['dx_m'], 4)} | {fmt(c['layers_over_depth'], 0)} "
            f"| {c['n_particles']} | {c['steps']} "
            f"| {fmt(c['omega_measured'], 4)} | {fmt(c['omega_theory'], 4)} "
            f"| {fmt(c['frequency_error_pct'], 2, ' %')} | {fmt(c['fit_r2'], 3)} "
            f"| {fmt(c['fit_amplitude_over_initial'], 2)} "
            f"| {fmt(c['damping_rate_1_s'], 3)} | {fmt(c['mach'], 4)} "
            f"| {fmt(c['density_compression'] * 100, 2, ' %')} "
            f"| {fmt(c['wall_clock_s'], 1)} |")
    add("")
    add("`amp. ratio` is the fitted amplitude of `q_n(t)` over the initial `A`: a")
    add("value below 1 is the numerical damping of the run. `damping rate` is the")
    add("slope of `ln` of the windowed RMS of `q_n(t)`; the analytic inviscid value")
    add("is zero, so it measures numerical dissipation only.")
    add("")
    if data["dispersion_ratio"]:
        add("**Dispersion check** (mode-2/mode-1 ratio, insensitive to a common offset):")
        add("")
        add("| `dx` [m] | measured `omega_2/omega_1` | analytic | error |")
        add("|---|---|---|---|")
        for dx, row in sorted(data["dispersion_ratio"].items(), key=lambda kv: float(kv[0])):
            add(f"| {dx} | {fmt(row['measured'], 4)} | {fmt(row['analytic'], 4)} "
                f"| {fmt(row['error_pct'], 2, ' %')} |")
        add("")
    add("![B5 sloshing](slosh.png)")
    add("")
    add("(a) modal coordinate with both estimators and the cosine fit; (b) measured")
    add("vs analytic frequency over the resolution ladder; (c) frequency error with")
    add("the 15 % acceptance and 3 % target; (d) reconstructed surface at an early")
    add("instant against the initial mode shape.")
    add("")

    # ------------------------------------------------------------------ 4
    add("## 4. Error judgement against the analytic reference")
    add("")
    add("| mode | `dx` [m] | frequency error | < 15 %? | < 3 %? |")
    add("|---|---|---|---|---|")
    for c in cases:
        add(f"| {c['mode']} | {fmt(c['dx_m'], 4)} | {fmt(c['frequency_error_pct'], 2, ' %')} "
            f"| {fmt(c['within_15pct'])} | {fmt(c['within_3pct'])} |")
    add("")
    add("The comparison is against the *linear* frequency. Finite amplitude shifts a")
    add("standing wave by order `(k A)^2` (`(k A)^2 / 8` is quoted per case in the")
    add("JSON as `nonlinear_shift_scale`); for `A/H = 0.1` that is the size of the")
    add("3 % target, so the residual is reported rather than corrected with a fitted")
    add("constant.")
    add("")

    # ------------------------------------------------------------------ 5
    add("## 5. Caveats and limits of this benchmark")
    add("")
    add("- The tank is closed and the mode is exact there; **no absorbing or open")
    add("  boundary is exercised**, so nothing here says how a wave leaves the domain.")
    add("- `H/L = 0.5` is intermediate depth. The shallow (`kH -> 0`) and deep")
    add("  (`kH >> 1`) limits are checked on the *formula* in the test suite, not on")
    add("  the solver; a shallow tank needs many more layers for the same error.")
    add("- Numerical damping is measured, not explained: the run is inviscid, so the")
    add("  reported decay is the dissipation of the free-surface treatment and the")
    add("  pressure clamp, and it is not separated into contributions here.")
    add("- Only `n = 1, 2` and one amplitude are measured. A frequency depends weakly")
    add("  on amplitude at second order, so a single amplitude cannot separate a")
    add("  method offset from a nonlinear one.")
    add("- Single-phase, two-dimensional, weakly compressible: this is a verification")
    add("  of the free-surface and time-integration path, not a validation of any")
    add("  measured sloshing experiment.")
    add("")
    DOCS.write_text("\n".join(lines) + "\n")
    print(f"wrote {DOCS}")


if __name__ == "__main__":
    main()