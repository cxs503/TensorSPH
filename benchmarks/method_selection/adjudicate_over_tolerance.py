"""Adjudicate every registry record that misses the owner's 15 % accuracy standard.

Anchor ``XVAL-SPH-METHOD-SELECTION-2026-11-12``, mission 22787.

Why this exists
---------------
``audit_quantity_coverage.py`` (mission 20432) lists two classes of open flag and
never adjudicates them:

* ``integrity_failures`` -- a banked number that its own independent recomputation
  cannot reproduce.  Mission 22787 traced the only entry (``x_couette_design``) to
  a defect in the *auditor*, not the artefact: the recomputation sliced the row
  list positionally (``rows[1:-1]``) while the Couette artefact defines "interior"
  as the ``0.15 <= y/H <= 0.85`` band.  That fix lives in
  ``audit_quantity_coverage.py``; this script requires the flag to be empty.
* ``records_over_owner_tolerance`` -- records whose banked error exceeds the
  owner's 15 % accuracy standard.  Mission 20432 emitted the list and stopped;
  mission 22608 explicitly left it unadjudicated.  A bare list invites two
  opposite misreadings: "the scheme is disqualified" and "the ledger is
  trustworthy because it flags itself".  Neither is established without knowing,
  per record, *what* the quantity is and *which resolution* it was read at.

So this script classifies each over-tolerance record from data only:

``reading_mobility``
    The registry record is ``kind == "robustness"``: it measures the spread of a
    reading across a sweep, not the error against a reference.  Comparing a spread
    with an accuracy standard is a category error, and the record must not be
    counted among accuracy failures.
``resolution_attributable``
    The same quantity, same method, measured on a finer rung of the same
    benchmark, is within the standard.  The over-tolerance value is then a
    discretisation symptom that the registry's missing resolution column hides.
``genuine_accuracy_failure``
    Neither of the above: an accuracy claim against an analytic reference that
    really is above 15 %.

For every record it also reports the *decision linkage*: whether the published
strict-bound decision (``docs/reports/method_selection_strict_bound_m21537.json``)
uses that record (e.g. to exclude a scheme) or does not depend on it at all.

Outputs (regenerated by running this file)::

    docs/reports/method_selection_open_flags_adjudication_m22787.json
    docs/reports/method_selection_open_flags_adjudication_m22787.md
    docs/figures/method_selection_m22787/open_flags.png

Usage::

    PYTHONPATH=src python benchmarks/method_selection/adjudicate_over_tolerance.py
    PYTHONPATH=src python benchmarks/method_selection/adjudicate_over_tolerance.py --check
"""
