#: Explicit coarse -> fine pairings, each justified by data checks in
#: :func:`_check_pairing` (same method, same quantity family, coarse > 15 >= fine).
#: Nothing here is a measurement; the numbers are read from the artefacts.
RESOLUTION_PAIRS = [
    {
        "over": "x_couette_wall_shear",
        "fine": "x_couette_wall_shear_design",
        "parameter": "H/dx",
        "coarse_value": 8.0,
        "fine_value": 16.0,
    },
    {
        "over": "x_transport_velocity_coarse",
        "fine": "x_transport_velocity",
        "parameter": "dx [m]",
        "coarse_value": 0.04,
        "fine_value": 0.03,
    },
]


# --------------------------------------------------------------------------- #
# Artefact-level re-derivations (independent of the registry's stored values)
# --------------------------------------------------------------------------- #
def _load(path: str | Path) -> dict:
    return json.loads((ROOT / path).read_text())


def couette_wall_shear_by_resolution(artifact: str) -> dict[float, float]:
    """Bottom-wall shear error [%] at every rung of a Couette artefact."""
    doc = _load(artifact)
    out: dict[float, float] = {}
    for row in doc["ladder"]:
        metrics = row["metrics"]
        out[float(row["resolution_H_over_dx"])] = aqc._rel_pct(
            float(metrics["wall_shear_measured"]), float(metrics["wall_shear_analytic"]))
    return out


def couette_viscous_time_readings(artifact: str) -> list[dict]:
    """Per-point wall-shear readings of the viscous-time sweep, admissible flag kept."""
    doc = _load(artifact)
    return [
        {
            "resolution_H_over_dx": float(p["resolution_H_over_dx"]),
            "viscous_times": float(p["viscous_times"]),
            "admissible": bool(p["admissible"]),
            "bottom_pct": float(p["wall_shear_error_pct_bottom"]),
            "top_pct": float(p["wall_shear_error_pct_top"]),
        }
        for p in doc["points"]
    ]


def _tvc_arm_mean(source: str, variant: str) -> float:
    doc = _load(source)
    arm = next(r for r in doc["records"] if r["variant"] == variant)
    rel = [abs(float(row["rel_error"])) for row in arm["score"]["rows"]
           if row["rel_error"] is not None]
    return sum(rel) / len(rel) * 100.0


def _dx_from_record(record: dict) -> float:
    match = re.search(r"dx\s*=\s*([0-9.]+)\s*m", record["case"])
    if match:
        return float(match.group(1))
    match = re.search(r"dx0*([0-9]+)", Path(record["source"]).name)
    if match:
        digits = match.group(1)
        return float(f"0.{digits.lstrip('0') or '0'}")
    raise ValueError(f"cannot read a grid spacing out of {record['case']!r}")


# --------------------------------------------------------------------------- #
# Classification
# --------------------------------------------------------------------------- #
def _quantity_of(extractor: str) -> aqc.Quantity:
    return next(q for q in aqc.QUANTITIES if q.extractor == extractor)


def _check_pairing(pair: dict, over: dict, fine: dict) -> list[str]:
    """Data checks that make the pairing evidence rather than an assertion."""
    problems = []
    if over["method"] != fine["method"]:
        problems.append(f"{pair['over']}/{pair['fine']} pair different methods")
    if not (float(over["measured_pct"]) > OWNER_TOLERANCE_PCT
            >= float(fine["measured_pct"])):
        problems.append(
            f"{pair['over']}={over['measured_pct']:.2f}% / "
            f"{pair['fine']}={fine['measured_pct']:.2f}% do not straddle the "
            f"{OWNER_TOLERANCE_PCT}% standard")
    over_q = over["quantity"].lower()
    fine_q = fine["quantity"].lower()
    # The fine record must call itself the same quantity (the registry writes
    # "same quantity on the coarser rung" on the coarse side, so compare the
    # leading words of the definition instead of the whole sentence).
    head = " ".join(over_q.split()[:4])
    if head not in fine_q and "same quantity" not in over_q:
        problems.append(f"{pair['over']} quantity text does not match its pair")
    return problems


def classify(over_record: dict, registry_by_extractor: dict[str, dict],
             artefacts: dict[str, dict]) -> dict:
    extractor = over_record["extractor"]
    quantity = _quantity_of(extractor)
    entry = {
        "extractor": extractor,
        "method": over_record["method"],
        "registry_kind": over_record["registry_kind"],
        "banked_pct": float(over_record["banked_pct"]),
        "recomputed_pct": float(over_record["recomputed_pct"]),
        "own_gate_pct": over_record["banked_gate_pct"],
        "own_gate_passed": over_record["own_gate_passed"],
        "artifact": over_record["artifact"],
        "quantity": over_record["quantity"],
        "evidence": [],
        "problems": [],
    }

    if over_record["registry_kind"] == "robustness":
        entry["class"] = "reading_mobility"
        entry["evidence"].append(
            "registry record kind=robustness: the quantity is the spread of a "
            "reading across the sweep, not an error against a reference")
        mobility = _mobility_rederivation(over_record)
        entry["rederived"] = mobility
        if mobility is not None and abs(
                mobility["bottom_spread_pct"] - entry["banked_pct"]) > 1e-6:
            entry["problems"].append(
                f"re-derived mobility {mobility['bottom_spread_pct']:.6f}% != "
                f"banked {entry['banked_pct']:.6f}%")
        return entry

    for pair in RESOLUTION_PAIRS:
        if pair["over"] != extractor:
            continue
        fine_record = registry_by_extractor[pair["fine"]]
        entry["problems"].extend(
            _check_pairing(pair, registry_by_extractor[extractor], fine_record))
        entry["class"] = "resolution_attributable"
        entry["pair"] = {
            "fine_extractor": pair["fine"],
            "parameter": pair["parameter"],
            "coarse_value": pair["coarse_value"],
            "fine_value": pair["fine_value"],
            "coarse_pct": float(over_record["banked_pct"]),
            "fine_pct": float(fine_record["measured_pct"]),
            "fine_case": fine_record["case"],
            "fine_source": fine_record["source"],
        }
        entry["evidence"].append(
            f"same quantity at {pair['parameter']}={pair['fine_value']}: "
            f"{float(fine_record['measured_pct']):.2f}% <= {OWNER_TOLERANCE_PCT}% "
            f"(record {pair['fine']})")
        entry["rederived"] = _rederive_pair(extractor, pair)
        return entry

    entry["class"] = "genuine_accuracy_failure"
    entry["rederived"] = _rederive_accuracy(extractor, quantity, artefacts)
    entry["evidence"].append(
        "accuracy claim against an analytic reference; no finer-rung record of the "
        "same quantity is inside the standard")
    return entry


def _mobility_rederivation(over_record: dict) -> dict | None:
    artifact = "benchmarks/couette/out_design/viscous_time_convergence.json"
    try:
        readings = couette_viscous_time_readings(artifact)
    except (OSError, KeyError):
        return None
    match = re.search(r"_h([0-9]+)$", over_record["extractor"])
    if not match:
        return None
    resolution = float(match.group(1))
    rows = [r for r in readings if r["resolution_H_over_dx"] == resolution]
    pool = [r for r in rows if r["admissible"]] or rows
    bottom = [r["bottom_pct"] for r in pool]
    return {
        "source": artifact,
        "resolution_H_over_dx": resolution,
        "n_points": len(rows),
        "n_admissible": sum(1 for r in rows if r["admissible"]),
        "bottom_spread_pct": max(bottom) - min(bottom),
        "bottom_readings_pct": bottom,
    }


def _rederive_pair(extractor: str, pair: dict) -> dict:
    if extractor.startswith("x_couette"):
        over_artifact = _quantity_of(extractor).artifact
        fine_artifact = _quantity_of(pair["fine"]).artifact
        over_ladder = couette_wall_shear_by_resolution(over_artifact)
        fine_ladder = couette_wall_shear_by_resolution(fine_artifact)
        return {
            "kind": "bottom-wall shear error vs H/dx",
            # One series per artefact: the two artefacts stop at different
            # terminal times, so their shared H/dx = 8 rung is *not* merged.
            "series": [
                {"artifact": over_artifact,
                 "values": {f"{k:g}": v for k, v in sorted(over_ladder.items())}},
                {"artifact": fine_artifact,
                 "values": {f"{k:g}": v for k, v in sorted(fine_ladder.items())}},
            ],
            "coarse_pct": over_ladder[pair["coarse_value"]],
            "fine_pct": fine_ladder[pair["fine_value"]],
        }
    if extractor.startswith("x_transport_velocity"):
        registry = _load(REGISTRY_JSON)["records"]
        by_extractor = {r["extractor"]: r for r in registry}
        coarse = by_extractor[extractor]
        fine = by_extractor[pair["fine"]]
        points = {}
        for record in (coarse, fine):
            points[f"{_dx_from_record(record):g}"] = _tvc_arm_mean(
                record["source"], aqc.TVC_VARIANT)
        return {
            "kind": "front-position mean error vs dx [m]",
            "series": [{"artifact": "registry records (both grids)",
                        "values": dict(sorted(points.items()))}],
            "coarse_pct": points[f"{_dx_from_record(coarse):g}"],
            "fine_pct": points[f"{_dx_from_record(fine):g}"],
        }
    raise NotImplementedError(extractor)


def _rederive_accuracy(extractor: str, quantity: aqc.Quantity,
                       artefacts: dict[str, dict]) -> dict:
    doc = artefacts[quantity.artifact]
    value = float(quantity.recompute(doc))
    out = {"recomputed_pct": value}
    if extractor == "x_couette_viscous_time_top_h16":
        readings = couette_viscous_time_readings(
            "benchmarks/couette/out_design/viscous_time_convergence.json")
        by_res = {}
        for res in sorted({r["resolution_H_over_dx"] for r in readings}):
            rows = [r for r in readings if r["resolution_H_over_dx"] == res]
            pool = [r for r in rows if r["admissible"]] or rows
            end = max(pool, key=lambda r: r["viscous_times"])
            by_res[f"{res:g}"] = {
                "n_points": len(rows),
                "n_admissible": sum(1 for r in rows if r["admissible"]),
                "top_pct_at_steady_end": end["top_pct"],
                "bottom_pct_at_steady_end": end["bottom_pct"],
            }
        out["resolution_response"] = by_res
        out["worsens_with_resolution"] = (
            by_res["16"]["top_pct_at_steady_end"]
            > by_res["8"]["top_pct_at_steady_end"])
    return out


# --------------------------------------------------------------------------- #
# Decision linkage: is a published decision standing on an over-tolerance record?
# --------------------------------------------------------------------------- #
def decision_linkage(method: str, strict: dict, banked_pct: float) -> dict:
    rows = strict["rows"]
    primary_in, excluded_by, modifier_in = [], [], []
    for row in rows:
        strict_row = row["strict"]
        if strict_row.get("primary") == method:
            primary_in.append({
                "profile": row["label"],
                "status": strict_row["primary_status"],
                "headline_bound_pct": strict_row["headline_bound_pct"],
                "within_owner_standard": strict_row["within_owner_standard"],
            })
        for excluded in strict_row.get("excluded", []):
            if excluded.get("method") == method:
                worst = excluded.get("worst_accuracy_pct")
                excluded_by.append({
                    "profile": row["label"],
                    "role": excluded.get("role"),
                    "worst_accuracy_pct": worst,
                    "worst_accuracy_case": excluded.get("worst_accuracy_case"),
                    "cites_this_record": (
                        None if worst is None
                        else abs(float(worst) - banked_pct) <= 1e-6),
                })
        if method in strict_row.get("modifiers", []):
            modifier_in.append({"profile": row["label"]})
    return {
        "strict_primary": primary_in,
        "strict_modifier": modifier_in,
        "excluded_by": excluded_by,
        "endorsed_within_standard": [
            p for p in primary_in if p["within_owner_standard"]] + modifier_in,
    }


# --------------------------------------------------------------------------- #
# Driver
# --------------------------------------------------------------------------- #
#: Every class the adjudication may hand out, in report order.
ADJUDICATION_CLASSES = ("resolution_attributable", "reading_mobility",
                        "genuine_accuracy_failure", "documented_trap_arm")


def classify_out_of_catalogue(record: dict) -> dict:
    """Adjudicate a registry record the coverage audit never recomputes.

    The coverage audit's catalogue covers the artefacts it knows how to
    re-derive; a registry record outside that catalogue is *unaudited*, which is
    exactly the blind spot mission 22787 measured.  These entries are re-derived
    from their own artefact here, or marked ``stored_only`` when no independent
    recomputation exists (an honest downgrade, not a silent pass).
    """
    entry = {
        "extractor": record["extractor"],
        "method": record["method"],
        "registry_kind": record["kind"],
        "banked_pct": float(record["measured_pct"]),
        "recomputed_pct": None,
        "own_gate_pct": float(record["gate_pct"]),
        "own_gate_passed": bool(record.get("own_gate_passed", False)),
        "artifact": record["source"],
        "quantity": record["quantity"],
        "audit_catalogue": False,
        "evidence": [],
        "problems": [],
    }
    if record["extractor"] == "x_conduction_2d_one_d_calibration":
        doc = _load(record["source"])
        arms = doc["arms_summary"]
        trap = float(arms["lattice_1d_worst_error"]) * 100.0
        shipped = float(arms["k0_2d_worst_error"]) * 100.0
        entry["class"] = "documented_trap_arm"
        entry["recomputed_pct"] = trap
        entry["rederived"] = {
            "trap_arm_pct": trap,
            "shipped_arm_pct": shipped,
            "artefact_note": arms.get("note"),
            "source": record["source"],
        }
        entry["evidence"].append(
            "the artefact calls this arm a documented trap and reports the "
            f"shipped 2-D-calibrated arm at {shipped:.2f}% in the same file")
        if abs(trap - entry["banked_pct"]) > 1e-6:
            entry["problems"].append(
                f"re-derived trap arm {trap:.6f}% != banked {entry['banked_pct']}")
        if shipped > OWNER_TOLERANCE_PCT:
            entry["problems"].append(
                f"shipped arm {shipped:.2f}% is itself over the standard")
        return entry

    entry["class"] = "genuine_accuracy_failure"
    entry["recomputed_pct"] = None
    entry["rederived"] = {"recompute_kind": "stored_only",
                          "source": record["source"]}
    entry["evidence"].append(
        "outside the coverage audit's recomputation catalogue: the value is the "
        "artefact's stored number, verified only against the artefact text")
    return entry


def build() -> dict:
    registry = _load(REGISTRY_JSON)["records"]
    registry_by_extractor = {r["extractor"]: r for r in registry}
    audit_path = AUDIT_JSON
    if not audit_path.exists():
        raise SystemExit(
            "run benchmarks/method_selection/audit_quantity_coverage.py first")
    audit = json.loads(audit_path.read_text())
    strict = json.loads(STRICT_JSON.read_text())

    audit_rows = {row["extractor"]: row for row in audit["quantities"]}
    artefacts: dict[str, dict] = {}
    for extractor in audit["records_over_owner_tolerance"]:
        artifact = audit_rows[extractor]["artifact"]
        artefacts[artifact] = _load(artifact)

    # The owner's ledger is the registry, not the audit: audit only sees the
    # quantities its catalogue can re-derive.  Adjudicate the whole registry and
    # report the difference, so an unaudited record cannot stay invisible.
    registry_over = [r for r in registry
                     if float(r["measured_pct"]) > OWNER_TOLERANCE_PCT]
    adjudications = []
    for record in registry_over:
        extractor = record["extractor"]
        if extractor in audit_rows:
            entry = classify(audit_rows[extractor], registry_by_extractor,
                             artefacts)
            entry["audit_catalogue"] = True
        else:
            entry = classify_out_of_catalogue(record)
        entry["decision_linkage"] = decision_linkage(
            entry["method"], strict, entry["banked_pct"])
        adjudications.append(entry)
    audit_coverage_gap = [a["extractor"] for a in adjudications
                          if not a.get("audit_catalogue", False)]

    classes = {c: [a["extractor"] for a in adjudications if a["class"] == c]
               for c in ADJUDICATION_CLASSES}
    accuracy_only = [a["extractor"] for a in adjudications
                     if a["registry_kind"] == "accuracy"]
    # A leak is a *live accuracy claim* above the standard whose method a
    # published decision still endorses inside the standard.  A robustness
    # record (a spread) and a documented trap arm are not live accuracy claims,
    # but they are reported separately so the difference stays visible.
    live = {"resolution_attributable", "genuine_accuracy_failure"}
    leaks = [a["extractor"] for a in adjudications
             if a["class"] in live
             and a["decision_linkage"]["endorsed_within_standard"]]
    endorsed_with_trap_arm = [a["extractor"] for a in adjudications
                              if a["class"] == "documented_trap_arm"
                              and a["decision_linkage"]["endorsed_within_standard"]]
    endorsed_with_spread = [a["extractor"] for a in adjudications
                            if a["class"] == "reading_mobility"
                            and a["decision_linkage"]["endorsed_within_standard"]]
    return {
        "schema_version": "1.0",
        "anchor": "XVAL-SPH-METHOD-SELECTION-2026-11-12",
        "mission": 22787,
        "generated_by": "benchmarks/method_selection/adjudicate_over_tolerance.py",
        "owner_tolerance_pct": OWNER_TOLERANCE_PCT,
        "audit_source": str(AUDIT_JSON.relative_to(ROOT)),
        "registry_records": len(registry),
        "audit_integrity_failures": audit["integrity_failures"],
        "over_tolerance_records": [a["extractor"] for a in adjudications],
        "audit_over_tolerance_records": audit["records_over_owner_tolerance"],
        "audit_coverage_gap": audit_coverage_gap,
        "over_tolerance_accuracy_records": accuracy_only,
        "classes": classes,
        "decision_leaks": leaks,
        "endorsed_with_trap_arm": endorsed_with_trap_arm,
        "endorsed_with_spread": endorsed_with_spread,
        "adjudications": adjudications,
    }


