# --------------------------------------------------------------------------- #
# Independent recomputations: raw artefact -> percent error
# --------------------------------------------------------------------------- #
def _rel_pct(measured: float, reference: float) -> float:
    if reference == 0:
        raise ZeroDivisionError("reference is zero")
    return abs(measured / reference - 1.0) * 100.0


def r_wave_flume(doc: dict) -> float:
    # worst |H_got - H_target| / H_target over the graded gauges, recomputed from
    # the per-gauge block instead of reading ``worst_error_percent``.
    worst = 0.0
    for case in doc["cases"]:
        for gauge in case["gauges"]:
            height = float(gauge["height"])
            target = float(case["target_height"])
            worst = max(worst, abs(height - target) / target * 100.0)
    return worst


def r_sod(doc: dict) -> float:
    return max(abs(v) for v in doc["metrics"]["rel_err"].values()) * 100.0


def r_conduction(doc: dict) -> float:
    return abs(float(doc["main_run"]["max_normalised_error"])) * 100.0


def r_laplace_pressure(doc: dict) -> float:
    return _rel_pct(float(doc["laplace"]["delta_p_measured_Pa"]),
                    float(doc["laplace"]["delta_p_theory_Pa"]))


def r_laplace_curvature(doc: dict) -> float:
    final = doc["curvature_final"]
    return _rel_pct(float(final["band_mean_1_per_m"]), float(final["exact_1_per_m"]))


def r_csf_kappa(doc: dict) -> float:
    entry = doc["instant"]["consistent"][0]
    return _rel_pct(float(entry["kappa"]["delta_s_weighted_mean_1_per_m"]),
                    float(entry["kappa"]["exact_1_per_m"]))


def r_csf_cut_force(doc: dict) -> float:
    entry = doc["instant"]["consistent"][0]
    return _rel_pct(float(entry["cut_force"]["measured_N_per_m"]),
                    float(entry["cut_force"]["theory_N_per_m"]))


def r_dd_rate(doc: dict) -> float:
    worst = 0.0
    for ladder in ("resolution_ladder", "wavenumber_ladder", "smoothing_length_ladder"):
        for rung in doc.get(ladder, []):
            worst = max(worst, _rel_pct(float(rung["gamma_measured_1_per_s"]),
                                        float(rung["gamma_theory_1_per_s"])))
    return worst


def r_dd_finite_time(doc: dict) -> float:
    ft = doc["finite_time"]
    return _rel_pct(float(ft["final_amplitude"]), float(ft["final_theory"]))


def _isph_finest(doc: dict) -> dict:
    return max(doc["results"], key=lambda row: row["resolution_H_over_dx"])


def r_isph_centre(doc: dict) -> float:
    gate = _isph_finest(doc)["gates"]["centre_velocity"]
    return _rel_pct(float(gate["measured"]), float(gate["reference"]))


def r_isph_wall_shear(doc: dict) -> float:
    gate = _isph_finest(doc)["gates"]["wall_shear_budget"]
    return _rel_pct(float(gate["measured"]), float(gate["reference"]))


def r_compression(doc: dict) -> float:
    arm = next(r for r in doc["records"] if r["arm"] == "compression_refmean")
    return abs(float(arm["gate"]["max_band_error_pct"]))


def r_particle_shifting(doc: dict) -> float:
    break_case = doc["cases"]["dam_break"]
    column = 0.2  # dam-break column width of this benchmark, metres
    return abs(float(break_case["max_front_delta_m"])) / column * 100.0


def _couette_finest(doc: dict) -> dict:
    return max(doc["ladder"], key=lambda row: row["resolution_H_over_dx"])


def r_couette_l2(doc: dict) -> float:
    """``metrics.interior_l2``: RMS of the per-row relative error, *interior rows only*.

    The artefact defines "interior" as every row except the two wall-adjacent ones
    (``rows[0]`` and ``rows[-1]``); the recomputation follows that definition and
    the all-row RMS is banked separately below, so the definition cannot hide the
    wall-adjacent error.
    """
    rows = _couette_finest(doc)["metrics"]["rows"][1:-1]
    return math.sqrt(sum(float(r["rel_err"]) ** 2 for r in rows) / len(rows)) * 100.0


def r_couette_l2_all_rows(doc: dict) -> float:
    rows = _couette_finest(doc)["metrics"]["rows"]
    return math.sqrt(sum(float(r["rel_err"]) ** 2 for r in rows) / len(rows)) * 100.0


def r_couette_flux(doc: dict) -> float:
    metrics = _couette_finest(doc)["metrics"]
    return _rel_pct(float(metrics["flux_measured"]), float(metrics["flux_analytic"]))


def r_couette_wall_shear(doc: dict) -> float:
    metrics = _couette_finest(doc)["metrics"]
    return _rel_pct(float(metrics["wall_shear_measured"]),
                    float(metrics["wall_shear_analytic"]))


TVC_VARIANT = "tvc_a010_all"


def _r_tvc(dx: float) -> Callable[[dict], float]:
    def run(doc: dict) -> float:
        arm = next(r for r in doc["records"]
                   if r["variant"] == TVC_VARIANT and abs(float(r["dx"]) - dx) < 1e-12)
        rel = [abs(float(row["rel_error"])) for row in arm["score"]["rows"]
               if row["rel_error"] is not None]
        return sum(rel) / len(rel) * 100.0
    return run


