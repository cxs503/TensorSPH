    lines.append("## 3 方法级汇总（claim vs 最差已登记量）\n")
    lines.append("| 方法 | claimed bound（仅取过 15% 的记录）[%] | 最差已登记量 [%] | 差额 [%] |")
    lines.append("|---|---|---|---|")
    for entry in result["methods"]:
        claimed = entry["claimed_pct"]
        worst = entry["worst_banked_pct"]
        gap = "-" if claimed is None else f"{worst - claimed:.3g}"
        lines.append(f"| `{entry['method']}` | {_fmt(claimed)} | {_fmt(worst)} | {gap} |")
    lines.append("")

    lines.append("## 4 产物自评状态\n")
    lines.append("| 产物 | 自评 |")
    lines.append("|---|---|")
    for verdict in result["artefact_verdicts"]:
        lines.append(f"| `{verdict['artifact']}` | `{verdict['own_verdict']}` |")
    lines.append("")

