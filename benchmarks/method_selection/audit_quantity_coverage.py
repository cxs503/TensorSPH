"""Audit the method-selection registry for *metric shopping* and stale evidence.

Anchor ``XVAL-SPH-METHOD-SELECTION-2026-11-12``, mission 20432.

Why this exists
---------------
The registry (``docs/reports/method_selection_registry.json``) stores **one**
percentage per (method, case, artefact).  A benchmark artefact usually reports
*several* quantities, each with its own pass/fail limit.  If the registry banks
only the kindest one, a scheme can be reported as "5.7 %" while the quantity
that defines the physics claim (e.g. the wall shear of a no-slip wall) is 32 %
off.  That is metric shopping by construction, and it is invisible from the
registry alone.

This script is an **independent** re-derivation: it does not import
``build_registry`` and does not trust the artefacts' stored percentages.  For
every artefact behind a registry record it

1. enumerates the quantities the artefact itself gates (``limit``/``tol`` with a
   stored measurement),
2. recomputes the percentage from the raw measured/reference pair whenever the
   artefact stores that pair (``recompute=direct``) and otherwise records that
   only a stored percentage is available (``recompute=stored``) -- the honest
   distinction matters, a "verified" number that nobody recomputed is a claim,
   not evidence,
3. checks that a registry record banks exactly that quantity (matched by the
   record's ``extractor`` key, so the link is explicit and not by string
   similarity),
4. compares the banked value with the independent recomputation (integrity),
5. lists the artefacts' own verdict flags (a benchmark whose verdict is FAIL
   must not be quoted as a passing record without a caveat).

Outputs (all regenerated by running this file)::

    docs/reports/method_selection_coverage_audit_m20432.json
    docs/reports/method_selection_coverage_audit_m20432.md
    docs/figures/method_selection_m20432/coverage_audit.png

Usage::

    PYTHONPATH=src python benchmarks/method_selection/audit_quantity_coverage.py
    PYTHONPATH=src python benchmarks/method_selection/audit_quantity_coverage.py --check
"""
