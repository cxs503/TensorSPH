# --------------------------------------------------------------------------- #
# Audit
# --------------------------------------------------------------------------- #
def audit() -> dict:
    registry = json.loads(REGISTRY_PATH.read_text())
    banked = {rec["extractor"]: rec for rec in registry["records"]}

    rows: list[dict] = []
    for quantity in QUANTITIES:
        artifact = ROOT / quantity.artifact
        doc = json.loads(artifact.read_text())
        recomputed = (quantity.recompute(doc) if quantity.recompute is not None
                      else float("nan"))
        stored = quantity.stored(doc) if quantity.stored is not None else None
        record = banked.get(quantity.extractor)
        row = {
            "extractor": quantity.extractor,
            "method": quantity.method,
            "artifact": quantity.artifact,
            "label": quantity.label,
            "quantity": quantity.quantity,
            "gate_pct": quantity.gate_pct,
            "gate_note": quantity.gate_note,
            "recompute_kind": quantity.recompute_kind,
            "recomputed_pct": recomputed,
            "stored_pct": stored,
            "stored_matches_recomputed": (
                None if stored is None
                else abs(stored - recomputed) <= 1e-9 * max(1.0, abs(recomputed))
            ),
            "banked": record is not None,
            "banked_pct": None if record is None else float(record["measured_pct"]),
            "banked_gate_pct": None if record is None else float(record["gate_pct"]),
            "integrity_ok": None,
            "within_owner_tolerance": None,
            "own_gate_passed": None,
        }
        if record is not None:
            row["integrity_ok"] = (
                abs(float(record["measured_pct"]) - recomputed)
                <= INTEGRITY_RTOL * max(1.0, abs(recomputed))
            )
            row["within_owner_tolerance"] = row["banked_pct"] <= OWNER_TOLERANCE_PCT
            row["own_gate_passed"] = (
                None if row["banked_gate_pct"] is None
                else row["banked_pct"] <= row["banked_gate_pct"]
            )
        rows.append(row)

    gated = [row for row in rows if row["gate_pct"] is not None]
    unbanked_gated = [row["extractor"] for row in gated if not row["banked"]]
    integrity_failures = [row["extractor"] for row in rows
                          if row["integrity_ok"] is False]
    stored_mismatches = [row["extractor"] for row in rows
                         if row["stored_matches_recomputed"] is False]
    over_owner = [row for row in rows
                  if row["banked"] and not row["within_owner_tolerance"]]
    own_gate_missed = [row for row in rows
                       if row["banked"] and row["own_gate_passed"] is False]

    by_method: dict[str, dict] = {}
    for row in rows:
        if not row["banked"]:
            continue
        entry = by_method.setdefault(
            row["method"],
            {"method": row["method"], "quantities": [], "claimed_pct": None,
             "worst_banked_pct": None},
        )
        entry["quantities"].append(
            {"extractor": row["extractor"], "quantity": row["quantity"],
             "pct": row["banked_pct"],
             "within_owner_tolerance": row["within_owner_tolerance"]}
        )
        passing = [row["banked_pct"] for row in rows
                   if row["banked"] and row["method"] == row["method"]]
        del passing
    for method, entry in by_method.items():
        values = [q["pct"] for q in entry["quantities"]]
        passing = [q["pct"] for q in entry["quantities"] if q["within_owner_tolerance"]]
        entry["claimed_pct"] = max(passing) if passing else None
        entry["worst_banked_pct"] = max(values)

    verdicts = []
    for artifact in sorted({row["artifact"] for row in rows}):
        doc = json.loads((ROOT / artifact).read_text())
        flag = None
        for key in ("passed", "verdict", "status"):
            if key in doc:
                flag = doc[key]
                break
        if isinstance(flag, dict) and "status" in flag:
            flag = flag["status"]
        verdicts.append({"artifact": artifact, "own_verdict": flag})

    return {
        "schema_version": "1.0",
        "anchor": "XVAL-SPH-METHOD-SELECTION-2026-11-12",
        "mission": 20432,
        "generated_by": "benchmarks/method_selection/audit_quantity_coverage.py",
        "owner_tolerance_pct": OWNER_TOLERANCE_PCT,
        "registry_records": len(registry["records"]),
        "gated_quantities": len(gated),
        "coverage_complete": not unbanked_gated,
        "unbanked_gated_quantities": unbanked_gated,
        "integrity_failures": integrity_failures,
        "stored_vs_recomputed_mismatches": stored_mismatches,
        "records_over_owner_tolerance": [row["extractor"] for row in over_owner],
        "records_missing_own_gate": [row["extractor"] for row in own_gate_missed],
        "unbacked_gates": [dict(item) for item in UNBACKED_GATES],
        "artefact_verdicts": verdicts,
        "methods": [by_method[key] for key in sorted(by_method)],
        "quantities": rows,
    }


