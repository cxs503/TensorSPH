def render_resolution_figure(payload: dict, path: Path = None):  # noqa: C901
    """Draw the three resolution-criterion panels from ``payload`` alone."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    path = Path(path) if path is not None else FIGURE_DIR / RES_FIGURE_NAME
    path.parent.mkdir(parents=True, exist_ok=True)
    budget = payload["force_budget"]
    floor = payload["curvature_floor"]
    rows = payload["ladder"]
    bcs = payload["wall_bc"]
    th = payload["predeclared"]["thresholds"]

    fig, axes = plt.subplots(1, 3, figsize=(13.2, 3.8))

    ax = axes[0]
    names = ["wall_adjacent", "free_surface", "interior"]
    shares = [budget["zones"][n]["share_of_total_abs_a"] * 100 for n in names]
    ax.bar(range(len(names)), shares, color="#4477aa")
    for i, share in enumerate(shares):
        ax.text(i, share + 2, f"{share:.0f} %", ha="center", fontsize=8)
    ax.set_xticks(range(len(names)))
    ax.set_xticklabels([n.replace("_", "\n") for n in names], fontsize=7)
    ax.set_ylabel("share of $\\sum_i |a_i|$ [%]")
    ax.set_ylim(0, 110)
    ax.set_title("(a) where the CSF force at $t=0$ lives")
    ax.grid(alpha=0.3, axis="y")

    ax = axes[1]
    ppw = [c["points_per_wavelength"] for c in floor["cells"]]
    rms = [c["kappa_flat_rms_1_per_m"] for c in floor["cells"]]
    mean = [c["kappa_flat_mean_1_per_m"] for c in floor["cells"]]
    ax.plot(ppw, rms, "o-", color="#cc3311", label=r"flat-surface $\kappa_{rms}$ (floor)")
    ax.plot(ppw, mean, "s--", color="#ee8866", label=r"flat-surface $\overline{\kappa}$ (bias)")
    k = floor["k_1_per_m"]
    for cell, style in zip(floor["cells"], ("-", "--", ":")):
        signal = k * k * 0.5 * cell["dx_m"]
        ax.axhline(signal, color="#228833", ls=style, lw=1.0)
    ax.axhline(k * k * 0.5 * floor["cells"][0]["dx_m"], color="#228833", ls="-",
               lw=1.4, label=r"signal $k^2A$ at $A=0.5\,dx$")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel(r"$\lambda/dx$")
    ax.set_ylabel("curvature [1/m]")
    ax.set_title("(b) the floor does not vanish under refinement")
    ax.legend(fontsize=6.5)
    ax.grid(alpha=0.3, which="both")

    ax = axes[2]
    labels = [r["variant"].replace("ppw=", "").replace("/", "\n") for r in rows]
    errors = [r.get("omega_relative_error_pct", float("nan")) for r in rows]
    colors = ["#228833" if r["graded"] else "#4477aa" for r in rows]
    ax.bar(range(len(rows)), errors, color=colors)
    ax.axhline(th["dispersion_rel_error_pct"], color="k", ls="--", lw=1.1,
               label="3 % tolerance")
    ax.axhline(-th["dispersion_rel_error_pct"], color="k", ls="--", lw=1.1)
    ax.set_xticks(range(len(rows)))
    ax.set_xticklabels(labels, fontsize=6)
    ax.set_ylabel(r"$\omega$ error vs Lamb [%]")
    ax.set_title(f"(c) ladder ({len(rows)} cells, "
                 f"{payload['summary']['n_completed']} completed)")
    ax.legend(fontsize=7)
    ax.grid(alpha=0.3, axis="y")
    clamp = bcs["clamp_box_no_wall"]
    wall = bcs["static_wall_particles"]
    ax.text(0.02, 0.03,
            f"clamp box (round 1): {clamp['status']}"
            + (f" @ step {clamp['escape_step']}" if clamp.get("escape_step") else "")
            + f"\nstatic walls: {wall['status']}",
            transform=ax.transAxes, fontsize=6, va="bottom")

    fig.tight_layout()
    fig.savefig(path, dpi=140, metadata={"Software": None})
    plt.close(fig)
    return path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the committed page is stale")
    ap.add_argument("--figures", action="store_true",
                    help=f"also re-render {FIGURE_DIR.name}/{FIGURE_NAME} "
                         "from the committed JSON")
    ap.add_argument("--resolution-only", action="store_true",
                    help="only re-render the round-2 resolution-criterion page "
                         f"({RES_DOC.name}) when it has not been written yet")
    args = ap.parse_args()
    if args.resolution_only:
        text = render_resolution(json.loads(RES_JSON.read_text()))
        RES_DOC.write_text(text)
        print(f"wrote {RES_DOC} ({len(text.splitlines())} lines)")
        return 0
    payload = json.loads((HERE / "open_surface_audit.json").read_text())
    text = render(payload)
    if args.check:
        current = DOC.read_text() if DOC.is_file() else ""
        if current != text:
            print(f"{DOC} is stale -- run make_doc.py")
            return 1
        fig = FIGURE_DIR / FIGURE_NAME
        if not fig.is_file():
            print(f"{fig} is missing -- run make_doc.py --figures")
            return 1
        print(f"{DOC} is up to date")
        return 0
    DOC.write_text(text)
    print(f"wrote {DOC} ({len(text.splitlines())} lines)")
    if args.figures:
        path = render_figure(payload, FIGURE_DIR / FIGURE_NAME)
        print(f"wrote {path} ({path.stat().st_size} bytes)")
        if RES_JSON.is_file():
            res_payload = json.loads(RES_JSON.read_text())
            text = render_resolution(res_payload)
            RES_DOC.write_text(text)
            print(f"wrote {RES_DOC} ({len(text.splitlines())} lines)")
            rpath = render_resolution_figure(res_payload,
                                             FIGURE_DIR / RES_FIGURE_NAME)
            print(f"wrote {rpath} ({rpath.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
