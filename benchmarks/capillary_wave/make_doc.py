"""Render ``docs/verification_capillary_wave_open_surface.md`` from the audit JSON.

Every number in the page is injected from ``open_surface_audit.json``; the test
``tests/test_capillary_wave_open_surface.py`` regenerates the page and fails on
drift, so nothing in the document is hand typed.

Usage::

    PYTHONPATH=src python benchmarks/capillary_wave/make_doc.py --figures
    PYTHONPATH=src python benchmarks/capillary_wave/make_doc.py --check
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
DOC = REPO / "docs" / "verification_capillary_wave_open_surface.md"
#: The figure lives under ``docs/`` and not next to the JSON, and that is a
#: measurement, not a taste: ``git ls-tree -r HEAD`` carries 83 ``*.png`` under
#: ``docs/`` and **zero** under ``benchmarks/`` -- four separate branches
#: (9bd7148, 04f6b24, d9bb365, 296dbee) committed
#: ``benchmarks/capillary_wave/capillary_wave_open_surface.png`` and none of them
#: reached ``main``, which left the gate in
#: ``tests/test_capillary_wave_open_surface.py`` red on ``main`` (missing figure)
#: for a record whose whole point is that it is load-bearing.  Generated binaries
#: therefore belong under ``docs/figures/``.
FIGURE_DIR = REPO / "docs" / "figures"
FIGURE_NAME = "capillary_wave_open_surface.png"


def _fmt(value, spec=".2f", dash="-"):  # noqa: ANN001
    if value is None:
        return dash
    return f"{value:{spec}}"


def _status(row: dict) -> str:
    if row["status"] == "aborted":
        return f"aborted @ step {row['escape_step']}"
    return "completed"


def _figure_sha256(path: Path = None) -> str:
    """sha256 of the committed figure, or a marker when it has not been drawn."""
    import hashlib

    path = Path(path) if path is not None else FIGURE_DIR / FIGURE_NAME
    if not path.is_file():
        return "not-rendered (run make_doc.py --figures)"
    return hashlib.sha256(path.read_bytes()).hexdigest()


def render(payload: dict) -> str:
    case = payload["case"]
    head = payload["harness_at_head"]
    acc = payload["initial_acceleration"]
    curv = payload["curvature"]
    sweep = payload["variant_sweep"]
    ladder = payload["amplitude_ladder"]
    summ = payload["summary"]

    lines: list[str] = []
    add = lines.append

    add("# The capillary-wave verification harness and the open free surface")
    add("")
    add("*TensorSPH, verification record. Generated by "
        "`benchmarks/capillary_wave/make_doc.py` from "
        "`benchmarks/capillary_wave/open_surface_audit.json` -- do not edit by hand.*")
    add("")
    add("## 1. Case and problem")
    add("")
    add("`benchmarks/verification_ledger/waivers.json` used to carry the entry")
    add("")
    add("> `benchmarks/capillary_wave/`: harness only (capillary-wave dispersion "
        "check), no committed artifact - evidence debt E1")
    add("")
    add("so the repository shipped a capillary-wave harness with **no committed "
        "evidence** that the capability works. `benchmarks/capillary_wave/validation.py` "
        "is the end-to-end comparison against Lamb (1932); it commits no output either, "
        "and running it at HEAD on its own `resolution` case aborts inside two "
        "capillary periods. This page replaces that silence with a measurement.")
    add("")
    add("The physical case is a **standing capillary wave on an open free surface**: "
        "a 2-D pool held by a free-slip (`clamp`) bottom and sides, no gravity, no "
        "physical viscosity, perturbed as `eta = A cos(kx)` with the mode matched to "
        "the domain width so that the side boundaries are crest and trough.")
    add("")
    add("| parameter | value |")
    add("|---|---|")
    add(f"| wavelength `lambda` | {case['wavelength']*1e3:.1f} mm |")
    add(f"| wavenumber `k = 2 pi/lambda` | {curv['k_1_per_m']:.1f} 1/m |")
    add(f"| water depth `H` | {case['depth']*1e3:.1f} mm |")
    add(f"| `kH` (deep-water factor `tanh kH`) | "
        f"{curv['k_1_per_m']*case['depth']:.2f} "
        f"({_fmt(__import__('math').tanh(curv['k_1_per_m']*case['depth']), '.5f')}) |")
    add(f"| initial amplitude `A` | {curv['amplitude_m']*1e3:.2f} mm "
        f"(= {case['amp_over_dx']:.1f} dx) |")
    add(f"| particle spacing `dx` | {case['dx']*1e3:.2f} mm "
        f"({case['wavelength']/case['dx']:.0f} points per wavelength) |")
    add(f"| surface tension `sigma` | {case['sigma']:.1f} N/m |")
    add(f"| density `rho0` | {case['rho0']:.0f} kg/m^3 |")
    add(f"| sound speed `c0` | {case['sound_speed']:.0f} m/s |")
    add(f"| analytic `omega` (Lamb 1932 Art. 267, `g = 0`) | "
        f"{acc['omega_rad_per_s']:.1f} rad/s |")
    add(f"| analytic period | {2*3.141592653589793/acc['omega_rad_per_s']*1e3:.2f} ms |")
    add(f"| physical restoring acceleration `omega^2 A` | "
        f"{acc['a_physical_omega2A_m_per_s2']:.1f} m/s^2 |")
    add(f"| physical particle velocity `u_ref = A omega` | "
        f"{curv['amplitude_m']*acc['omega_rad_per_s']:.3f} m/s |")
    add("")
    add("The audit horizon is "
        f"{payload['horizon_periods']:.1f} capillary periods "
        "(the harness itself simulates four to five).")
    add("")
    add("## 2. What was done")
    add("")
    add("`benchmarks/capillary_wave/open_surface_audit.py` performs three "
        "measurements on that case and records a status row instead of an exception:")
    add("")
    add("1. **Harness as-is.** `validation.run_case` is called with the harness's own "
        "`resolution` parameters. Whatever it does -- abort or finish -- is recorded.")
    add("2. **Initial-state decomposition.** The acceleration of the untouched initial "
        "state is measured by `rhs` with surface tension on and off, so the CSF "
        "contribution is isolated from the density/pressure transient; the discrete "
        "curvature field of the same interface (`csf_fields`) is compared with the "
        "perturbation's own curvature `k^2 A`.")
    add("3. **Variant sweep and amplitude ladder.** "
        f"{summ['n_variants']} solver configurations (density renormalisation, mass "
        "calibration, both free-surface pressure-closure donor semantics, the legacy "
        "CSF scheme, a square lattice, a higher sound speed) and two amplitudes "
        "(`A/dx = 0.5, 2`) are marched over the same horizon. Admissibility follows "
        "Adami, Ihmsen & Adams (2012): a surface-tension run may only be graded when "
        "the spurious current is below 10 % of the capillary velocity scale, here "
        "`u_ref = A omega`.")
    add("")
    add("Everything is deterministic and CPU-only; the whole audit is "
        f"{summ['wall_clock_s']:.0f} s of wall clock on the repo checkout.")
    add("")
    add("## 3. Results")
    add("")
    add("### 3.1 The harness does not run at HEAD")
    add("")
    add("| item | value |")
    add("|---|---|")
    add(f"| case | `{head['case']}` |")
    add(f"| status | **{head['status']}** |")
    if head["status"] == "aborted":
        add(f"| abort step | {head['escape_step']} |")
        add("| exception | `" + head.get("exception", "").replace("|", "/") + "` |")
    else:
        add(f"| frequency error | {head.get('omega_rel_error_pct'):+.1f} % |")
    add("")
    add("### 3.2 The first step is already unphysical")
    add("")
    add("| configuration | `max|a|` [m/s^2] | `p99 |a|` | median `|a|` on the "
        "surface shell | `rho_min/rho0` | `p_max` [Pa] | `max|a| / omega^2 A` |")
    add("|---|---|---|---|---|---|---|")
    for key in ("csf_off", "csf_on_mass_calibrated", "csf_on",
                "csf_on_density_renormalization"):
        row = acc[key]
        add(f"| `{key}` | {row['a_max_m_per_s2']:.1f} | {row['a_p99_m_per_s2']:.1f} | "
            f"{row['a_median_shell_m_per_s2']:.1f} | "
            f"{row['rho_min_over_rho0']:.3f} | {row['p_max_Pa']:.0f} | "
            f"{row['a_max_over_physical']:.0f}x |")
    add("")
    add(f"The CSF contribution to the very first step is "
        f"{acc['csf_excess_a_max_m_per_s2']:.0f} m/s^2 "
        f"(**{acc['csf_excess_over_physical']:.0f}x** the wave's own restoring "
        f"acceleration of {acc['a_physical_omega2A_m_per_s2']:.1f} m/s^2). "
        "The acceleration with surface tension off is not zero either: the "
        "uncalibrated lattice kernel-sum bias builds "
        f"{acc['csf_off']['p_max_Pa']:.0f} Pa of spurious pressure, which the Tait "
        "clamp releases at the free surface; mass calibration removes it, but the "
        "CSF term is then still the dominant acceleration in the problem.")
    add("")
    add("### 3.3 Where the CSF force comes from: curvature noise on a flat surface")
    add("")
    add("For the perturbation, the analytic interface curvature is `k^2 A = "
        f"{curv['analytic_signal_kappa_1_per_m']:.1f} 1/m`. The discrete curvature "
        "of the *same* interface, measured on the particles that carry the surface "
        "delta function, is:")
    add("")
    add("| lattice | `h/dx` | curvature operator | interface particles | "
        "`kappa_rms` [1/m] | `|kappa|` p95 | `|kappa|` max | noise / signal |")
    add("|---|---|---|---|---|---|---|---|")
    for cell in curv["cells"]:
        add(f"| {cell['lattice']} | {cell['h_factor']} | `{cell['curvature_scheme']}` | "
            f"{cell['n_interface_particles']} | {cell['kappa_rms_1_per_m']:.1f} | "
            f"{cell['kappa_abs_p95_1_per_m']:.1f} | "
            f"{cell['kappa_abs_max_1_per_m']:.1f} | "
            f"{cell['noise_over_signal']:.1f}x |")
    add("")
    add(f"The curvature noise is {summ['min_noise_over_signal']:.1f}x to "
        f"{summ['max_noise_over_signal']:.1f}x the physical signal on every lattice "
        "and both operators; the force per unit volume scales with "
        "`sigma kappa delta_s`, which is what section 3.2 measures directly.")
    add("")
    add("### 3.4 No knob rescues it")
    add("")
    add("| variant | status | `max|v| / u_ref` | `rho_min/rho0` | omega error [%] | "
        "fit residual | admissible (Adami) |")
    add("|---|---|---|---|---|---|---|")
    for row in sweep:
        add(f"| `{row['variant']}` | {_status(row)} | {row['v_max_over_u_ref']:.1f} | "
            f"{row['rho_min_over_rho0']:.3f} | "
            f"{_fmt(row.get('omega_rel_error_pct'), '+.1f')} | "
            f"{_fmt(row.get('fit_residual_rel'), '.2f')} | "
            f"{'yes' if row['admissible_adami'] else '**no**'} |")
    add("")
    add(f"{summ['n_aborted']} of {summ['n_variants']} variants abort before the "
        f"horizon; {summ['n_admissible']} run is admissible under the Adami limit. "
        "Note that `rho_min/rho0` and the abort step move in opposite directions for "
        "the closure variants: they raise the shell density but inject more momentum "
        "at the surface, which is the same trade-off measured on the "
        "Young-Laplace ladder.")
    add("")
    add("### 3.5 A larger amplitude does not help either")
    add("")
    add("| variant | status | imposed `A` [mm] | measured `a(0)` | omega error [%] | "
        "fit residual | `max|v| / u_ref` |")
    add("|---|---|---|---|---|---|---|")
    for row in ladder:
        add(f"| `{row['variant']}` | {_status(row)} | "
            f"{(row.get('amplitude_imposed_m') or 0.0)*1e3:.2f} | "
            f"{_fmt(row.get('amplitude_initial_measured_m') and row['amplitude_initial_measured_m']*1e3, '+.2f')} mm | "
            f"{_fmt(row.get('omega_rel_error_pct'), '+.1f')} | "
            f"{_fmt(row.get('fit_residual_rel'), '.2f')} | "
            f"{row['v_max_over_u_ref']:.1f} |")
    add("")
    add("A larger amplitude raises the physical signal, but the fit residual stays "
        "high and the extracted frequency does not follow the analytic one: the "
        "measured mode is dominated by the surface transient, not by the wave.")
    add("")
    add("## 4. Figures")
    add("")
    add(f"![open free-surface audit](figures/{FIGURE_NAME})")
    add("")
    add(f"*Figure provenance:* `docs/figures/{FIGURE_NAME}`, sha256 "
        f"`{_figure_sha256()}`, drawn by `make_doc.render_figure` from "
        "`benchmarks/capillary_wave/open_surface_audit.json` alone -- no "
        "simulator is re-run to make the picture, so the page and the figure are "
        "two renderings of one artifact and the gate compares both.")
    add("")
    add("*(a)* the measured mode amplitude in the two runs that complete: it decays "
        "and drifts instead of oscillating at the analytic period; *(b)* maximum "
        "speed per variant against the physical velocity scale; *(c)* discrete "
        "curvature noise of the open free surface against the perturbation's own "
        "`k^2 A`; *(d)* acceleration at `t = 0` with surface tension off and on.")
    add("")
    add("## 5. Notes and limitations")
    add("")
    add("1. **Scope.** The audit covers the standing-wave geometry the harness uses. "
        "It says nothing about closed interfaces: the Young-Laplace work on a drop "
        "reaches -34 % with a 0.03 spurious current and the two-phase control is "
        "inside 5 %, so the failure here is specific to a *one-sided, open* support.")
    add("2. **Not a defect of the measuring chain.** The abort is a guard: when a "
        "particle leaves the box the case is no longer a free-surface standing wave. "
        "The guard was kept, not weakened, and the audit records the abort instead of "
        "grading the run.")
    add("3. **The amplitude estimator is not the blocker.** `column_elevation` "
        "quantises the surface into horizontal bins of one particle spacing; at "
        "`A = 0.5 dx` that is comparable to the signal, which is why section 3.5 "
        "repeats the case at `A = 2 dx`. Even there the fit residual stays high, so "
        "the limitation is in the force, not in the estimator.")
    add("4. **What would change the verdict.** A curvature operator or colour field "
        "that is smooth at the particle scale on a one-sided support (the "
        "`curvature_color_smoothing` option of `csf_fields`, interface smoothing, or "
        "a delta-function renormalisation) has to bring the section 3.3 noise ratio "
        "below one *before* the wave can be graded; the tests below pin the current "
        "numbers so the fix cannot pass unnoticed.")
    add("")
    add("## 6. Error verdict")
    add("")
    add("| key quantity | reference | measured | error | below 3 % ? |")
    add("|---|---|---|---|---|")
    add("| capillary frequency `omega` | Lamb (1932) "
        f"{acc['omega_rad_per_s']:.1f} rad/s | no admissible reading | not measured "
        "(spurious current "
        f"{min(r['v_max_over_u_ref'] for r in sweep):.1f}x to "
        f"{max(r['v_max_over_u_ref'] for r in sweep):.1f}x `u_ref`, Adami limit 0.1) | "
        "**no -- WITHHELD** |")
    add("| viscous damping `gamma = 2 nu k^2` | Lamb (1932) | no admissible reading "
        "| not measured | **no -- WITHHELD** |")
    add(f"| curvature of the flat interface | 0 1/m | "
        f"{curv['cells'][0]['kappa_signed_mean_1_per_m']:+.1f} 1/m (signed mean, "
        f"`{curv['cells'][0]['lattice']}`, `h/dx={curv['cells'][0]['h_factor']}`) | "
        f"`kappa_rms` {curv['cells'][0]['kappa_rms_1_per_m']:.1f} 1/m vs signal "
        f"{curv['analytic_signal_kappa_1_per_m']:.1f} 1/m | **no** |")
    add("")
    add("**Explicit answer to the platform question.** The capillary-wave dispersion "
        "and damping claims are **not** within 3 % of Lamb (1932) -- they are not "
        "measurable at all at HEAD, because the run that would produce them is "
        "inadmissible (spurious current above the Adami limit in every variant, and "
        "an abort in the harness itself). The capability stays graded WITHHELD, now "
        "with a committed root cause and a committed noise floor instead of an "
        "unregistered directory.")
    add("")
    add("## 7. Reproduction")
    add("")
    add("```bash")
    add("PYTHONPATH=src python benchmarks/capillary_wave/open_surface_audit.py  "
        "# ~3 min")
    add("PYTHONPATH=src python benchmarks/capillary_wave/make_doc.py --figures")
    add("PYTHONPATH=src python -m pytest tests/test_capillary_wave_open_surface.py -q")
    add("```")
    add("")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# figure: a pure function of the committed JSON
# --------------------------------------------------------------------------- #
def render_figure(payload: dict, path: Path = None):  # noqa: C901
    """Draw the four audit panels from ``payload`` alone and write ``path``.

    No simulator is touched: every quantity plotted is a field of the committed
    ``open_surface_audit.json``, so the figure is a *fresh rendering of the
    artifact* in exactly the sense the page already is.  That is what lets the
    test regenerate it instead of trusting a binary blob.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np

    path = Path(path) if path is not None else FIGURE_DIR / FIGURE_NAME
    path.parent.mkdir(parents=True, exist_ok=True)

    done = [r for r in payload["amplitude_ladder"] if r["status"] == "completed"]
    sweep = payload["variant_sweep"]
    omega = payload["initial_acceleration"]["omega_rad_per_s"]
    period_ms = 2.0 * math.pi / omega * 1e3

    fig, axes = plt.subplots(2, 2, figsize=(13.0, 8.6))

    ax = axes[0][0]
    for row in done:
        t = np.asarray(row["t_history"])
        a = np.asarray(row["amplitude_history_m"])
        ax.plot(t * 1e3, a * 1e3, ".", ms=3,
                label=f"{row['variant']} (resid {row['fit_residual_rel']:.2f})")
    ax.axvline(period_ms, color="k", ls=":", lw=1,
               label=f"one analytic period ({period_ms:.1f} ms)")
    ax.set_xlabel("t [ms]")
    ax.set_ylabel(r"mode amplitude $a(t)$ [mm]")
    ax.set_title("(a) the measured mode decays, it does not oscillate")
    ax.legend(fontsize=6)
    ax.grid(alpha=0.3)

    ax = axes[0][1]
    for row in sweep:
        hist = row["v_max_history"]
        if not hist:
            continue
        ax.semilogy(np.arange(len(hist)) * payload["horizon_periods"]
                    / max(1, len(hist) - 1), hist, "-o", ms=2.5,
                    label=row["variant"])
    ax.axhline(payload["admissibility"]["limit"] * 1.0, color="k", ls="--", lw=1,
               label="physical $u_{ref}=A\\omega$ (limit is 0.1x this)")
    ax.set_xlabel("t [capillary periods]")
    ax.set_ylabel(r"$\max_i |v_i|$ [m/s]")
    ax.set_title("(b) spurious current grows in every variant")
    ax.legend(fontsize=5.5)
    ax.grid(alpha=0.3, which="both")

    ax = axes[1][0]
    cells = payload["curvature"]["cells"]
    names = [f"{c['lattice']}\nh={c['h_factor']}\n{c['curvature_scheme'][:8]}"
             for c in cells]
    ax.bar(range(len(cells)), [c["kappa_rms_1_per_m"] for c in cells],
           color="#4477aa")
    ax.axhline(payload["curvature"]["analytic_signal_kappa_1_per_m"], color="k",
               ls="--", lw=1.2, label=r"perturbation's own $k^2A$")
    ax.set_xticks(range(len(cells)))
    ax.set_xticklabels(names, fontsize=5)
    ax.set_ylabel(r"$\kappa_{rms}$ on the interface [1/m]")
    ax.set_title("(c) discrete curvature noise of an open free surface")
    ax.legend(fontsize=7)
    ax.grid(alpha=0.3, axis="y")

    ax = axes[1][1]
    keys = ["csf_off", "csf_on_mass_calibrated", "csf_on",
            "csf_on_density_renormalization"]
    ax.bar(range(len(keys)),
           [payload["initial_acceleration"][k]["a_max_m_per_s2"] for k in keys],
           color="#ee6677")
    ax.axhline(payload["initial_acceleration"]["a_physical_omega2A_m_per_s2"],
               color="k", ls="--", lw=1.2, label=r"physical $\omega^2A$")
    ax.set_yscale("log")
    ax.set_xticks(range(len(keys)))
    ax.set_xticklabels([k.replace("_", "\n") for k in keys], fontsize=6)
    ax.set_ylabel(r"$\max_i |a_i|$ at $t=0$ [m/s$^2$]")
    ax.set_title("(d) CSF contribution at the very first step")
    ax.legend(fontsize=7)
    ax.grid(alpha=0.3, axis="y")

    fig.tight_layout()
    fig.savefig(path, dpi=140, metadata={"Software": None})
    plt.close(fig)
    return path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the committed page is stale")
    ap.add_argument("--figures", action="store_true",
                    help=f"also re-render {FIGURE_DIR.name}/{FIGURE_NAME} "
                         "from the committed JSON")
    args = ap.parse_args()
    payload = json.loads((HERE / "open_surface_audit.json").read_text())
    text = render(payload)
    if args.check:
        current = DOC.read_text() if DOC.is_file() else ""
        if current != text:
            print(f"{DOC} is stale -- run make_doc.py")
            return 1
        fig = FIGURE_DIR / FIGURE_NAME
        if not fig.is_file():
            print(f"{fig} is missing -- run make_doc.py --figures")
            return 1
        print(f"{DOC} is up to date")
        return 0
    DOC.write_text(text)
    print(f"wrote {DOC} ({len(text.splitlines())} lines)")
    if args.figures:
        path = render_figure(payload, FIGURE_DIR / FIGURE_NAME)
        print(f"wrote {path} ({path.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
