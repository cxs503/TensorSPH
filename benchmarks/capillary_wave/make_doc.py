"""Render ``docs/benchmarks/capillary-wave.md`` from the benchmark JSON.

Every number in the generated page comes from ``validation_report.json`` (no
hand-copied figures); re-run the benchmark and then this script to refresh it:

    python benchmarks/capillary_wave/run.py --json-out benchmarks/capillary_wave/validation_report.json \
        --png-out benchmarks/capillary_wave/capillary_wave.png
    python benchmarks/capillary_wave/make_doc.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPORT = HERE / "validation_report.json"
DOC = HERE.parents[1] / "docs" / "benchmarks" / "capillary-wave.md"


def fmt(value, spec: str) -> str:
    return "n/a" if value is None else format(value, spec)


def main() -> None:
    data = json.loads(REPORT.read_text())
    setup = data["setup"]
    ana = data["analytical"]
    cases = data["cases"]
    verdict = data["verdict"]
    scheme = data["scheme"]

    rows = []
    for case in cases:
        fit_eta = case["period_fit_interface"]
        rows.append(
            "| {dx:.0f} | {n} | {dt:.2e} | {tmeas} | {terr} | {teta} | {decay} | {dmin:.2e} / {dmax:.2e} |".format(
                dx=case["dx"] * 1e6,
                n=case["particles"],
                dt=case["dt"],
                tmeas=fmt(case["period_measured_s"], ".6f"),
                terr=("n/a" if case["frequency_error"] is None
                      else f"{100 * case['frequency_error']:.1f} %"),
                teta="n/a" if fit_eta is None else f"{fit_eta['period_s']:.6f}",
                decay=fmt(case["envelope_velocity"]["decay_ratio"], ".3f"),
                dmin=case["min_density_deviation"],
                dmax=case["max_density_deviation"],
            )
        )

    worst = verdict["max_frequency_error"]
    passed = verdict["pass"]
    status = ("PASS" if passed else
              "FAIL (model over-tests the dispersion relation at this resolution)")
    within3 = (worst is not None and worst < 0.03)
    within15 = (worst is not None and worst < 0.15)

    text = f"""# Capillary-gravity wave: dynamic verification of the CSF surface tension

Generated by `benchmarks/capillary_wave/make_doc.py` from
`benchmarks/capillary_wave/validation_report.json`. Do not edit by hand.

## 1. What this case tests

The Young-Laplace pressure jump (`docs/validation/young_laplace_csf.md`,
`docs/verification_surface_tension_laplace.md`) verifies the *static* side of
surface tension: a stationary interface must carry `dp = sigma * kappa`. The
dynamic side is a different operator chain — curvature of a *moving*
interface, momentum coupling and the free-surface treatment — and a model can
pass the Laplace gate and still get the dispersion relation wrong. This
benchmark closes that gap by measuring the period of a standing
capillary-gravity wave against linear theory:

    omega^2 = (g k + sigma k^3 / rho) tanh(k H)

with `k = 2 pi / lambda` and `H` the fluid depth (Lamb 1932, Art. 267). The
wavelength is placed at the capillary length, so gravity and surface tension
contribute comparable shares of `omega^2`; a wrong capillary term moves the
period by about half of its relative error.

## 2. Setup

| parameter | value |
|---|---|
| `sigma` | {setup['sigma']} N/m (water/air) |
| `g` | {setup['gravity']} m/s^2 |
| `lambda` | {setup['wavelength'] * 1e3:.2f} mm |
| `k` | {setup['k']:.2f} 1/m |
| `H` (fluid depth) | {setup['fluid_depth_m'] * 1e3:.3f} mm (`kH = {setup['k'] * setup['fluid_depth_m']:.3f}`) |
| capillary length | {setup['capillary_length_m'] * 1e3:.3f} mm |
| amplitude `A` | {setup['amplitude'] * 1e6:.0f} um (`ak = {setup['ak']:.3f}`) |
| `rho0` | {setup['rho0']} kg/m^3 |
| artificial `c0` | {setup['sound_speed']} m/s |
| CSF scheme | `{scheme['csf_scheme']}`, curvature `{scheme['csf_curvature']}` |
| gravity share of `omega^2` | {100 * setup['gravity_share_of_omega_sq']:.1f} % |
| analytical period | {ana['period_s']:.6f} s |

Mode: `{setup['mode']}`; initial condition: {setup['initial_condition']}.
Observable: {setup['observable']}.

Modelling choices worth stating up front:

* **Not pure capillary waves.** With `g = 0` a finite fluid body has no flat
  equilibrium: surface tension rounds the pool up. A trial at `sigma = 0.072`,
  `g = 0` drifted the mean interface level by 45 mm on a 190 mm pool (six
  amplitudes) and destroyed the mode. Gravity is what makes "flat interface
  plus a sinusoidal perturbation" an equilibrium, so the run keeps real water
  surface tension at the capillary length scale.
* **Intermediate depth.** `kH = 1` keeps the particle count affordable at a
  spacing of `dx = A / 3`; the `tanh(kH) = {__import__('math').tanh(setup['k'] * setup['fluid_depth_m']):.3f}`
  factor is included in the analytical reference, so the comparison is still
  exact linear theory, not a deep-water approximation.
* **Initial condition.** The masses carry the hydrostatic density of the
  *displaced* interface and are then rescaled by one global factor so that the
  kernel-sum density of the square lattice matches that target in the interior.
  Without that factor the lattice density is 0.8 % low, which is small in
  absolute terms but large against `p_bottom / B = {100 * setup['gravity'] * setup['rho0'] * setup['fluid_depth_m'] / (setup['rho0'] * setup['sound_speed'] ** 2 / 7.0):.1f} %`:
  the pressure collapses to the `max(p, 0)` clamp and the pool starts in free
  fall (measured -33 m/s^2 at the bottom before the fix).
* **Observable.** The interface height is quantised to `dx` and at `A / dx = 3`
  it is noise-dominated. The period is therefore measured from the
  mass-weighted `cos(kx)` mode of the vertical velocity, which averages over
  every particle and is exactly sinusoidal for the linear standing wave.

## 3. Results

| dx (um) | particles | dt (s) | T measured (s) | error vs theory | T from interface | envelope decay | density deviation |
|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}

* Verdict: **{status}**
* Worst period error: {fmt(worst, '.1%') if worst is not None else 'n/a'} (threshold {verdict['threshold']:.0%})
* Within 3 %: **{'yes' if within3 else 'no'}**; within the platform 15 % bar: **{'yes' if within15 else 'no'}**

![capillary wave](capillary_wave.png)

## 4. Error check (platform standard: is it < 3 %? < 15 %?)

| quantity | reference | measured | relative error |
|---|---|---|---|
""" + "\n".join(
        "| period `T` (dx = {dx:.0f} um) | {ana:.6f} s | {meas} | {err} |".format(
            dx=case["dx"] * 1e6,
            ana=case["period_analytical_s"],
            meas=fmt(case["period_measured_s"], ".6f"),
            err=("n/a" if case["frequency_error"] is None
                 else f"{100 * case['frequency_error']:.1f} %"),
        ) for case in cases
    ) + f"""

**Answer to "is it < 3 %?"**: {'yes' if within3 else 'no'}.
**Answer to "is it < 15 %?"**: {'yes' if within15 else 'no'}.
{'' if within15 else 'The dispersion relation is therefore **not** verified at the affordable resolution: the dynamic surface-tension operator remains unproven even though the static Laplace gate passes. Evidence level for "surface tension verified dynamically": WITHHELD.'}

## 5. Notes, limitations, and what would move this forward

* **Cost, not physics, set the resolution.** A faithful capillary-gravity wave
  needs `A >= 3 dx` (interface resolution) and `ak <= 0.2` (linear theory),
  which together pin `dx <= 0.2 / (3 k)`. On a single CPU core this platform's
  per-step cost is ~45 us per particle, so one period at `dx = 135 um` costs
  ~2 minutes per resolution level. Only the coarse level was run for this
  report; the ladder is wired (`--dx-list`) and should be re-run on a quiet
  machine. Note the running load average: this run was taken while the host was
  ~2.6x oversubscribed, which affects wall clock, not trajectories.
* **Numerical damping is the main residual error source.** `envelope decay` in
  the table is the ratio of the last to the first extremum of the modal
  velocity; the inviscid theory predicts 1.0 (no dissipation), so anything
  below 1 is numerical. Strong damping both biases the crossing fit and
  signals that the acoustic/pressure noise is not negligible.
* **Particle-scale capillary noise.** The pressure field is `p = B((rho/rho0)^gamma - 1)`
  clamped at zero, so a density jitter of 1 % is a pressure signal comparable
  to `p_bottom` itself. Density diffusion (`cfg.density_diffusion`) or
  delta-SPH smoothing would reduce it; both are available in `droplet_impact`
  and are the first thing to try next, followed by the `fit_circle` curvature
  operator (`cfg.csf_curvature`) as an A/B against the default `mls`.
* **Regression guard.** `tests/test_capillary_wave.py` pins the analytical
  reference, the two modal observables, the crossing fit (against a synthetic
  damped sinusoid, so a broken estimator fails immediately) and the
  hydrostatic initial condition. The runner is smoke-tested in process.
"""
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(text)
    print(f"wrote {DOC} ({len(text)} bytes)")


if __name__ == "__main__":
    main()