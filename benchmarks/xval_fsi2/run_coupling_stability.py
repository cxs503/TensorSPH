"""Controlled experiment: can the loosely-coupled explicit FSI2 driver run FSI2?

Decision
--------
Whether the shipped coupled Turek-Hron driver (one fluid solve + one explicit
rod step per time step) can be used to produce the benchmark numbers, or whether
the ledger anchor ``XVAL-SPH-FSI2-BENCHMARK-AND-FORCE-FROM-FLUID`` needs an
implicit / added-mass-aware coupling first.

Competing alternatives (all on the same particle set, same dx, same dt, same
cubic-spline kernel, same inlet)
-----------------------------------------------------------------------------
* ``loose``       -- force from fluid -> explicit rod step, no modification.
* ``impedance``   -- acoustic (Riemann star-state) wall pressure in the load
                     transfer, ``p* = p_f + rho0 c0 (v_wall - v_f).n``.
* ``relaxed``     -- under-relaxation of the nodal load, alpha = 0.05.

Manipulated variable
--------------------
The solid/fluid density ratio.  Turek-Hron FSI2 is posed at
``rho_s/rho_f = 1``; the SPHinXsys regression point is at 10.  The ratio is the
parameter that controls added mass, so it is the control knob.

Outcome metric (predeclared)
----------------------------
``sigma = ln(|v_beam|max(t_end) / |v_beam|max(t_20)) / (t_end - t_20)`` [1/s],
the exponential growth rate of the beam speed.  A run that is merely responding
to the drag load has ``sigma -> 0`` once the load saturates (the drag
acceleration scale is ``F/m = 6.4 N/m / 7 kg ~ 0.9 m/s2``, i.e. ~0.03 m/s after
0.035 s).  A loosely coupled scheme hit by added-mass instability has
``sigma > 0`` and grows without bound.  Thresholds, fixed before the runs:

* ``sigma > 0`` **and** ``max|v_beam| > 10 x 0.03 m/s``  -> divergent (FAIL),
* otherwise -> stable.

Stopping rule: a run is abandoned as soon as a non-finite value appears.
Resources: dx = 20 mm coarse probe (fast), one dx = 12.5 mm confirmation of the
ratio-1 verdict, all local, < 8 cores.

Provenance
----------
Every row carries the configuration it was measured under, and the payload
records the case switches that change the physics between rounds:

* ``open_boundaries`` -- the through-flow treatment (D4).  Off, the channel is a
  closed tank and the beam sees a different flow entirely.
* ``rod_substeps`` -- the *effective* rod sub-step count.  The criterion was
  fixed in m20761 (bending-aware); before that, ratio 1 diverged because the
  shortest bending mode was unresolvable, not because of added mass.  A record
  without this number cannot be compared with an older one.
* ``wall_impedance`` / ``coupling_relaxation`` -- the two arms of ``variant``.

The payload is regenerated by rerunning this file; the markdown table it produces
is written between the ``BEGIN GENERATED`` / ``END GENERATED`` markers of the
defect ledger, so the documentation never carries a hand-copied number.
"""
from __future__ import annotations

import argparse
import json
import math
import os

from tensorsph.fsi2_similarity import similarity_corrected_case
from tensorsph.fsi2_turek_hron import initial_state, step_fsi2

DRAG_ACCEL_SCALE = 0.03  # m/s after 0.035 s, see module docstring
DIVERGENCE_LIMIT = 10.0 * DRAG_ACCEL_SCALE  # m/s, predeclared

BEGIN = "<!-- BEGIN GENERATED: coupling_stability -->"
END = "<!-- END GENERATED: coupling_stability -->"


def _case_for(dx, ratio, variant, u_mean, c0):
    case = similarity_corrected_case(U_mean=u_mean)
    case.dx = dx
    case.sound_speed = c0
    case.beam_rho = 1000.0 * ratio
    if variant == "impedance":
        case.wall_impedance = True
    elif variant == "relaxed":
        case.wall_impedance = False
        case.coupling_relaxation = 0.05
    elif variant == "loose":
        case.wall_impedance = False
    else:
        raise ValueError(f"unknown variant {variant!r}")
    return case


def run_case(dx, ratio, variant, nst, u_mean=0.2, c0=5.0, stores_series=False,
             open_boundaries=True):
    case = _case_for(dx, ratio, variant, u_mean, c0)
    case.open_boundaries = bool(open_boundaries)
    state = initial_state(case)
    dt = case.dt()
    n_particles_0 = int(state.fluid_pos.shape[0])
    v20 = None
    v_end = 0.0
    series = []
    finite = True
    for k in range(nst):
        row = step_fsi2(state, case, dt)
        v = float(state.beam_vel.norm(dim=1).max())
        if stores_series:
            series.append((row["t"], v, row["tip_y"]))
        if not math.isfinite(v) or not math.isfinite(row["max_speed"]):
            finite = False
            break
        if k == 20:
            v20 = v
        v_end = v
    sigma = float("inf")
    if finite and v20 and v20 > 0.0 and v_end > 0.0:
        sigma = math.log(v_end / v20) / ((nst - 20) * dt)
    divergent = (not finite) or (sigma > 0.0 and v_end > DIVERGENCE_LIMIT)
    return {
        "dx": dx, "ratio": ratio, "variant": variant, "n_steps": nst, "dt": dt,
        "open_boundaries": bool(open_boundaries),
        "wall_impedance": bool(case.wall_impedance),
        "coupling_relaxation": float(case.coupling_relaxation),
        "rod_substeps": int(case.rod_substeps_effective()),
        "n_particles_0": n_particles_0,
        "n_particles_end": int(state.fluid_pos.shape[0]),
        "steps_completed": len(series) if stores_series else nst,
        "v_at_step20": v20, "v_end": v_end, "sigma_per_s": sigma,
        "finite": finite,
        "verdict": "divergent" if divergent else "stable",
        "series": series,
    }


def table_markdown(payload) -> str:
    """Render the measured matrix as a markdown table (generated, not typed)."""
    lines = [
        "| variant | rho_s/rho_f | sigma [1/s] | |v_beam|max, step 20 [m/s] "
        "| |v_beam|max, end [m/s] | verdict |",
        "|---|---|---|---|---|---|",
    ]
    for r in payload["rows"]:
        v20 = "n/a" if r["v_at_step20"] is None else f"{r['v_at_step20']:.2e}"
        lines.append(
            f"| {r['variant']} | {r['ratio']:g} | {r['sigma_per_s']:+.1f} | {v20} "
            f"| {r['v_end']:.2e} | {r['verdict'].upper()} |")
    ctrl = payload.get("controls", [])
    for r in ctrl:
        v20 = "n/a" if r["v_at_step20"] is None else f"{r['v_at_step20']:.2e}"
        lines.append(
            f"| {r['variant']} (open_boundaries=False) | {r['ratio']:g} "
            f"| {r['sigma_per_s']:+.1f} | {v20} | {r['v_end']:.2e} "
            f"| {r['verdict'].upper()} |")
    conf = payload.get("resolution_check")
    if conf:
        lines.append(
            f"| {conf['variant']} (dx={conf['dx']:g} m confirmation) | "
            f"{conf['ratio']:g} | {conf['sigma_per_s']:+.1f} | n/a "
            f"| {conf['v_end']:.2e} | {conf['verdict'].upper()} |")
    lines += ["", "Findings (derived from the rows above):"]
    for ratio in sorted({r["ratio"] for r in payload["rows"]}):
        arm = [r for r in payload["rows"] if r["ratio"] == ratio]
        bad = [r["variant"] for r in arm if r["verdict"] == "divergent"]
        head = ", ".join(f"{r['variant']} {r['v_end']:.2e} m/s" for r in arm)
        lines.append(
            f"* `rho_s/rho_f = {ratio:g}`: "
            + ("**DIVERGENT** in " + ", ".join(bad) if bad else "stable in every variant")
            + f" (end speeds: {head}).")
    prov = payload["provenance"]
    lines += [
        "",
        f"Generated by `benchmarks/xval_fsi2/run_coupling_stability.py` at "
        f"{prov['n_steps']} steps, dt = {prov['dt']:.3e} s "
        f"({prov['t_end']:.3f} s of physical time), dx = {prov['dx']:g} m, "
        f"c0 = {prov['sound_speed']:g} m/s, U_mean = {prov['u_mean']:g} m/s, "
        f"auto rod sub-steps = {prov['rod_substeps']}.  Divergence threshold "
        f"(predeclared): sigma > 0 and |v_beam|max > {prov['divergence_limit']:g} m/s.",
    ]
    return "\n".join(lines)


def write_figure(payload, path):
    """Beam-speed history of the divergent and the stable control (same variant).

    Reads the series out of the payload, so the figure cannot drift away from the
    JSON it is quoted next to.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    limit = payload["divergence_limit_m_per_s"]
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    for key, label, style in (("ratio_1", r"$\rho_s/\rho_f = 1$ (FSI2 point)", "-"),
                              ("ratio_10", r"$\rho_s/\rho_f = 10$ (SPHinXsys point)", "--")):
        series = payload["series"][key]
        t = [row[0] for row in series]
        v = [max(row[1], 1e-12) for row in series]
        ax.semilogy(t, v, style, label=label)
    ax.axhline(limit, color="0.4", lw=0.8, ls=":")
    ax.text(0.02, limit * 1.6, "predeclared divergence limit", fontsize=8, color="0.4")
    ax.axhline(DRAG_ACCEL_SCALE, color="0.6", lw=0.8, ls=":")
    ax.text(0.02, DRAG_ACCEL_SCALE * 1.6, "drag-load acceleration scale", fontsize=8,
            color="0.6")
    ax.set_xlabel("t [s]")
    ax.set_ylabel(r"$\max|v_{beam}|$ [m/s]")
    ax.set_title("Loosely coupled explicit FSI2: beam speed history")
    ax.grid(True, which="both", alpha=0.25)
    ax.legend(fontsize=8, loc="lower right")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    print("wrote", path)


def _write_markdown(path, block):
    with open(path) as fh:
        text = fh.read()
    if BEGIN not in text or END not in text:
        print(f"[skip] {path} has no generated-block markers")
        return
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    with open(path, "w") as fh:
        fh.write(f"{head}{BEGIN}\n{block}\n{END}{tail}")
    print("updated generated block in", path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/xval_fsi2/assets/coupling_stability.json")
    ap.add_argument("--md-doc", default="docs/xval_fsi2/COUPLED_RUN_DEFECTS.md")
    ap.add_argument("--dx", type=float, default=0.02)
    ap.add_argument("--nst", type=int, default=600)
    ap.add_argument("--fig", default="docs/xval_fsi2/assets/fig_added_mass_divergence.png")
    args = ap.parse_args()

    rows = []
    for variant in ("loose", "impedance", "relaxed"):
        for ratio in (1.0, 2.0, 5.0, 10.0):
            r = run_case(args.dx, ratio, variant, args.nst)
            rows.append(r)
            print(f"{variant:10s} ratio={ratio:5.1f} sigma={r['sigma_per_s']:+11.3e} "
                  f"v20={r['v_at_step20']:.3e} vend={r['v_end']:.3e} "
                  f"-> {r['verdict']}", flush=True)

    # dx-independence of the ratio-1 verdict (coarser probe could be a resolution artefact)
    confirm = run_case(0.0125, 1.0, "loose", 250)
    print(f"confirm dx=0.0125 ratio=1.0 sigma={confirm['sigma_per_s']:+11.3e} "
          f"vend={confirm['v_end']:.3e} -> {confirm['verdict']}", flush=True)

    # control: the same ratio-1 point with the through-flow switched off.  The
    # open boundary treatment changes the load history, so the verdict must be
    # shown not to hinge on it.
    control = run_case(args.dx, 1.0, "loose", args.nst, open_boundaries=False)
    print(f"control open_boundaries=False ratio=1.0 "
          f"sigma={control['sigma_per_s']:+11.3e} vend={control['v_end']:.3e} "
          f"-> {control['verdict']}", flush=True)

    # time series for the figure: the divergent and the stable control, same variant
    series = {
        "ratio_1": run_case(args.dx, 1.0, "loose", 120, stores_series=True)["series"],
        "ratio_10": run_case(args.dx, 10.0, "loose", args.nst, stores_series=True)["series"],
    }

    ref = rows[0]
    payload = {
        "decision": "does the loosely-coupled explicit FSI2 driver run the Turek-Hron "
                    "point (rho_s/rho_f = 1)?",
        "metric": "sigma = d ln|v_beam|max/dt [1/s]; divergent iff sigma > 0 and "
                  f"v_end > {DIVERGENCE_LIMIT:g} m/s",
        "drag_accel_scale_m_per_s": DRAG_ACCEL_SCALE,
        "divergence_limit_m_per_s": DIVERGENCE_LIMIT,
        "u_mean": 0.2, "sound_speed": 5.0,
        "provenance": {
            "dx": args.dx, "n_steps": args.nst, "dt": ref["dt"],
            "t_end": args.nst * ref["dt"],
            "u_mean": 0.2, "sound_speed": 5.0,
            "open_boundaries": True,
            "rod_substeps": ref["rod_substeps"],
            "divergence_limit": DIVERGENCE_LIMIT,
            "kernel": "cubic spline (di.cubic_spline_kernel)",
            "runner": "benchmarks/xval_fsi2/run_coupling_stability.py",
        },
        "rows": rows,
        "resolution_check": confirm,
        "controls": [control],
        "series": series,
    }
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as fh:
        json.dump(payload, fh, indent=2)
    print("wrote", args.out)

    if args.fig:
        os.makedirs(os.path.dirname(args.fig), exist_ok=True)
        write_figure(payload, args.fig)

    if args.md_doc:
        _write_markdown(args.md_doc, table_markdown(payload))


if __name__ == "__main__":
    main()
